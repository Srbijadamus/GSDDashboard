using Microsoft.EntityFrameworkCore;
using GSDDashboard.API.Data.Models;

namespace GSDDashboard.API.Data;

public class GSDContext : DbContext
{
    private readonly ILogger<GSDContext>? _log;
    private readonly HashSet<ShiftEntry> _manualEdits = [];

    // ShiftEntries ids the ROLLOUT feature is allowed to delete in this unit of work. See
    // AllowRolloutOwnedDelete.
    private readonly HashSet<int> _rolloutOwnedDeletes = [];

    // ShiftEntries rows whose TYPE change in this unit of work came from a MANUAL RTM entry
    // point (Shift Plan cell / Bulk RTM paste). Only these may clear a stale WIC centre name
    // from AgentTask. See RecordManualRtmShiftEdit.
    private readonly HashSet<ShiftEntry> _manualRtmTypeEdits = [];

    public GSDContext(DbContextOptions<GSDContext> options, ILogger<GSDContext>? log = null) : base(options) => _log = log;

    public bool PreserveManualShift(ShiftEntry? row, string operation)
    {
        if (row?.IsManualChange != true) return false;
        _log?.LogWarning("Manual shift preserved: operation={Operation}, id={Id}, employee={Employee}, date={Date}, actor={Actor}",
            operation, row.Id, row.EmployeeId, row.ShiftDate, row.ManualChangeBy);
        return true;
    }

    internal void RecordManualShiftEdit(ShiftEntry row, string actor)
    {
        if (string.IsNullOrWhiteSpace(actor) || actor.Length > 100)
            throw new ArgumentException("A session actor is required.", nameof(actor));
        _manualEdits.Add(row);
        row.ManualChangeBy = actor;
        row.ManualChangeAt = DateTime.UtcNow;
        row.AutoGenerated = false;
        // Preserve source/batch provenance and business links; the explicit marker is the authority.
        row.ManualChangeNote = "Manual shift cell edit (/shifts); automatic writers must preserve this row.";
    }

    /// <summary>
    /// Records a MANUAL RTM shift-type edit: the Shift Plan cell
    /// (<c>PATCH /api/shifts/{id}</c> / <c>PATCH /api/shifts/{id}/manual</c>) or the Bulk RTM
    /// paste (<c>POST /api/shifts/assign</c> / <c>/api/shifts/assign/manual</c>). It is the
    /// same manual marker as <see cref="RecordManualShiftEdit"/> AND the only declaration
    /// that lets this unit of work clear a stale WIC centre name from <c>AgentTask</c> when
    /// the edit took the row from <c>WIC_DUTY</c> to WORKING or BO.
    ///
    /// Every other writer — the roster generator, the sickness/vacation sync and their
    /// reverts, the future-vacation reconciliation, the rollout, a substitute accept, the
    /// WIC writers, startup reconciliation — keeps using the plain marker (or none) and
    /// therefore NEVER clears the centre name. That name is the trace of a TEMPORARY move
    /// (the agent is helping at another WIC centre, or is on BO/GSD) and the handle by which
    /// he returns to his home centre; automation must not erase it.
    /// </summary>
    internal void RecordManualRtmShiftEdit(ShiftEntry row, string actor)
    {
        RecordManualShiftEdit(row, actor);
        _manualRtmTypeEdits.Add(row);
    }

    /// <summary>
    /// Explicit, narrow escape hatch for removing a ShiftEntries row the ROLLOUT feature
    /// itself created. GuardManualShifts refuses to delete a manual row through
    /// SaveChanges — deliberately, because every other writer must not remove a human
    /// decision. A rollout day that is edited or deleted must remove exactly the rows
    /// that came from it (requirement: "a change or delete of a rollout day changes only
    /// what came from it"), so the rollout service registers those rows here first.
    ///
    /// It only ever accepts a row whose SourceModule is ROLLOUT, and the caller must pass
    /// the row it actually owns. Nothing else can delete a manual row.
    /// </summary>
    internal void AllowRolloutOwnedDelete(ShiftEntry row)
    {
        if (!string.Equals(row.SourceModule, RolloutSource.Module, StringComparison.Ordinal))
            throw new InvalidOperationException(
                $"ShiftEntry {row.Id} is not rollout-owned (SourceModule='{row.SourceModule}'); refusing to delete it.");
        _rolloutOwnedDeletes.Add(row.Id);
    }

    private void GuardManualShifts()
    {
        ChangeTracker.DetectChanges();
        foreach (var entry in ChangeTracker.Entries<ShiftEntry>())
        {
            if (entry.State is not (EntityState.Modified or EntityState.Deleted)) continue;
            var wasManual = !string.IsNullOrWhiteSpace(entry.OriginalValues.GetValue<string?>(
                nameof(ShiftEntry.ManualChangeBy)));
            if (!wasManual || (_manualEdits.Contains(entry.Entity) && entry.State != EntityState.Deleted)) continue;
            // Rollout-owned rows: only the explicit, SourceModule-checked registration above.
            if (entry.State == EntityState.Deleted &&
                string.Equals(entry.Entity.SourceModule, RolloutSource.Module, StringComparison.Ordinal) &&
                _rolloutOwnedDeletes.Contains(entry.Entity.Id)) continue;
            _log?.LogError("Blocked unapproved {State} of manual ShiftEntry {Id}", entry.State, entry.Entity.Id);
            throw new InvalidOperationException($"Manual shift {entry.Entity.Id} cannot be overwritten or deleted by this operation.");
        }
    }

    public override int SaveChanges(bool acceptAllChangesOnSuccess)
    {
        GuardManualShifts();
        LinkWicRowsToShiftTypeChanges();
        SyncWicRowsForPlanBackOffice();
        var result = base.SaveChanges(acceptAllChangesOnSuccess);
        _manualEdits.Clear();
        _rolloutOwnedDeletes.Clear();
        _manualRtmTypeEdits.Clear();
        return result;
    }

    public override async Task<int> SaveChangesAsync(bool acceptAllChangesOnSuccess, CancellationToken cancellationToken = default)
    {
        GuardManualShifts();
        LinkWicRowsToShiftTypeChanges();
        SyncWicRowsForPlanBackOffice();
        var result = await base.SaveChangesAsync(acceptAllChangesOnSuccess, cancellationToken);
        _manualEdits.Clear();
        _rolloutOwnedDeletes.Clear();
        _manualRtmTypeEdits.Clear();
        return result;
    }

    /// <summary>
    /// WIC OVER BO (owner rule, 2026-10-15): every AUTOMATIC back-office day
    /// (<c>RawValue="BO"</c>/<c>ShiftType="BO"</c> with no <c>ManualChangeBy</c>) whose agent
    /// holds an active WIC assignment gets its on-site <c>WicShiftEntries</c> row created or
    /// kept, with <c>WorkingShift = shift ∩ centre hours</c>. It runs in the SAME unit of work
    /// as the ShiftEntries change, for every writer — roster generator, imports, the
    /// generator's overwrite path — exactly like
    /// <see cref="LinkWicRowsToShiftTypeChanges"/> does for the opposite transition.
    ///
    /// A BO day RTM authored is excluded twice over: <c>ManualChangeBy</c> is set before the
    /// save by <see cref="RecordManualRtmShiftEdit"/>, so it is not a "plan" BO row, and
    /// <see cref="GuardManualShifts"/> already protects the row itself. Leave types
    /// (AL/SL/UL/OL/PH/LPH), HALF_AL, OFF/OFF_WEEKEND, TRAINING and RESIGNED are never BO
    /// days and never reach this code.
    /// </summary>
    private void SyncWicRowsForPlanBackOffice()
    {
        ChangeTracker.DetectChanges();
        var rows = ChangeTracker.Entries<ShiftEntry>()
            .Where(e => e.State is EntityState.Added or EntityState.Modified)
            .Select(e => e.Entity)
            .Where(Services.WicBackOfficePriority.IsPlanBackOffice)
            .ToList();
        if (rows.Count == 0) return;

        var changed = Services.WicBackOfficeSync.Apply(this, rows);
        if (changed > 0)
            _log?.LogInformation(
                "WIC>BO rule: created/updated {Count} on-site WicShiftEntries row(s) for automatic back-office day(s)",
                changed);
    }

    /// <summary>
    /// RTM 2026-10-15, requirement 3 — WIC ATTENDANCE FOLLOWS THE SHIFT PLAN.
    ///
    /// Every <c>ShiftEntries</c> row that stops being WIC duty in this unit of work (a) has its
    /// employee+date's ON-SITE <c>WicShiftEntries</c> rows stood down (<c>IsOnSite=false</c>)
    /// and (b) — ONLY when the change came from a MANUAL RTM edit that took the row to
    /// WORKING or BO — has a stale WIC-centre name cleared from <c>AgentTask</c>, both BEFORE
    /// anything is written. WIC Attendance, the coverage cards, /api/wic/open, the forecast,
    /// the conflicts detector and the HR export therefore all see the change in the same
    /// SaveChanges as the Shift Plan cell / Bulk RTM paste / import / generator that made it.
    ///
    /// Doing the stand-down here (rather than in each writer) is the point: the writers are
    /// many and independent, and the previous implementation only covered the hand Shift Plan
    /// cell. A writer that already stands the rows down itself is unaffected — the rule is
    /// idempotent.
    ///
    /// (b) exists because AgentTask is what every reader of the SECOND cover signal matches a
    /// centre against (AvailabilityResolver.IsWicDutyAt / WicPresenceResolver): a WORKING row
    /// whose AgentTask still names a centre is read as WIC duty with a flipped ShiftType. When
    /// RTM changes a WIC_DUTY cell to WORKING or BO, leaving the centre name behind made the
    /// agent keep appearing in the WIC cards after he had been taken off WIC duty (9129428,
    /// Pfaffenhofen, 2026-11-16). Clearing it on the manual transition removes the phantom
    /// cover at the source. Only a value that actually names a WIC centre is cleared; a task
    /// badge ("GSD", "Voice", ...) is the cell's own legitimate content and is left alone.
    ///
    /// (b) is deliberately restricted to the MANUAL RTM writers — <see cref="RecordManualRtmShiftEdit"/>:
    /// the Shift Plan cell and the Bulk RTM paste, and only for a transition to WORKING (a
    /// plain WORKING day or a BO day, which is WORKING + RawValue="BO"). Everything else keeps
    /// the name:
    ///   * an AUTOMATIC writer (roster generator, sickness/vacation sync and reverts, future
    ///     vacation reconciliation, rollout, substitute accept, WIC writers, startup) may take
    ///     the row off WIC_DUTY, but the centre name is the trace of a TEMPORARY move and the
    ///     agent's handle back to his home centre, so it is never erased by automation;
    ///   * a manual WIC_DUTY → AL/SL/OFF/... is a decision about the DAY, not about the centre,
    ///     so the name stays too;
    ///   * WIC_DUTY centre A → WIC_DUTY centre B (temporary help) is not a transition at all
    ///     (see <see cref="Services.WicAttendanceLink.LeavesWicDuty"/>), so nothing is cleared.
    ///
    /// Only a TRANSITION is acted on (was WIC_DUTY, is now something else). Creating a new
    /// non-WIC row for a day that never was WIC duty is not this rule's business, and a
    /// move INTO WIC_DUTY must keep the on-site rows the WIC writers create.
    /// See <see cref="Services.WicAttendanceLink"/> for the full rationale.
    /// </summary>
    private void LinkWicRowsToShiftTypeChanges()
    {
        ChangeTracker.DetectChanges();

        var keys = new HashSet<(string Employee, DateOnly Date)>();
        var leavers = new List<(ShiftEntry Row, string? Before)>();
        foreach (var entry in ChangeTracker.Entries<ShiftEntry>())
        {
            if (entry.State != EntityState.Modified) continue;
            var before = entry.OriginalValues.GetValue<string?>(nameof(ShiftEntry.ShiftType));
            if (!Services.WicAttendanceLink.LeavesWicDuty(before, entry.Entity.ShiftType)) continue;
            keys.Add((entry.Entity.EmployeeId, entry.Entity.ShiftDate));
            leavers.Add((entry.Entity, before));
        }
        if (keys.Count == 0) return;

        // (b) Clear a stale centre name BEFORE the stand-down query below: the clearing only
        // touches ShiftEntry.AgentTask and is committed by this SaveChanges with everything else.
        var manualClearing = leavers
            .Where(l => _manualRtmTypeEdits.Contains(l.Row))
            .Where(l => Services.WicAttendanceLink.ClearsCentreOnManualRtmTypeEdit(l.Before, l.Row.ShiftType))
            .ToList();
        if (manualClearing.Count > 0)
        {
            var activeCentres = WicLocations
                .Where(l => l.IsActive)
                .ToList();
            var cleared = 0;
            foreach (var (row, before) in manualClearing)
            {
                if (!Services.WicAttendanceLink.ClearsWicCentreAgentTask(row, activeCentres)) continue;
                _log?.LogInformation(
                    "WIC link: manual RTM {Before} -> {After} cleared stale centre name '{AgentTask}' " +
                    "from AgentTask on ShiftEntry {Id} (employee {Employee}, {Date})",
                    before, row.ShiftType, row.AgentTask, row.Id, row.EmployeeId, row.ShiftDate);
                row.AgentTask = null;
                cleared++;
            }
            if (cleared > 0)
                _log?.LogInformation(
                    "WIC link: cleared AgentTask on {Count} manual RTM row(s) that left WIC_DUTY", cleared);
        }

        var employees = keys.Select(k => k.Employee).Distinct().ToList();
        var dates     = keys.Select(k => k.Date).Distinct().ToList();

        // Queried (not ChangeTracker-scanned) so a writer that changed ShiftEntries without
        // ever loading the WIC rows — the common case — is still covered.
        var rows = WicShiftEntries
            .Where(w => w.IsOnSite && employees.Contains(w.EmployeeId) && dates.Contains(w.ShiftDate))
            .ToList();

        var changed = 0;
        foreach (var w in rows)
        {
            if (!keys.Contains((w.EmployeeId, w.ShiftDate))) continue;
            w.IsOnSite = false;
            changed++;
        }

        if (changed > 0)
            _log?.LogInformation(
                "WIC attendance link: stood down {Count} on-site WicShiftEntries row(s) for {Keys} shift-type change(s)",
                changed, keys.Count);
    }

