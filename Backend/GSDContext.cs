using Microsoft.EntityFrameworkCore;
using GSDDashboard.API.Data.Models;

namespace GSDDashboard.API.Data;

public class GSDContext : DbContext
{
    private readonly ILogger<GSDContext>? _log;
    private readonly HashSet<ShiftEntry> _manualEdits = [];

    // ShiftEntries ids the ROLLOUT feature is allowed to delete in this unit of work. See
    // AllowRolloutOwnedDelete.
    private readonly HashSet<int> _rolloutOwnedDeletes = [];

    public GSDContext(DbContextOptions<GSDContext> options, ILogger<GSDContext>? log = null) : base(options) => _log = log;

    public bool PreserveManualShift(ShiftEntry? row, string operation)
    {
        if (row?.IsManualChange != true) return false;
        _log?.LogWarning("Manual shift preserved: operation={Operation}, id={Id}, employee={Employee}, date={Date}, actor={Actor}",
            operation, row.Id, row.EmployeeId, row.ShiftDate, row.ManualChangeBy);
        return true;
    }

    internal void RecordManualShiftEdit(ShiftEntry row, string actor)
    {
        if (string.IsNullOrWhiteSpace(actor) || actor.Length > 100)
            throw new ArgumentException("A session actor is required.", nameof(actor));
        _manualEdits.Add(row);
        row.ManualChangeBy = actor;
        row.ManualChangeAt = DateTime.UtcNow;
        row.AutoGenerated = false;
        // Preserve source/batch provenance and business links; the explicit marker is the authority.
        row.ManualChangeNote = "Manual shift cell edit (/shifts); automatic writers must preserve this row.";
    }

    /// <summary>
    /// Explicit, narrow escape hatch for removing a ShiftEntries row the ROLLOUT feature
    /// itself created. GuardManualShifts refuses to delete a manual row through
    /// SaveChanges — deliberately, because every other writer must not remove a human
    /// decision. A rollout day that is edited or deleted must remove exactly the rows
    /// that came from it (requirement: "a change or delete of a rollout day changes only
    /// what came from it"), so the rollout service registers those rows here first.
    ///
    /// It only ever accepts a row whose SourceModule is ROLLOUT, and the caller must pass
    /// the row it actually owns. Nothing else can delete a manual row.
    /// </summary>
    internal void AllowRolloutOwnedDelete(ShiftEntry row)
    {
        if (!string.Equals(row.SourceModule, RolloutSource.Module, StringComparison.Ordinal))
            throw new InvalidOperationException(
                $"ShiftEntry {row.Id} is not rollout-owned (SourceModule='{row.SourceModule}'); refusing to delete it.");
        _rolloutOwnedDeletes.Add(row.Id);
    }

    private void GuardManualShifts()
    {
        ChangeTracker.DetectChanges();
        foreach (var entry in ChangeTracker.Entries<ShiftEntry>())
        {
            if (entry.State is not (EntityState.Modified or EntityState.Deleted)) continue;
            var wasManual = !string.IsNullOrWhiteSpace(entry.OriginalValues.GetValue<string?>(
                nameof(ShiftEntry.ManualChangeBy)));
            if (!wasManual || (_manualEdits.Contains(entry.Entity) && entry.State != EntityState.Deleted)) continue;
            // Rollout-owned rows: only the explicit, SourceModule-checked registration above.
            if (entry.State == EntityState.Deleted &&
                string.Equals(entry.Entity.SourceModule, RolloutSource.Module, StringComparison.Ordinal) &&
                _rolloutOwnedDeletes.Contains(entry.Entity.Id)) continue;
            _log?.LogError("Blocked unapproved {State} of manual ShiftEntry {Id}", entry.State, entry.Entity.Id);
            throw new InvalidOperationException($"Manual shift {entry.Entity.Id} cannot be overwritten or deleted by this operation.");
        }
    }

    public override int SaveChanges(bool acceptAllChangesOnSuccess)
    {
        GuardManualShifts();
        var result = base.SaveChanges(acceptAllChangesOnSuccess);
        _manualEdits.Clear();
        _rolloutOwnedDeletes.Clear();
        return result;
    }

    public override async Task<int> SaveChangesAsync(bool acceptAllChangesOnSuccess, CancellationToken cancellationToken = default)
    {
        GuardManualShifts();
        var result = await base.SaveChangesAsync(acceptAllChangesOnSuccess, cancellationToken);
        _manualEdits.Clear();
        _rolloutOwnedDeletes.Clear();
        return result;
    }

    public DbSet<Employee>           Employees           { get; set; }
    public DbSet<ShiftEntry>         ShiftEntries        { get; set; }
    public DbSet<WicShiftEntry>      WicShiftEntries     { get; set; }
    public DbSet<WicLocation>        WicLocations        { get; set; }
    public DbSet<DailyAttendance>    DailyAttendances    { get; set; }
    public DbSet<SickLeave>          SickLeaves          { get; set; }
    public DbSet<Vacation>           Vacations           { get; set; }
    public DbSet<ALBalance>          ALBalances          { get; set; }
    public DbSet<WicAgentAssignment> WicAgentAssignments { get; set; }
    public DbSet<WicOpeningHour>     WicOpeningHours     { get; set; }
    public DbSet<WicPipelineItem>    WicPipeline         { get; set; }
    public DbSet<PublicHoliday>      PublicHolidays      { get; set; }
    public DbSet<TrainingTopic>      TrainingTopics      { get; set; }
    public DbSet<TrainingSession>    TrainingSessions    { get; set; }
    public DbSet<LeaveQuota>         LeaveQuotas         { get; set; }
    public DbSet<SubstitutionHistory> SubstitutionHistory { get; set; } = null!;
    public DbSet<BreakSlot>           BreakSlots           { get; set; }
    public DbSet<VwicRotationSlot>    VwicRotationSlots    { get; set; }
    public DbSet<AgentReachableCity>  AgentReachableCities { get; set; }
    public DbSet<BoEntry>             BoEntries            { get; set; }
    public DbSet<RtmEntry>            RtmEntries           { get; set; }
    public DbSet<AppUserRole>         AppUserRoles         { get; set; }
    public DbSet<RosterBatch>         RosterBatches        { get; set; }
    public DbSet<WicRolloutDay>       WicRolloutDays       { get; set; }
    public DbSet<WicRolloutWorker>    WicRolloutWorkers    { get; set; }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<Employee>(e => {
            e.HasIndex(x => x.EmployeeId).IsUnique();
        });
        modelBuilder.Entity<ShiftEntry>(e => {
            // An automatic writer loaded before a human edit must fail, not clobber it.
            e.Property(x => x.ManualChangeBy).IsConcurrencyToken();
            e.Property(x => x.ManualChangeAt).IsConcurrencyToken();
            e.Property(x => x.ManualChangeNote).IsConcurrencyToken();
            e.HasIndex(x => x.ShiftDate).HasDatabaseName("IX_Shift_Date");
            e.HasIndex(x => x.EmployeeId).HasDatabaseName("IX_Shift_Emp");
            e.HasIndex(x => x.ShiftType).HasDatabaseName("IX_Shift_Type");
            e.HasIndex(x => new { x.EmployeeId, x.ShiftDate, x.SourceSheet })
             .IsUnique().HasDatabaseName("UQ_ShiftEntries_EmpDateSheet");
            e.HasIndex(x => new { x.EmployeeId, x.ShiftDate, x.ShiftType })
             .IsUnique().HasDatabaseName("UQ_ShiftEntries_EmpDateType");
        });
        modelBuilder.Entity<WicShiftEntry>(e => {
            e.HasIndex(x => x.ShiftDate).HasDatabaseName("IX_Wic_Date");
            e.HasIndex(x => x.EmployeeId).HasDatabaseName("IX_Wic_Emp");
            e.HasIndex(x => x.SupportLocation).HasDatabaseName("IX_Wic_Location");
            e.HasIndex(x => new { x.EmployeeId, x.ShiftDate, x.SupportLocation })
             .IsUnique().HasDatabaseName("UQ_WicShift_EmpDateLoc");
        });
        modelBuilder.Entity<WicLocation>(e => {
            e.HasIndex(x => x.LocationCode).IsUnique();
        });
        modelBuilder.Entity<DailyAttendance>(e => {
            e.HasIndex(x => x.AttendanceDate).HasDatabaseName("IX_Att_Date");
            e.HasIndex(x => x.LocationName).HasDatabaseName("IX_Att_Location");
            e.HasIndex(x => x.Country).HasDatabaseName("IX_Att_Country");
        });
        modelBuilder.Entity<SickLeave>(e => {
            e.HasIndex(x => x.EmployeeId).HasDatabaseName("IX_SL_Emp");
            e.HasIndex(x => new { x.FirstDay, x.LastDay }).HasDatabaseName("IX_SL_Dates");
            e.HasIndex(x => x.TeamLeadName).HasDatabaseName("IX_SL_TL");
            e.HasIndex(x => new { x.EmployeeId, x.FirstDay })
             .IsUnique().HasDatabaseName("UQ_SickLeaves_EmpFirstDay");
            e.HasIndex(x => x.EmployeeId)
             .HasFilter("[LastDay] = '2099-12-31'")
             .IsUnique()
             .HasDatabaseName("UQ_SickLeaves_EmployeeId_Sentinel");
        });
        modelBuilder.Entity<Vacation>(e => {
            e.HasIndex(x => x.EmployeeId).HasDatabaseName("IX_Vac_Emp");
            e.HasIndex(x => new { x.FirstDay, x.LastDay }).HasDatabaseName("IX_Vac_Dates");
            e.HasIndex(x => new { x.EmployeeId, x.FirstDay, x.LastDay })
             .IsUnique().HasDatabaseName("UQ_Vacations_EmpFirstLastDay");
        });
        modelBuilder.Entity<ALBalance>(e => {
            e.HasIndex(x => new { x.EmployeeId, x.Year })
             .IsUnique().HasDatabaseName("UQ_ALBalance_EmpYear");
        });
        modelBuilder.Entity<WicAgentAssignment>(e => {
            e.HasIndex(x => x.LocationCode).HasDatabaseName("IX_WicAssign_Location");
            e.HasIndex(x => x.EmployeeName).HasDatabaseName("IX_WicAssign_Employee");
        });
        modelBuilder.Entity<WicOpeningHour>(e => {
            e.HasIndex(x => x.LocationCode).HasDatabaseName("IX_WicHours_Location");
            e.HasIndex(x => x.DayOfWeek).HasDatabaseName("IX_WicHours_Day");
        });
        modelBuilder.Entity<WicPipelineItem>(e => {
            e.HasIndex(x => x.PipelineDate).HasDatabaseName("IX_Pipeline_Date");
            e.HasIndex(x => x.LocationCode).HasDatabaseName("IX_Pipeline_Location");
        });
        modelBuilder.Entity<LeaveQuota>(e => {
            e.HasIndex(x => x.QuotaDate).HasDatabaseName("IX_Quota_Date");
        });
        modelBuilder.Entity<SubstitutionHistory>(e => {
            e.HasIndex(x => x.EmployeeId).HasDatabaseName("IX_SubHist_Emp");
            e.HasIndex(x => x.Date).HasDatabaseName("IX_SubHist_Date");
        });
        modelBuilder.Entity<BreakSlot>(e => {
            e.Property(b => b.Status).HasConversion<string>();  // DB column is NVARCHAR(20)
            e.HasIndex(x => x.BreakDate).HasDatabaseName("IX_Break_Date");
            e.HasIndex(x => x.Status).HasDatabaseName("IX_Break_Status");
            e.HasIndex(x => new { x.EmployeeId, x.BreakDate }).HasDatabaseName("IX_Break_EmpDate");
        });
        modelBuilder.Entity<VwicRotationSlot>(e => {
            e.HasIndex(x => x.RotationDate).HasDatabaseName("IX_VwicRot_Date");
            e.HasIndex(x => new { x.EmployeeId, x.RotationDate }).HasDatabaseName("IX_VwicRot_EmpDate");
        });
        modelBuilder.Entity<BoEntry>(e => {
            e.HasIndex(x => x.EntryDate).HasDatabaseName("IX_Bo_Date");
        });
        modelBuilder.Entity<RtmEntry>(e => {
            e.HasIndex(x => x.EntryDate).HasDatabaseName("IX_Rtm_Date");
            e.HasIndex(x => x.EmployeeId).HasDatabaseName("IX_Rtm_Emp");
        });
        modelBuilder.Entity<RosterBatch>(e => {
            e.HasIndex(x => x.EmployeeId).HasDatabaseName("IX_RosterBatch_Emp");
            e.HasIndex(x => x.CreatedAt).HasDatabaseName("IX_RosterBatch_Created");
        });
        modelBuilder.Entity<AppUserRole>(e => {
            // A non-empty KID identifies exactly one login row; placeholder rows (Kid='')
            // may repeat and never authenticate (AuthService requires a non-empty Kid).
            e.HasIndex(x => x.Kid).IsUnique().HasFilter("[Kid] <> ''")
             .HasDatabaseName("UX_AppUserRoles_Kid");
        });
        modelBuilder.Entity<WicRolloutDay>(e => {
            // One rollout day per centre and date: a second one for the same pair would make
            // "the hours for that centre and date" ambiguous, and the WicOpeningHours
            // exception projection is keyed by (centre, date) too.
            e.HasIndex(x => new { x.LocationCode, x.RolloutDate })
             .IsUnique().HasDatabaseName("UQ_WicRolloutDays_LocDate");
            e.HasIndex(x => x.RolloutDate).HasDatabaseName("IX_WicRollout_Date");
            e.HasMany(x => x.Workers).WithOne(w => w.RolloutDay!)
             .HasForeignKey(w => w.RolloutDayId).OnDelete(DeleteBehavior.Cascade);
        });
        modelBuilder.Entity<WicRolloutWorker>(e => {
            e.HasIndex(x => new { x.RolloutDayId, x.EmployeeId })
             .IsUnique().HasDatabaseName("UQ_WicRolloutWorkers_DayEmp");
        });
        base.OnModelCreating(modelBuilder);
    }
}
