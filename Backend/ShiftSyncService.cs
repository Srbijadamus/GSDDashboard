using GSDDashboard.API.Data;
using GSDDashboard.API.Data.Models;
using Microsoft.EntityFrameworkCore;

namespace GSDDashboard.API.Services;

public class ShiftSyncService
{
    private readonly GSDContext _db;

    public ShiftSyncService(GSDContext db) => _db = db;

    public async Task SyncSickLeaveAsync(string employeeId, DateOnly dateFrom, DateOnly dateTo, int sourceId)
    {
        // Cap sync horizon so open-ended SL records (dateTo=2099-12-31) don't
        // flood ShiftEntries with decades of placeholder rows.
        var horizon = DateOnly.FromDateTime(DateTime.Today).AddDays(90);
        if (dateTo > horizon) dateTo = horizon;

        for (var d = dateFrom; d <= dateTo; d = d.AddDays(1))
        {
            if (d.DayOfWeek == DayOfWeek.Saturday || d.DayOfWeek == DayOfWeek.Sunday) continue;

            var existing = await _db.ShiftEntries.FirstOrDefaultAsync(x => x.EmployeeId == employeeId && x.ShiftDate == d);
            if (_db.PreserveManualShift(existing, "Sick leave sync")) continue;
            if (existing != null)
            {
                existing.PreviousStatus = existing.ShiftType;
                existing.ShiftType = "SL";
                existing.IsWicDuty = false;
                existing.AutoGenerated = true;
                existing.SourceModule = "SickLeave";
                existing.SourceId = sourceId;
            }
            else
            {
                _db.ShiftEntries.Add(new ShiftEntry
                {
                    EmployeeId = employeeId,
                    ShiftDate = d,
                    ShiftType = "SL",
                    AutoGenerated = true,
                    SourceModule = "SickLeave",
                    SourceId = sourceId
                });
            }
        }
        await _db.SaveChangesAsync();
    }

    public async Task SyncVacationAsync(string employeeId, DateOnly dateFrom, DateOnly dateTo, int sourceId, string shiftType = "AL", string sourceModule = "Vacation")
    {
        for (var d = dateFrom; d <= dateTo; d = d.AddDays(1))
        {
            if (d.DayOfWeek == DayOfWeek.Saturday || d.DayOfWeek == DayOfWeek.Sunday) continue;

            var existing = await _db.ShiftEntries.FirstOrDefaultAsync(x => x.EmployeeId == employeeId && x.ShiftDate == d);
            if (_db.PreserveManualShift(existing, "Vacation sync")) continue;
            if (existing != null)
            {
                existing.PreviousStatus = existing.ShiftType;
                existing.ShiftType = shiftType;
                existing.IsWicDuty = false;
                existing.AutoGenerated = true;
                existing.SourceModule = sourceModule;
                existing.SourceId = sourceId;
            }
            else
            {
                _db.ShiftEntries.Add(new ShiftEntry
                {
                    EmployeeId = employeeId,
                    ShiftDate = d,
                    ShiftType = shiftType,
                    AutoGenerated = true,
                    SourceModule = sourceModule,
                    SourceId = sourceId
                });
            }
        }
        await _db.SaveChangesAsync();
    }

    public async Task RevertSickLeaveAsync(string employeeId, DateOnly dateFrom, DateOnly dateTo, int sourceId)
    {
        var entries = await _db.ShiftEntries
            .Where(x => x.EmployeeId == employeeId
                     && x.ShiftDate >= dateFrom
                     && x.ShiftDate <= dateTo
                     && x.SourceModule == "SickLeave"
                     && x.SourceId == sourceId)
            .ToListAsync();

        foreach (var e in entries)
        {
            if (_db.PreserveManualShift(e, "Sick leave revert")) continue;
            if (e.PreviousStatus != null)
            {
                e.ShiftType = e.PreviousStatus;
                e.AutoGenerated = false;
                e.SourceModule = null;
                e.SourceId = null;
                e.PreviousStatus = null;
            }
            else
            {
                _db.ShiftEntries.Remove(e);
            }
        }
        await _db.SaveChangesAsync();
    }

    public async Task RevertVacationAsync(string employeeId, DateOnly dateFrom, DateOnly dateTo, int sourceId, string sourceModule = "Vacation")
    {
        var entries = await _db.ShiftEntries
            .Where(x => x.EmployeeId == employeeId
                     && x.ShiftDate >= dateFrom
                     && x.ShiftDate <= dateTo
                     && x.SourceModule == sourceModule
                     && x.SourceId == sourceId)
            .ToListAsync();

        foreach (var e in entries)
        {
            if (_db.PreserveManualShift(e, "Vacation revert")) continue;
            if (e.PreviousStatus != null)
            {
                e.ShiftType = e.PreviousStatus;
                e.AutoGenerated = false;
                e.SourceModule = null;
                e.SourceId = null;
                e.PreviousStatus = null;
            }
            else
            {
                _db.ShiftEntries.Remove(e);
            }
        }
        await _db.SaveChangesAsync();
    }

    /// <summary>
    /// Vacations written straight into the Vacations table (tracker import, SQL)
    /// never pass through VacationService, so SyncVacationAsync never ran for them
    /// and their days stayed WORKING / WIC_DUTY. This reconciles FUTURE dates:
    /// every weekday inside a vacation becomes AL and its WIC duty is removed.
    /// Days already carrying an absence are never touched.
    /// </summary>
    public async Task<int> ReconcileFutureVacationsAsync()
    {
        var today = DateOnly.FromDateTime(DateTime.Today);

        var keep = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
            { "AL", "HALF_AL", "SL", "UL", "OL", "PH", "LPH", "OFF", "OFF_WEEKEND", "CD", "RESIGNED" };

        var vacs = await _db.Vacations
            .Where(v => v.LastDay >= today && v.EmployeeId != null)
            .Select(v => new { v.Id, v.EmployeeId, v.FirstDay, v.LastDay })
            .ToListAsync();
        if (vacs.Count == 0) return 0;

        var empIds = vacs.Select(v => v.EmployeeId!).Distinct().ToList();
        var maxDay = vacs.Max(v => v.LastDay);

        var active = (await _db.Employees
            .Where(e => e.IsActive && empIds.Contains(e.EmployeeId))
            .Select(e => e.EmployeeId)
            .ToListAsync()).ToHashSet();

        var shifts = await _db.ShiftEntries
            .Where(s => empIds.Contains(s.EmployeeId) && s.ShiftDate >= today && s.ShiftDate <= maxDay)
            .ToListAsync();
        var byKey = shifts.ToLookup(s => (s.EmployeeId, s.ShiftDate));

        var touched = new List<(string Emp, DateOnly Date)>();

        foreach (var v in vacs)
        {
            if (!active.Contains(v.EmployeeId!)) continue;
            var from = v.FirstDay < today ? today : v.FirstDay;
            for (var d = from; d <= v.LastDay; d = d.AddDays(1))
            {
                if (d.DayOfWeek is DayOfWeek.Saturday or DayOfWeek.Sunday) continue;
                var row = byKey[(v.EmployeeId!, d)].FirstOrDefault();
                if (_db.PreserveManualShift(row, "Future vacation reconciliation")) continue;
                if (row == null || keep.Contains(row.ShiftType)) continue;

                row.PreviousStatus = row.ShiftType;
                row.ShiftType      = "AL";
                row.RawValue       = "AL";
                row.ShiftStart     = null;
                row.ShiftEnd       = null;
                row.IsWicDuty      = false;
                row.AgentTask      = null;
                row.AutoGenerated  = true;
                row.SourceModule   = "Vacation";
                row.SourceId       = v.Id;
                touched.Add((v.EmployeeId!, d));
            }
        }

        if (touched.Count == 0) return 0;

        var emps  = touched.Select(t => t.Emp).Distinct().ToList();
        var dates = touched.Select(t => t.Date).Distinct().ToList();
        var keySet = touched.ToHashSet();
        var wic = await _db.WicShiftEntries
            .Where(w => emps.Contains(w.EmployeeId) && dates.Contains(w.ShiftDate))
            .ToListAsync();
        _db.WicShiftEntries.RemoveRange(wic.Where(w => keySet.Contains((w.EmployeeId, w.ShiftDate))));

        await _db.SaveChangesAsync();
        return touched.Count;
    }
}
