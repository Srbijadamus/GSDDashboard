# wic_manual_duty_report.ps1  (v2)
# READ-ONLY (SELECT + GET only). No INSERT/UPDATE/DELETE, no schema change.
# Purpose: analyse all manual WIC_DUTY ShiftEntries rows (ManualChangeBy not empty)
# with ShiftDate >= today, and report the four asked-for groups.
# Output intentionally contains NO employee names (only ShiftEntries Id, date, centre).
#
# Groups are MUTUALLY EXCLUSIVE:
#   G1 = has WicShiftEntries that day, but the centre(s) differ from AgentTask (incl. no centre at all)
#   G2 = NO WicShiftEntries row for that employee+day
#   G3 = AgentTask empty/NULL, but has a WicShiftEntries row (otherwise it lands in G2)
#   G4 = clean

$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.Data
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8

# Exact same rule as Backend/Services/WicLocationMatcher.MatchesAgentTask.
Add-Type -TypeDefinition @"
using System;
public static class AgentTaskMatch
{
    public static bool Matches(string agentTask, string displayName, string locationCode, string legacy)
    {
        if (string.IsNullOrWhiteSpace(agentTask)) return false;
        var raw = agentTask.Trim();
        bool wasTruncated = raw.Length >= 20;
        var task = raw;
        if (Eq(task, displayName) || Eq(task, locationCode) || Eq(task, legacy)) return true;
        if (!wasTruncated || task.Length == 0) return false;
        return Starts(displayName, task) || Starts(locationCode, task) || Starts(legacy, task);
    }
    static bool Eq(string a, string b) { return !string.IsNullOrEmpty(b) && string.Equals(a, b, StringComparison.OrdinalIgnoreCase); }
    static bool Starts(string full, string p) { return !string.IsNullOrEmpty(full) && full.StartsWith(p, StringComparison.OrdinalIgnoreCase); }
}
"@

$cs = "Server=localhost\SQLEXPRESS;Database=GSDDashboard;Integrated Security=true;TrustServerCertificate=yes;"
$base = "http://localhost:5000"
$today = (Get-Date).ToString("yyyy-MM-dd")

$conn = New-Object System.Data.SqlClient.SqlConnection($cs)
$conn.Open()

function Rows([string]$sql) {
    $cmd = $conn.CreateCommand(); $cmd.CommandText = $sql; $cmd.CommandTimeout = 300
    $rdr = $cmd.ExecuteReader()
    $out = New-Object System.Collections.ArrayList
    while ($rdr.Read()) {
        $h = @{}
        for ($i = 0; $i -lt $rdr.FieldCount; $i++) {
            $v = $rdr.GetValue($i); if ($v -is [System.DBNull]) { $v = $null }
            $h[$rdr.GetName($i)] = $v
        }
        [void]$out.Add([pscustomobject]$h)
    }
    $rdr.Close()
    return $out
}

$manual = Rows @"
SELECT se.Id, se.EmployeeId, CONVERT(varchar(10),se.ShiftDate,23) AS D, se.AgentTask, se.SourceModule,
       se.ManualChangeBy, se.ManualChangeAt, se.AutoGenerated
FROM ShiftEntries se
WHERE se.ShiftType='WIC_DUTY'
  AND se.ManualChangeBy IS NOT NULL AND LTRIM(RTRIM(se.ManualChangeBy))<>''
  AND se.ShiftDate >= CAST(GETDATE() AS date)
ORDER BY se.ShiftDate, se.Id
"@

$wic = Rows @"
SELECT w.Id, w.EmployeeId, CONVERT(varchar(10),w.ShiftDate,23) AS D, w.SupportLocation,
       w.LocationCode, w.IsOnSite, w.WorkingShift, w.Task
FROM WicShiftEntries w
WHERE w.ShiftDate >= CAST(GETDATE() AS date)
"@

$locs = Rows "SELECT LocationCode, DisplayName, City, LocationCodeLegacy, IsActive, MinAgentsRequired FROM WicLocations"

$wicByKey = @{}
foreach ($w in $wic) {
    $k = "$($w.EmployeeId)|$($w.D)"
    if (-not $wicByKey.ContainsKey($k)) { $wicByKey[$k] = New-Object System.Collections.ArrayList }
    [void]$wicByKey[$k].Add($w)
}

function Resolve-AgentTask([string]$task) {
    if ([string]::IsNullOrWhiteSpace($task)) { return @() }
    $hits = New-Object System.Collections.ArrayList
    foreach ($l in $locs) {
        if ([AgentTaskMatch]::Matches($task, $l.DisplayName, $l.LocationCode, $l.LocationCodeLegacy)) {
            [void]$hits.Add($l)
        }
    }
    return $hits
}

$covCache = @{}
function Get-Coverage([string]$date) {
    if ($covCache.ContainsKey($date)) { return $covCache[$date] }
    $map = @{}
    try {
        $resp = Invoke-WebRequest -Uri "$base/api/wic/coverage?date=$date" -Method GET -TimeoutSec 30 -UseBasicParsing
        foreach ($l in ($resp.Content | ConvertFrom-Json)) { $map[$l.displayName] = $l }
    } catch { $map["__ERROR__"] = $_.Exception.Message }
    $covCache[$date] = $map
    return $map
}

$G1 = New-Object System.Collections.ArrayList
$G2 = New-Object System.Collections.ArrayList
$G3 = New-Object System.Collections.ArrayList
$G4 = New-Object System.Collections.ArrayList
$all = New-Object System.Collections.ArrayList

foreach ($m in $manual) {
    $k = "$($m.EmployeeId)|$($m.D)"
    $rows = @()
    if ($wicByKey.ContainsKey($k)) { $rows = @($wicByKey[$k]) }

    $locsAll  = @($rows | ForEach-Object { $_.SupportLocation } | Where-Object { $_ } | Select-Object -Unique)
    $locsSite = @($rows | Where-Object { $_.IsOnSite } | ForEach-Object { $_.SupportLocation } | Where-Object { $_ } | Select-Object -Unique)
    $agentHits = Resolve-AgentTask $m.AgentTask
    $agentName = $null
    if ($agentHits.Count -gt 0) { $agentName = $agentHits[0].DisplayName }
    $otherLocs = @($locsAll | Where-Object { -not $agentName -or $_ -ne $agentName })

    $rec = [pscustomobject]@{
        Id = $m.Id; Date = $m.D; AgentTask = $m.AgentTask; Src = $m.SourceModule
        By = $m.ManualChangeBy; At = $m.ManualChangeAt
        WicRowCount = $rows.Count
        WicDetail = (@($rows | ForEach-Object { "wicId=$($_.Id) loc=[$($_.SupportLocation)] onSite=$($_.IsOnSite)" }) -join ' ; ')
        AllLocs = ($locsAll -join ' ; ')
        OnSiteLocs = ($locsSite -join ' ; ')
        OtherLocs = ($otherLocs -join ' ; ')
        AgentResolved = $agentName
        AgentHitCount = $agentHits.Count
        EmptyTask = [string]::IsNullOrWhiteSpace($m.AgentTask)
        RowCount = $rows.Count
    }
    [void]$all.Add($rec)

    if ($rows.Count -eq 0)            { [void]$G2.Add($rec) }
    elseif ($rec.EmptyTask)           { [void]$G3.Add($rec) }
    elseif ($agentHits.Count -eq 0 -or $otherLocs.Count -gt 0 -or $locsAll.Count -eq 0) { [void]$G1.Add($rec) }
    else                              { [void]$G4.Add($rec) }
}

$out = New-Object System.Collections.ArrayList
function P($s) { [void]$out.Add($s) }

P "WIC MANUAL DUTY REPORT (read-only)  generated $(Get-Date -Format 'yyyy-MM-dd HH:mm')  today=$today"
P "Scope: ShiftEntries ShiftType=WIC_DUTY, ManualChangeBy not empty, ShiftDate >= today"
P "Total manual WIC_DUTY rows today or later: $($manual.Count)"
P ("  {0} have >=1 WicShiftEntries row for that employee+day, {1} have none" -f ($manual.Count - $G2.Count), $G2.Count)
P ""
P "Groups are mutually exclusive. G1/G2/G3 are the rows RTM must look at."
P ""

function Dump($title, $set) {
    P "=== $title ($($set.Count)) ==="
    foreach ($r in $set) {
        P ("  Id={0,-6} {1}  AgentTask=[{2}]  WIC=[{3}]  WicRows={4}  by={5}" -f `
            $r.Id, $r.Date, $r.AgentTask, $(if($r.AllLocs){$r.AllLocs}else{'<none>'}), $r.WicRowCount, $r.By)
        if ($r.WicRowCount -gt 0) { P ("        raw: {0}" -f $r.WicDetail) }
    }
    P ""
}

Dump "GROUP 1 - WicShiftEntries exist but centre differs from AgentTask" $G1
Dump "GROUP 2 - no WicShiftEntries row for the same employee+day" $G2
Dump "GROUP 3 - empty/NULL AgentTask (with WicShiftEntries present)" $G3
Dump "GROUP 4 - clean (AgentTask centre is the only WIC centre)" $G4

P "=== GROUP 2: does the WIC coverage endpoint show the centre that day? ==="
P "  endpoint: GET $base/api/wic/coverage?date=  (counts WicShiftEntries with IsOnSite=1 per centre)"
foreach ($r in $G2) {
    $cov = Get-Coverage $r.Date
    if ($r.AgentResolved) {
        $c = $cov[$r.AgentResolved]
        $shown = if ($c) { "LISTED isCovered=$($c.isCovered) agentCount=$($c.agentCount)" } else { "NOT LISTED" }
        $lc = ($locs | Where-Object { $_.DisplayName -eq $r.AgentResolved } | Select-Object -First 1).LocationCode
        P ("  Id={0,-6} {1}  centre=[{2}]  locCode={3}  -> {4}" -f $r.Id, $r.Date, $r.AgentResolved, $lc, $shown)
    } else {
        P ("  Id={0,-6} {1}  AgentTask=[{2}]  -> AgentTask did not resolve to any WicLocation" -f $r.Id, $r.Date, $r.AgentTask)
    }
}
P ""

P "=== GROUP 1: coverage endpoint view of both centres ==="
foreach ($r in $G1) {
    $cov = Get-Coverage $r.Date
    $parts = @()
    foreach ($n in @($r.AllLocs -split ' ; ' | Where-Object { $_ })) {
        $c = $cov[$n]
        $parts += ("{0}: {1}" -f $n, $(if ($c) { "LISTED agentCount=$($c.agentCount) isCovered=$($c.isCovered)" } else { "NOT LISTED" }))
    }
    if ($parts.Count -eq 0) { $parts += "<no centre stored on the WIC rows>" }
    P ("  Id={0,-6} {1}  AgentTask=[{2}] -> resolved=[{3}]" -f $r.Id, $r.Date, $r.AgentTask, $r.AgentResolved)
    P ("        {0}" -f ($parts -join ' | '))
}
P ""

P "=== GROUP 3: coverage endpoint view of the centre named by the WIC rows ==="
foreach ($r in $G3) {
    $cov = Get-Coverage $r.Date
    foreach ($n in @($r.AllLocs -split ' ; ' | Where-Object { $_ })) {
        $c = $cov[$n]
        P ("  Id={0,-6} {1}  WIC centre=[{2}] -> {3}" -f $r.Id, $r.Date, $n, $(if ($c) { "LISTED agentCount=$($c.agentCount)" } else { "NOT LISTED" }))
    }
    if (-not $r.AllLocs) { P ("  Id={0,-6} {1}  WIC rows carry no SupportLocation" -f $r.Id, $r.Date) }
}
P ""

P "=== Q4: AUDIT / HISTORY SURFACES ==="
P "  Tables/columns whose NAME suggests history or last-modified:"
foreach ($a in (Rows @"
SELECT t.name AS T, c.name AS C, typ.name AS Ty
FROM sys.tables t
JOIN sys.columns c ON c.object_id = t.object_id
JOIN sys.types typ ON typ.user_type_id = c.user_type_id
WHERE t.name LIKE '%Histor%' OR t.name LIKE '%Audit%' OR t.name LIKE '%Log%'
   OR c.name LIKE '%LastModified%' OR c.name LIKE '%ChangedBy%' OR c.name LIKE '%ChangedAt%'
   OR c.name LIKE '%ModifiedBy%' OR c.name LIKE '%ModifiedAt%'
ORDER BY t.name, c.column_id
"@)) { P ("    {0}.{1} ({2})" -f $a.T, $a.C, $a.Ty) }
P "  SubstitutionHistory (49 rows): Id, EmployeeId, LocationCode, Date, SourceType, AssignedAt"
P "  RtmEntries (3 rows)          : Id, EntryDate, EmployeeId, FullName, ShiftStart, ShiftEnd, Tag, SourceLine, CreatedAt"
P "  ShiftEntries history fields  : ManualChangeBy / ManualChangeAt / ManualChangeNote (ONE value, last write only)"
P ""
P "  Manual WIC_DUTY today+ rows whose ManualChangeBy is NOT S60028:"
$notS = Rows @"
SELECT se.Id, CONVERT(varchar(10),se.ShiftDate,23) AS D, se.AgentTask, se.ManualChangeBy, se.ManualChangeAt, se.ManualChangeNote
FROM ShiftEntries se
WHERE se.ShiftType='WIC_DUTY' AND se.ManualChangeBy IS NOT NULL AND LTRIM(RTRIM(se.ManualChangeBy))<>''
  AND se.ManualChangeBy <> 'S60028' AND se.ShiftDate >= CAST(GETDATE() AS date)
ORDER BY se.ShiftDate, se.Id
"@
foreach ($r in $notS) { P ("    Id={0,-6} {1}  AgentTask=[{2}]  by={3}  at={4}" -f $r.Id, $r.D, $r.AgentTask, $r.ManualChangeBy, $r.ManualChangeAt) }
P ("    -> {0} row(s)" -f $notS.Count)
P ""
P "  Manual-WIC today+ rows touched by another writer AFTER ManualChangeAt"
P "  (evidence available: SubstitutionHistory.AssignedAt, RtmEntries.CreatedAt):"
$subs = Rows @"
SELECT se.Id, CONVERT(varchar(10),se.ShiftDate,23) AS D, sh.SourceType, sh.AssignedAt
FROM ShiftEntries se
JOIN SubstitutionHistory sh ON sh.EmployeeId = se.EmployeeId AND sh.Date = se.ShiftDate
WHERE se.ShiftType='WIC_DUTY' AND se.ManualChangeBy IS NOT NULL AND LTRIM(RTRIM(se.ManualChangeBy))<>''
  AND se.ShiftDate >= CAST(GETDATE() AS date) AND se.ManualChangeAt IS NOT NULL AND sh.AssignedAt > se.ManualChangeAt
ORDER BY se.ShiftDate, se.Id
"@
foreach ($s in $subs) { P ("    Id={0,-6} {1}  SubstitutionHistory source={2} assignedAt={3}" -f $s.Id, $s.D, $s.SourceType, $s.AssignedAt) }
if ($subs.Count -eq 0) { P "    (none)" }
$rtm = Rows @"
SELECT se.Id, CONVERT(varchar(10),se.ShiftDate,23) AS D, re.Tag, re.CreatedAt
FROM ShiftEntries se
JOIN RtmEntries re ON re.EmployeeId = se.EmployeeId AND re.EntryDate = se.ShiftDate
WHERE se.ShiftType='WIC_DUTY' AND se.ManualChangeBy IS NOT NULL AND LTRIM(RTRIM(se.ManualChangeBy))<>''
  AND se.ShiftDate >= CAST(GETDATE() AS date) AND se.ManualChangeAt IS NOT NULL AND re.CreatedAt > se.ManualChangeAt
ORDER BY se.ShiftDate, se.Id
"@
foreach ($s in $rtm) { P ("    Id={0,-6} {1}  RtmEntries tag={2} createdAt={3}" -f $s.Id, $s.D, $s.Tag, $s.CreatedAt) }
if ($rtm.Count -eq 0) { P "    (none)" }
P ""
P "  Also: distinct ManualChangeNote values among the manual WIC_DUTY today+ rows"
foreach ($n in (Rows @"
SELECT ISNULL(se.ManualChangeNote,'<NULL>') AS N, COUNT(*) AS C
FROM ShiftEntries se
WHERE se.ShiftType='WIC_DUTY' AND se.ManualChangeBy IS NOT NULL AND LTRIM(RTRIM(se.ManualChangeBy))<>''
  AND se.ShiftDate >= CAST(GETDATE() AS date)
GROUP BY ISNULL(se.ManualChangeNote,'<NULL>') ORDER BY C DESC
"@)) { P ("    {0,-70} {1}" -f $n.N, $n.C) }
P ""

P "=== SUMMARY COUNTS (mutually exclusive) ==="
P ("  manual WIC_DUTY rows, ShiftDate >= today : {0}" -f $manual.Count)
P ("  GROUP 1 centre mismatch                  : {0}" -f $G1.Count)
P ("  GROUP 2 no WicShiftEntries               : {0}" -f $G2.Count)
P ("  GROUP 3 empty AgentTask (has WIC rows)   : {0}" -f $G3.Count)
P ("  GROUP 4 clean                            : {0}" -f $G4.Count)
P ("  TOTAL G1+G2+G3+G4                        : {0}" -f ($G1.Count + $G2.Count + $G3.Count + $G4.Count))
P ""
P ("  GROUP 1 ids: $((($G1 | ForEach-Object { $_.Id }) -join ', '))")
P ("  GROUP 2 ids: $((($G2 | ForEach-Object { $_.Id }) -join ', '))")
P ("  GROUP 3 ids: $((($G3 | ForEach-Object { $_.Id }) -join ', '))")
P ""
P "=== RTM MANUAL CHECK LIST (G1 + G2 + G3, no duplicates) ==="
P ("  ids: $((($G1 + $G2 + $G3 | ForEach-Object { $_.Id } | Sort-Object -Unique) -join ', '))")

$conn.Close()
$out -join "`r`n" | Set-Content -Path "C:\GSDDashboard_secure\Tools\wic_manual_duty_report.txt" -Encoding UTF8
$out -join "`r`n"
