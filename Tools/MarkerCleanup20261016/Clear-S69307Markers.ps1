# Clear-S69307Markers.ps1
# =====================================================================
# POINT 2 of the 2026-10-16 task: the 12 ShiftEntries rows left over from
# 2026-10-09 with ManualChangeBy = 'S69307'.
#
# A manual marker means "a human deliberately decided this row" and makes the
# row untouchable for the roster generator. Script-driven edits must never carry
# it (Silvija's generator covers 85-90% of the plan and a manual marker blocks
# it), so this run removes the marker from exactly the rows no human has changed
# since the 2026-10-09 09:55-09:59 write window.
#
# WHAT EACH CLEANED ROW GETS (nothing else):
#     ManualChangeBy   = NULL
#     ManualChangeAt   = NULL
#     ManualChangeNote = NULL
#     SourceModule     = 'SHIFT_FIX 2026-10-16 MARKER_CLEANUP'
# The shift VALUE is NEVER touched: ShiftType, ShiftStart, ShiftEnd, RawValue,
# AgentTask, IsWicDuty, SourceId, AutoGenerated, ShiftDate and EmployeeId keep
# their current value. WicShiftEntries is not touched at all.
#
# PER-ROW GUARD ("RTM changed it in the meantime"): a row is written ONLY while
# it is still exactly the 2026-10-09 machine write -
#     ManualChangeBy   = 'S69307'
#     ManualChangeAt   inside [AtFrom, AtTo]  (the write window)
#     ManualChangeNote = 'Manual shift cell edit (/shifts); automatic writers must preserve this row.'
# Anything else (ManualChangeBy already cleared by RTM, a different note, a
# timestamp outside the window) is SKIPPED and listed in the report. Nothing is
# skipped silently.
#
# MODES
#   DryRun (default) : SELECT only. Prints cleaned/skipped split + the full
#                      pre-image table; writes the preview CSVs.
#   Apply            : requires -ExpectedMarkedCount (the total dry-run count of
#                      rows carrying the marker) and -ExpectedCleanCount (the
#                      dry-run count of rows free of human edits). Writes the
#                      backup directory (CSV + SHA256SUMS.txt + rollback.sql)
#                      FIRST, then ONE transaction with the per-row guard,
#                      ROLLBACK on any failure.
#
# Examples:
#   pwsh -File Tools\MarkerCleanup20261016\Clear-S69307Markers.ps1
#   pwsh -File Tools\MarkerCleanup20261016\Clear-S69307Markers.ps1 -Apply -ExpectedMarkedCount 12 -ExpectedCleanCount 12

[CmdletBinding()]
param(
    [string] $ConnectionString = "Server=localhost\SQLEXPRESS;Database=GSDDashboard;Integrated Security=true;TrustServerCertificate=yes;",
    [ValidateSet('DryRun','Apply')] [string] $Mode = 'DryRun',
    [string] $ActorKid    = 'S69307',
    [string] $TraceMarker = 'SHIFT_FIX 2026-10-16 MARKER_CLEANUP',
    [string] $FixNote     = 'Manual shift cell edit (/shifts); automatic writers must preserve this row.',
    [string] $AtFrom      = '2026-10-09T00:00:00',
    [string] $AtTo        = '2026-10-09T23:59:59',
    [string] $BackupRoot  = 'C:\GSDDashboard_secure\task-backups',
    [string] $PreviewDir  = 'C:\GSDDashboard_secure\.tmp-markercleanup-20261016',
    [int]    $ExpectedMarkedCount = 0,
    [int]    $ExpectedCleanCount  = 0,
    [switch] $Apply
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Data
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
if ($Apply) { $Mode = 'Apply' }
$isDryRun = ($Mode -ne 'Apply')

$Inv = [System.Globalization.CultureInfo]::InvariantCulture
function Enc([object]$v) {
    if ($null -eq $v -or $v -is [System.DBNull]) { return 'NULL' }
    $s = [string]$v
    if ($s.Length -eq 0) { return 'NULL' }
    return "N'" + $s.Replace("'", "''") + "'"
}
function EncDt([object]$v) {
    if ($null -eq $v -or $v -is [System.DBNull]) { return 'NULL' }
    return "CONVERT(datetime2,'" + ([datetime]$v).ToString('yyyy-MM-ddTHH:mm:ss.fffffff', $Inv) + "',126)"
}
function EncBit([object]$v) {
    if ($null -eq $v -or $v -is [System.DBNull]) { return 'NULL' }
    if ([bool]$v) { return '1' } else { return '0' }
}
function Sha([string]$p) { (Get-FileHash -LiteralPath $p -Algorithm SHA256).Hash }

$conn = New-Object System.Data.SqlClient.SqlConnection($ConnectionString)
$conn.Open()

function Invoke-Rows([string]$sql, $pars = $null, $tx = $null) {
    $cmd = $conn.CreateCommand(); $cmd.CommandText = $sql; $cmd.CommandTimeout = 900
    if ($tx) { $cmd.Transaction = $tx }
    if ($pars) { foreach ($pv in $pars.GetEnumerator()) { $pp = $cmd.CreateParameter(); $pp.ParameterName = $pv.Key; $pp.Value = $pv.Value; [void]$cmd.Parameters.Add($pp) } }
    $rdr = $cmd.ExecuteReader()
    $out = New-Object System.Collections.ArrayList
    while ($rdr.Read()) {
        $h = [ordered]@{}
        for ($i = 0; $i -lt $rdr.FieldCount; $i++) {
            $v = $rdr.GetValue($i); if ($v -is [System.DBNull]) { $v = $null }
            $h[$rdr.GetName($i)] = $v
        }
        [void]$out.Add([pscustomobject]$h)
    }
    $rdr.Close()
    return ,$out
}
function Invoke-NonQuery([string]$sql, $pars = $null, $tx = $null) {
    $cmd = $conn.CreateCommand(); $cmd.CommandText = $sql; $cmd.CommandTimeout = 900
    if ($tx) { $cmd.Transaction = $tx }
    if ($pars) { foreach ($pv in $pars.GetEnumerator()) { $pp = $cmd.CreateParameter(); $pp.ParameterName = $pv.Key; $pp.Value = $pv.Value; [void]$cmd.Parameters.Add($pp) } }
    return $cmd.ExecuteNonQuery()
}

$P = { param($s) Write-Host $s }
& $P "MODE  : $Mode"
& $P "marker: ManualChangeBy='$ActorKid'"

# ---------------------------------------------------------------------------
# Pre-image: EVERY row carrying the marker (the task's point 2a list)
# ---------------------------------------------------------------------------
$marked = Invoke-Rows @"
SELECT Id, EmployeeId, CONVERT(varchar(10),ShiftDate,23) AS D, ShiftType, RawValue, AgentTask,
       ShiftStart, ShiftEnd, IsWicDuty, AutoGenerated, SourceModule, SourceId,
       ManualChangeBy, CONVERT(varchar(23),ManualChangeAt,126) AS ManualChangeAtIso, ManualChangeNote
FROM ShiftEntries
WHERE ManualChangeBy = @kid
ORDER BY ShiftDate, EmployeeId, Id
"@ @{ '@kid' = $ActorKid }

& $P ""
& $P "Rows with ManualChangeBy='$ActorKid' : $($marked.Count)"

# ---------------------------------------------------------------------------
# Per-row verdict
# ---------------------------------------------------------------------------
$fromDt = [datetime]::SpecifyKind([datetime]::Parse($AtFrom, $Inv), [System.DateTimeKind]::Utc)
$toDt   = [datetime]::SpecifyKind([datetime]::Parse($AtTo,   $Inv), [System.DateTimeKind]::Utc)

$verdicts = foreach ($r in $marked) {
    $why = $null
    if ([string]$r.ManualChangeBy -ne $ActorKid) { $why = 'OTHER_ACTOR' }
    elseif ($null -eq $r.ManualChangeAtIso) { $why = 'AT_MISSING' }
    elseif ([datetime]::Parse($r.ManualChangeAtIso, $Inv, [System.Globalization.DateTimeStyles]::AdjustToUniversal) -lt $fromDt -or
            [datetime]::Parse($r.ManualChangeAtIso, $Inv, [System.Globalization.DateTimeStyles]::AdjustToUniversal) -gt $toDt) { $why = 'AT_OUTSIDE_WRITE_WINDOW' }
    elseif ([string]$r.ManualChangeNote -ne $FixNote) { $why = 'NOTE_CHANGED' }
    [pscustomobject]@{
        Id = [int]$r.Id; EmployeeId = [string]$r.EmployeeId; D = [string]$r.D
        ShiftType = [string]$r.ShiftType; RawValue = [string]$r.RawValue; AgentTask = [string]$r.AgentTask
        ShiftStart = [string]$r.ShiftStart; ShiftEnd = [string]$r.ShiftEnd
        IsWicDuty = [bool]$r.IsWicDuty; AutoGenerated = [bool]$r.AutoGenerated
        SourceModule = [string]$r.SourceModule; SourceId = $r.SourceId
        ManualChangeBy = [string]$r.ManualChangeBy; ManualChangeAtIso = [string]$r.ManualChangeAtIso
        ManualChangeNote = [string]$r.ManualChangeNote
        SkipWhy = $why
    }
}

$clean   = @($verdicts | Where-Object { [string]::IsNullOrEmpty($_.SkipWhy) })
$skipped = @($verdicts | Where-Object { -not [string]::IsNullOrEmpty($_.SkipWhy) })

& $P ""
& $P "== 2a PRE-IMAGE - every row carrying the marker =="
$verdicts | Select-Object Id, EmployeeId, D, ShiftType, RawValue, AgentTask, ShiftStart, ShiftEnd,
    IsWicDuty, SourceModule, SourceId, ManualChangeAtIso, SkipWhy |
    Format-Table -AutoSize | Out-String -Width 400 | Write-Output

& $P "TO CLEAN (still the 2026-10-09 machine write) : $($clean.Count)"
& $P "TO SKIP  (a human changed it in the meantime)  : $($skipped.Count)"
foreach ($s in $skipped) {
    & $P ("   SKIP Id={0} emp={1} {2} type={3} why={4} currentBy='{5}' at={6}" -f `
        $s.Id, $s.EmployeeId, $s.D, $s.ShiftType, $s.SkipWhy, $s.ManualChangeBy, $s.ManualChangeAtIso)
}

if (-not (Test-Path -LiteralPath $PreviewDir)) { New-Item -ItemType Directory -Path $PreviewDir -Force | Out-Null }
$verdicts | Export-Csv (Join-Path $PreviewDir 'marked-preview.csv') -NoTypeInformation -Encoding UTF8

# ---------------------------------------------------------------------------
# WIC pre/post control state: WicShiftEntries of the affected employee/days
# ---------------------------------------------------------------------------
$wicPre = New-Object System.Collections.ArrayList
foreach ($r in $verdicts) {
    $rows = Invoke-Rows @"
SELECT Id, EmployeeId, CONVERT(varchar(10),ShiftDate,23) AS D, SupportLocation, LocationCode,
       WorkingShift, IsOnSite, IsGSDDay, IsOffDay, Task
FROM WicShiftEntries
WHERE EmployeeId = @emp AND ShiftDate = CONVERT(date, @d, 23)
ORDER BY Id
"@ @{ '@emp' = $r.EmployeeId; '@d' = $r.D }
    foreach ($w in $rows) { [void]$wicPre.Add($w) }
}
& $P ""
& $P "WicShiftEntries control rows for the affected employee/days : $($wicPre.Count)"
$wicPre | Export-Csv (Join-Path $PreviewDir 'wicshiftentries-pre.csv') -NoTypeInformation -Encoding UTF8

if ($isDryRun) {
    & $P ""
    & $P "DRY RUN - no writes. Preview: $(Join-Path $PreviewDir 'marked-preview.csv')"
    $conn.Close()
    return
}

# ---------------------------------------------------------------------------
# APPLY
# ---------------------------------------------------------------------------
if ($ExpectedMarkedCount -le 0) { throw "APPLY REFUSED: pass -ExpectedMarkedCount (the dry-run total of marked rows)." }
if ($ExpectedCleanCount -le 0) { throw "APPLY REFUSED: pass -ExpectedCleanCount (the dry-run count of rows to clean)." }
if ($marked.Count -ne $ExpectedMarkedCount) { throw ("APPLY REFUSED: {0} marked row(s), expected {1}. Re-run the dry run." -f $marked.Count, $ExpectedMarkedCount) }
if ($clean.Count -ne $ExpectedCleanCount) { throw ("APPLY REFUSED: {0} row(s) would be cleaned, expected {1}. Re-run the dry run." -f $clean.Count, $ExpectedCleanCount) }
if ($clean.Count -eq 0) { throw "APPLY REFUSED: nothing to clean." }

$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$root  = Join-Path $BackupRoot ("marker-cleanup-$stamp")
if (Test-Path -LiteralPath $root) { throw "Backup root already exists: $root" }
New-Item -ItemType Directory -Path $root -Force | Out-Null
& $P ""
& $P "BACKUP ROOT : $root"

$cleanIds = @($clean | ForEach-Object { [int]$_.Id })
$inClean  = ($cleanIds -join ',')

# --- backup BEFORE any write -------------------------------------------------
$pre = Invoke-Rows "SELECT * FROM ShiftEntries WHERE Id IN ($inClean) ORDER BY Id"
if ($pre.Count -ne $clean.Count) { throw ("BACKUP MISMATCH: read {0} rows, expected {1}" -f $pre.Count, $clean.Count) }
$pre | Export-Csv (Join-Path $root 'ShiftEntries-pre.csv') -NoTypeInformation -Encoding UTF8
$clean | Export-Csv (Join-Path $root 'cleaned-rows.csv') -NoTypeInformation -Encoding UTF8
$verdicts | Export-Csv (Join-Path $root 'marked-all.csv') -NoTypeInformation -Encoding UTF8
if ($skipped.Count) { $skipped | Export-Csv (Join-Path $root 'skipped-human-changed.csv') -NoTypeInformation -Encoding UTF8 }
$wicPre  | Export-Csv (Join-Path $root 'WicShiftEntries-pre.csv') -NoTypeInformation -Encoding UTF8

$hashLines = New-Object System.Collections.ArrayList
foreach ($f in @('ShiftEntries-pre.csv','cleaned-rows.csv','marked-all.csv','WicShiftEntries-pre.csv')) {
    [void]$hashLines.Add("$(Sha (Join-Path $root $f))  $f")
}
if ($skipped.Count) { [void]$hashLines.Add("$(Sha (Join-Path $root 'skipped-human-changed.csv'))  skipped-human-changed.csv") }
($hashLines -join "`r`n") | Set-Content -LiteralPath (Join-Path $root 'SHA256SUMS.txt') -Encoding ASCII

# --- rollback.sql (from the backup, NOT executed here) -----------------------
# Only the marker + SourceModule are restored. The guard means a row that already
# left the cleaned state is left alone rather than overwritten.
$rb = New-Object System.Collections.ArrayList
[void]$rb.Add("-- rollback.sql  -  UNDO the 2026-10-16 marker cleanup of ManualChangeBy='$ActorKid'")
[void]$rb.Add("-- Generated $([DateTime]::Now.ToString('yyyy-MM-dd HH:mm:ss'))  Source: Tools\MarkerCleanup20261016\Clear-S69307Markers.ps1")
[void]$rb.Add("-- Restores ManualChangeBy/ManualChangeAt/ManualChangeNote and SourceModule on the $($clean.Count) cleaned rows.")
[void]$rb.Add("-- ShiftType / times / AgentTask / RawValue / AutoGenerated are NOT part of this rollback: the cleanup never changed them.")
[void]$rb.Add("-- NOT executed by the script. Run by hand only if the marker must be put back.")
[void]$rb.Add("SET XACT_ABORT ON;")
[void]$rb.Add("BEGIN TRAN;")
foreach ($b in $pre) {
    [void]$rb.Add("UPDATE ShiftEntries SET ManualChangeBy=$(Enc $b.ManualChangeBy), ManualChangeAt=$(EncDt $b.ManualChangeAt), ManualChangeNote=$(Enc $b.ManualChangeNote), SourceModule=$(Enc $b.SourceModule) WHERE Id=$($b.Id) AND ManualChangeBy IS NULL AND SourceModule='$TraceMarker';")
}
[void]$rb.Add("COMMIT;")
($rb -join "`r`n") | Set-Content -LiteralPath (Join-Path $root 'rollback.sql') -Encoding UTF8
[void]$hashLines.Add("$(Sha (Join-Path $root 'rollback.sql'))  rollback.sql")
($hashLines -join "`r`n") | Set-Content -LiteralPath (Join-Path $root 'SHA256SUMS.txt') -Encoding ASCII

# --- ONE transaction with the per-row guard ---------------------------------
$applied = 0
$txSkipped = New-Object System.Collections.ArrayList
$tx = $conn.BeginTransaction('MarkerCleanup')
try {
    $guard = @{}
    $cmd = $conn.CreateCommand(); $cmd.Transaction = $tx
    $cmd.CommandText = "SELECT Id, EmployeeId, ShiftDate, ShiftType, RawValue, AgentTask, ShiftStart, ShiftEnd, AutoGenerated, SourceModule, ManualChangeBy, ManualChangeAt, ManualChangeNote FROM ShiftEntries WITH (UPDLOCK, HOLDLOCK) WHERE Id IN ($inClean)"
    $rdr = $cmd.ExecuteReader()
    while ($rdr.Read()) {
        $id = [int]$rdr.GetValue(0)
        $guard[$id] = [pscustomobject]@{
            EmployeeId = [string]$rdr.GetValue(1)
            ShiftDate  = [datetime]$rdr.GetValue(2)
            ShiftType  = [string]$rdr.GetValue(3)
            RawValue   = if ($rdr.IsDBNull(4)) { $null } else { [string]$rdr.GetValue(4) }
            AgentTask  = if ($rdr.IsDBNull(5)) { $null } else { [string]$rdr.GetValue(5) }
            ShiftStart = if ($rdr.IsDBNull(6)) { $null } else { [string]$rdr.GetValue(6) }
            ShiftEnd   = if ($rdr.IsDBNull(7)) { $null } else { [string]$rdr.GetValue(7) }
            Auto       = [bool]$rdr.GetValue(8)
            SourceMod  = if ($rdr.IsDBNull(9)) { $null } else { [string]$rdr.GetValue(9) }
            Manual     = if ($rdr.IsDBNull(10)) { $null } else { [string]$rdr.GetValue(10) }
            ManualAt   = if ($rdr.IsDBNull(11)) { $null } else { [datetime]$rdr.GetValue(11) }
            ManualNote = if ($rdr.IsDBNull(12)) { $null } else { [string]$rdr.GetValue(12) }
        }
    }
    $rdr.Close()

    foreach ($c in ($clean | Sort-Object Id)) {
        $id  = [int]$c.Id
        $cur = $guard[$id]
        $why = $null
        if (-not $cur) { $why = 'ROW_MISSING' }
        elseif ($cur.Manual -ne $ActorKid) { $why = 'OTHER_ACTOR' }
        elseif (-not $cur.ManualAt -or $cur.ManualAt -lt $fromDt -or $cur.ManualAt -gt $toDt) { $why = 'AT_OUTSIDE_WRITE_WINDOW' }
        elseif ($cur.ManualNote -ne $FixNote) { $why = 'NOTE_CHANGED' }
        if ($why) { [void]$txSkipped.Add([pscustomobject]@{ Id = $id; EmployeeId = $c.EmployeeId; Why = $why }); continue }

        $n = Invoke-NonQuery @"
UPDATE ShiftEntries
   SET ManualChangeBy   = NULL,
       ManualChangeAt   = NULL,
       ManualChangeNote = NULL,
       SourceModule     = @trace
 WHERE Id = @id AND ManualChangeBy = @kid
"@ @{ '@trace' = $TraceMarker; '@id' = $id; '@kid' = $ActorKid } $tx
        if ($n -ne 1) { throw "ShiftEntries Id=$id update affected $n row(s)" }
        $applied++
    }

    # Post-write verification INSIDE the transaction: marker gone, trace set, and the
    # shift VALUE identical to the guarded pre-image.
    $verify = Invoke-Rows "SELECT Id, EmployeeId, ShiftType, RawValue, AgentTask, ShiftStart, ShiftEnd, AutoGenerated, SourceModule, ManualChangeBy, ManualChangeAt, ManualChangeNote FROM ShiftEntries WHERE Id IN ($inClean)" $null $tx
    foreach ($v in $verify) {
        $g = $guard[[int]$v.Id]
        if ($v.ManualChangeBy -ne $null -or $v.ManualChangeAt -ne $null -or $v.ManualChangeNote -ne $null) { throw "POST-WRITE VERIFY FAILED: Id=$($v.Id) still carries a manual marker" }
        if ($v.SourceModule -ne $TraceMarker) { throw "POST-WRITE VERIFY FAILED: Id=$($v.Id) SourceModule='$($v.SourceModule)'" }
        if ([string]$v.ShiftType -ne [string]$g.ShiftType -or
            [string]$v.RawValue -ne [string]$g.RawValue -or
            [string]$v.AgentTask -ne [string]$g.AgentTask -or
            [string]$v.ShiftStart -ne [string]$g.ShiftStart -or
            [string]$v.ShiftEnd -ne [string]$g.ShiftEnd -or
            [bool]$v.AutoGenerated -ne [bool]$g.Auto) {
            throw "POST-WRITE VERIFY FAILED: Id=$($v.Id) changed a shift value"
        }
    }

    $tx.Commit()
    & $P "TRANSACTION COMMITTED: cleaned=$applied  tx-skips=$($txSkipped.Count)"
} catch {
    $tx.Rollback()
    & $P "APPLY FAILED - transaction ROLLED BACK: $($_.Exception.Message)"
    throw
} finally { $tx.Dispose() }

# ---------------------------------------------------------------------------
# Post state
# ---------------------------------------------------------------------------
$stillMarked = Invoke-Rows "SELECT Id FROM ShiftEntries WHERE ManualChangeBy = @kid ORDER BY Id" @{ '@kid' = $ActorKid }
$wicPost = New-Object System.Collections.ArrayList
foreach ($r in $verdicts) {
    $rows = Invoke-Rows @"
SELECT Id, EmployeeId, CONVERT(varchar(10),ShiftDate,23) AS D, SupportLocation, LocationCode,
       WorkingShift, IsOnSite, IsGSDDay, IsOffDay, Task
FROM WicShiftEntries
WHERE EmployeeId = @emp AND ShiftDate = CONVERT(date, @d, 23)
ORDER BY Id
"@ @{ '@emp' = $r.EmployeeId; '@d' = $r.D }
    foreach ($w in $rows) { [void]$wicPost.Add($w) }
}
$wicPost | Export-Csv (Join-Path $root 'WicShiftEntries-post.csv') -NoTypeInformation -Encoding UTF8

$post = Invoke-Rows "SELECT Id, EmployeeId, CONVERT(varchar(10),ShiftDate,23) AS D, ShiftType, RawValue, AgentTask, ShiftStart, ShiftEnd, AutoGenerated, SourceModule, ManualChangeBy FROM ShiftEntries WHERE Id IN ($inClean) ORDER BY Id"
$post | Export-Csv (Join-Path $root 'ShiftEntries-post.csv') -NoTypeInformation -Encoding UTF8

$wicSame = $true
if ($wicPre.Count -ne $wicPost.Count) { $wicSame = $false }
else {
    for ($i = 0; $i -lt $wicPre.Count; $i++) {
        if (($wicPre[$i] | ConvertTo-Json -Compress) -ne ($wicPost[$i] | ConvertTo-Json -Compress)) { $wicSame = $false; break }
    }
}

$report = New-Object System.Collections.ArrayList
$R = { param($s) [void]$report.Add($s); Write-Host $s }
& $R ""
& $R "MARKER CLEANUP - APPLIED"
& $R "generated        : $([DateTime]::Now.ToString('yyyy-MM-dd HH:mm:ss'))"
& $R "backup root      : $root"
& $R "transaction      : single; per-row guard; committed once"
& $R ""
& $R "RELEASE : ManualChangeBy=NULL, ManualChangeAt=NULL, ManualChangeNote=NULL"
& $R "TRACE   : SourceModule='$TraceMarker'"
& $R "UNTOUCHED: ShiftType, times, RawValue, AgentTask, IsWicDuty, AutoGenerated, ShiftDate, EmployeeId, SourceId, WicShiftEntries"
& $R ""
& $R "MARKED ROWS BEFORE            : $($marked.Count)"
& $R "ROWS CLEANED                  : $applied"
& $R "ROWS SKIPPED (human-changed)  : $($skipped.Count + $txSkipped.Count)"
foreach ($s in $skipped)  { & $R "   SKIP(pre) Id=$($s.Id) emp=$($s.EmployeeId) why=$($s.SkipWhy) by='$($s.ManualChangeBy)' at=$($s.ManualChangeAtIso)" }
foreach ($s in $txSkipped) { & $R "   SKIP(tx)  Id=$($s.Id) emp=$($s.EmployeeId) why=$($s.Why)" }
& $R ""
& $R "MARKED ROWS AFTER             : $($stillMarked.Count)"
& $R "WicShiftEntries control rows  : pre=$($wicPre.Count) post=$($wicPost.Count) identical=$wicSame"
foreach ($l in $hashLines) { & $R "SHA256  $l" }
($report -join "`r`n") | Set-Content -LiteralPath (Join-Path $root 'REPORT.txt') -Encoding UTF8

$conn.Close()
if ($stillMarked.Count -ne 0) { throw "POST-CHECK FAILED: $($stillMarked.Count) row(s) still carry ManualChangeBy='$ActorKid'" }
if (-not $wicSame) { throw 'POST-CHECK FAILED: WicShiftEntries control rows changed.' }
& $P ""
& $P "DONE: cleaned $applied row(s); $($stillMarked.Count) rows with the marker remain. Backup: $root"
