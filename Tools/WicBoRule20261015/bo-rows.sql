SET NOCOUNT ON;
-- All ShiftEntries rows with RawValue='BO' in [2026-10-15 .. 2027-02-28] for employees with an
-- ACTIVE WIC assignment (MAIN/BACKUP/REGIONAL). Centre = the agent's active assignments.
WITH wic AS (
    SELECT e.EmployeeId, e.FullName,
           MAX(CASE WHEN a.AssignmentType='MAIN'     THEN 1 ELSE 0 END) AS HasMain,
           MAX(CASE WHEN a.AssignmentType='BACKUP'   THEN 1 ELSE 0 END) AS HasBackup,
           MAX(CASE WHEN a.AssignmentType='REGIONAL' THEN 1 ELSE 0 END) AS HasRegional,
           MAX(CASE WHEN a.AssignmentType='MAIN'     THEN a.LocationCode END) AS MainCode
    FROM Employees e
    JOIN WicAgentAssignments a ON a.EmployeeName = e.FullName
         AND a.IsActive = 1 AND a.AssignmentType IN ('MAIN','BACKUP','REGIONAL')
    GROUP BY e.EmployeeId, e.FullName
)
SELECT s.Id, s.EmployeeId, w.FullName, CONVERT(varchar(10),s.ShiftDate,120) AS ShiftDate,
       DATENAME(weekday, s.ShiftDate) AS Dow,
       s.ShiftType, s.RawValue, ISNULL(s.AgentTask,'') AS AgentTask,
       ISNULL(s.ShiftStart,'') AS ShiftStart, ISNULL(s.ShiftEnd,'') AS ShiftEnd,
       s.IsWicDuty, s.AutoGenerated, ISNULL(s.SourceModule,'') AS SourceModule, ISNULL(s.SourceId,'') AS SourceId,
       ISNULL(s.ManualChangeBy,'') AS ManualChangeBy,
       ISNULL(CONVERT(varchar(23),s.ManualChangeAt,126),'') AS ManualChangeAt,
       ISNULL(s.ManualChangeNote,'') AS ManualChangeNote,
       w.HasMain, w.HasBackup, w.HasRegional, ISNULL(w.MainCode,'') AS MainCode,
       CASE WHEN EXISTS (SELECT 1 FROM WicShiftEntries x WHERE x.EmployeeId=s.EmployeeId AND x.ShiftDate=s.ShiftDate AND x.IsOnSite=1) THEN 1 ELSE 0 END AS HasOnSiteRow
FROM ShiftEntries s
JOIN wic w ON w.EmployeeId = s.EmployeeId
WHERE s.ShiftDate >= '2026-10-15' AND s.ShiftDate <= '2027-02-28'
  AND s.RawValue = 'BO'
ORDER BY s.EmployeeId, s.ShiftDate;
