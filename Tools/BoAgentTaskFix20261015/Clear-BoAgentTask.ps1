param(
    [string] $ConnectionString = "Server=localhost\SQLEXPRESS;Database=GSDDashboard;Integrated Security=true;TrustServerCertificate=yes;",
    [ValidateSet('DryRun','Apply')] [string] $Mode = 'DryRun',
    [string] $BackupRoot = 'C:\ProgramData\PulseRollback',
    [string] $BackupPrefix = 'bo-agenttask',
    [string] $FromDate = '2026-10-15',
    [int]    $ExpectedClearedCount = 0,
    [switch] $Apply
)
<#
    BO / LEFT-WIC AGENTTASK CLEAN-UP  (RTM 2026-10-15, requirement 3)

    WHAT
      ShiftEntries rows that are NOT WIC duty but still carry a WIC centre's name in
      AgentTask. AgentTask is the handle every signal-2 reader matches a centre against
      (AvailabilityResolver.IsWicDutyAt / WicPresenceResolver), so a WORKING or BO row that
      kept the name kept being listed as covering the centre after RTM had taken the agent
      off WIC duty (live case: 9129428, Pfaffenhofen, 16.-27.11.2026).

      The row set is exactly the rule's shape:
        ShiftDate >= FromDate
        AND ShiftType = 'WORKING'          -- the WORKING / BO day the task is about
        AND AgentTask names an ACTIVE WicLocation (exact DisplayName, as the readers match)
        AND no on-site WicShiftEntries row for that employee+date
          (an agent who really IS on site at the centre keeps the name: that is signal 1,
           and the WicDutyRecognition/Forecast on-site tests depend on it)

      Leave types (AL/SL/RESIGNED/OFF/...) with a stale name are deliberately NOT touched:
      they are not "WORKING/BO" rows, and substituting one of those days already relies on
      that field (SubstitutionModule reads AgentTask as the substitute's duty). They are
      reported as a separate count, never changed.

    WHAT IT WRITES
      AgentTask = NULL on exactly those rows. Nothing else is written:
      no ShiftType, no times, no IsWicDuty, and ManualChangeBy / ManualChangeAt /
      ManualChangeNote are never touched (they are the "a human decided this" marker and the
      task forbids rewriting them). The executing KID is never written into the row.

    SAFETY
      DryRun is the default and only SELECTs. Apply requires -ExpectedClearedCount to match
      the dry-run count, writes the backup FIRST (full rows + SHA256SUMS + rollback.sql),
      then ONE transaction with a per-row guard (the row must still be WORKING, still carry
      the same AgentTask, still have no on-site WIC row) and ROLLBACK on any mismatch.

    Generated by the 2026-10-15 WIC-duty task; NOT executed by the build.
#>
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Data
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
if ($Apply) { $Mode = 'Apply' }
$isDryRun = ($Mode -ne 'Apply')

$Inv = [System.Globalization.CultureInfo]::InvariantCulture
function Enc([string]$s) { if ($null -eq $s) { return 'NULL' } return "N'" + $s.Replace("'","''") + "'" }
function Sha([string]$p) { (Get-FileHash -LiteralPath $p -Algorithm SHA256).Hash }

$conn = New-Object System.Data.SqlClient.SqlConnection($ConnectionString)
$conn.Open()

function Invoke-Rows([string]$sql, $pars = $null, $tx = $null) {
    $cmd = $conn.CreateCommand(); $cmd.CommandText = $sql; $cmd.CommandTimeout = 900
    if ($tx) { $cmd.Transaction = $tx }
    if ($pars) { foreach ($pv in $pars.GetEnumerator()) { $pp = $cmd.CreateParameter(); $pp.ParameterName = $pv.Key; $pp.Value = $pv.Value; [void]$cmd.Parameters.Add($pp) } }
    $rdr = $cmd.ExecuteReader()
    $out = New-Object System.Collections.ArrayList
    while ($rdr.Read()) {
        $h = [ordered]@{}
        for ($i = 0; $i -lt $rdr.FieldCount; $i++) {
            $v = $rdr.GetValue($i); if ($v -is [System.DBNull]) { $v = $null }
            $h[$rdr.GetName($i)] = $v
        }
        [void]$out.Add([pscustomobject]$h)
    }
    $rdr.Close()
    return ,$out
}
function Invoke-NonQuery([string]$sql, $pars = $null, $tx = $null) {
    $cmd = $conn.CreateCommand(); $cmd.CommandText = $sql; $cmd.CommandTimeout = 900
    if ($tx) { $cmd.Transaction = $tx }
    if ($pars) { foreach ($pv in $pars.GetEnumerator()) { $pp = $cmd.CreateParameter(); $pp.ParameterName = $pv.Key; $pp.Value = $pv.Value; [void]$cmd.Parameters.Add($pp) } }
    return $cmd.ExecuteNonQuery()
}

# ---------------------------------------------------------------------------
# The row set (SELECT only in DryRun)
# ---------------------------------------------------------------------------
$where = @"
  s.ShiftDate >= @from
  AND s.ShiftType = 'WORKING'
  AND s.AgentTask IS NOT NULL AND s.AgentTask <> ''
  AND s.AgentTask IN (SELECT DisplayName FROM WicLocations WHERE IsActive = 1)
  AND NOT EXISTS (SELECT 1 FROM WicShiftEntries w
                  WHERE w.EmployeeId = s.EmployeeId AND w.ShiftDate = s.ShiftDate AND w.IsOnSite = 1)
"@

$rows = Invoke-Rows "SELECT s.* FROM ShiftEntries s WHERE $where ORDER BY s.EmployeeId, s.ShiftDate, s.Id" @{ '@from' = $FromDate }
$leaveRows = Invoke-Rows @"
SELECT s.Id, s.EmployeeId, s.ShiftType FROM ShiftEntries s
WHERE s.ShiftDate >= @from
  AND s.ShiftType NOT IN ('WORKING', 'WIC_DUTY')
  AND s.AgentTask IS NOT NULL AND s.AgentTask <> ''
  AND s.AgentTask IN (SELECT DisplayName FROM WicLocations WHERE IsActive = 1)
  AND NOT EXISTS (SELECT 1 FROM WicShiftEntries w
                  WHERE w.EmployeeId = s.EmployeeId AND w.ShiftDate = s.ShiftDate AND w.IsOnSite = 1)
ORDER BY s.EmployeeId, s.ShiftDate, s.Id
"@ @{ '@from' = $FromDate }

Write-Host ("MODE            : {0}" -f $Mode)
Write-Host ("from date       : {0}" -f $FromDate)
Write-Host ("rows to clear   : {0}" -f $rows.Count)
Write-Host ("leave rows with a stale centre name (NOT touched) : {0}" -f $leaveRows.Count)
if ($rows.Count) {
    $rows | Group-Object EmployeeId | ForEach-Object {
        Write-Host ("   employee {0}: {1} row(s)  {2} .. {3}" -f `
            $_.Name, $_.Count,
            (($_.Group | Select-Object -First 1).ShiftDate.ToString('yyyy-MM-dd')),
            (($_.Group | Select-Object -Last 1).ShiftDate.ToString('yyyy-MM-dd')))
    }
}

if ($isDryRun) {
    Write-Host ''
    Write-Host 'DRY RUN - nothing written.'
    $conn.Close()
    return
}

# ---------------------------------------------------------------------------
# APPLY
# ---------------------------------------------------------------------------
if ($ExpectedClearedCount -le 0) { throw 'APPLY REFUSED: pass -ExpectedClearedCount (the dry-run count of rows to clear).' }
if ($rows.Count -ne $ExpectedClearedCount) { throw ('APPLY REFUSED: {0} row(s) would be cleared, expected {1}. Re-run the dry run.' -f $rows.Count, $ExpectedClearedCount) }
if ($rows.Count -eq 0) { throw 'APPLY REFUSED: nothing to clear.' }

$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$root  = Join-Path $BackupRoot ("{0}-{1}" -f $BackupPrefix, $stamp)
New-Item -ItemType Directory -Force -Path $root | Out-Null
Write-Host ''
Write-Host "backup root     : $root"

# --- backup BEFORE any write -------------------------------------------------
$ids  = @($rows | ForEach-Object { [int]$_.Id })
$inIds = ($ids -join ',')
$backupRows = Invoke-Rows "SELECT * FROM ShiftEntries WHERE Id IN ($inIds) ORDER BY Id"
if ($backupRows.Count -ne $rows.Count) { throw ("BACKUP MISMATCH: read {0} rows, expected {1}" -f $backupRows.Count, $rows.Count) }
$backupRows | Export-Csv (Join-Path $root 'ShiftEntries-pre.csv') -NoTypeInformation -Encoding UTF8
$rows | Select-Object Id,EmployeeId,ShiftDate,ShiftType,RawValue,AgentTask,ManualChangeBy,ManualChangeAt,ManualChangeNote,SourceModule,SourceId,AutoGenerated |
    Export-Csv (Join-Path $root 'cleared-rows.csv') -NoTypeInformation -Encoding UTF8
$leaveRows | Export-Csv (Join-Path $root 'untouched-leave-rows.csv') -NoTypeInformation -Encoding UTF8

$hashLines = New-Object System.Collections.ArrayList
foreach ($f in @('ShiftEntries-pre.csv','cleared-rows.csv','untouched-leave-rows.csv')) {
    [void]$hashLines.Add("$(Sha (Join-Path $root $f))  $f")
}
($hashLines -join "`r`n") | Set-Content -Path (Join-Path $root 'SHA256SUMS.txt') -Encoding ASCII

# --- rollback.sql (from the backup, NOT executed here) -----------------------
# Restores AgentTask EXACTLY, and only while the row still holds the value this run
# cleared — so a later human edit can never be overwritten by the rollback.
$rb = New-Object System.Collections.ArrayList
[void]$rb.Add("-- ROLLBACK for $BackupPrefix-$stamp (generated $([DateTime]::Now.ToString('yyyy-MM-dd HH:mm:ss')))")
[void]$rb.Add("-- Restores ShiftEntries.AgentTask for the $($rows.Count) WORKING/BO rows this run cleared.")
[void]$rb.Add("-- Only AgentTask was changed. ManualChangeBy/At/Note were never touched by the fix.")
[void]$rb.Add("-- Guarded by Id AND the cleared state, so a later edit is never overwritten.")
[void]$rb.Add("SET XACT_ABORT ON;")
[void]$rb.Add("BEGIN TRAN;")
foreach ($b in $backupRows) {
    [void]$rb.Add("UPDATE ShiftEntries SET AgentTask=$(Enc $b.AgentTask) WHERE Id=$($b.Id) AND ShiftType='WORKING' AND AgentTask IS NULL;")
}
[void]$rb.Add("COMMIT;")
($rb -join "`r`n") | Set-Content -Path (Join-Path $root 'rollback.sql') -Encoding UTF8

# --- ONE transaction with a per-row guard -----------------------------------
$cleared = 0
$tx = $conn.BeginTransaction()
try {
    $guard = @{}
    $cmd = $conn.CreateCommand(); $cmd.Transaction = $tx
    $cmd.CommandText = "SELECT Id, EmployeeId, ShiftType, AgentTask FROM ShiftEntries WITH (UPDLOCK, HOLDLOCK) WHERE Id IN ($inIds)"
    $rdr = $cmd.ExecuteReader()
    while ($rdr.Read()) {
        $id = [int]$rdr.GetValue(0)
        $guard[$id] = [pscustomobject]@{
            EmployeeId = [string]$rdr.GetValue(1)
            ShiftType  = [string]$rdr.GetValue(2)
            AgentTask  = if ($rdr.IsDBNull(3)) { $null } else { [string]$rdr.GetValue(3) }
        }
    }
    $rdr.Close()

    foreach ($r in ($rows | Sort-Object Id)) {
        $cur = $guard[[int]$r.Id]
        if (-not $cur) { throw "Row $($r.Id) disappeared; transaction rolled back." }
        if ($cur.ShiftType -ne 'WORKING') { throw "Row $($r.Id) is no longer WORKING ('$($cur.ShiftType)'); transaction rolled back." }
        if ($cur.AgentTask -ne $r.AgentTask) { throw "Row $($r.Id) AgentTask changed ('$($cur.AgentTask)'); transaction rolled back." }

        $n = Invoke-NonQuery "UPDATE ShiftEntries SET AgentTask = NULL WHERE Id = @id AND ShiftType = 'WORKING' AND AgentTask = @task" @{ '@id' = [int]$r.Id; '@task' = [string]$r.AgentTask } $tx
        if ($n -ne 1) { throw "ShiftEntries Id=$($r.Id) update affected $n row(s)" }
        $cleared++
    }

    # Post-write verification INSIDE the transaction.
    $after = Invoke-Rows "SELECT Id, EmployeeId, ShiftDate, ShiftType, AgentTask, ManualChangeBy, ManualChangeNote FROM ShiftEntries WHERE Id IN ($inIds)" $null $tx
    $bad = @($after | Where-Object { $null -ne $_.AgentTask })
    if ($bad.Count -gt 0) { throw "POST-WRITE VERIFY FAILED on $($bad.Count) row(s); first Id=$($bad[0].Id)" }

    $tx.Commit()
} catch {
    $tx.Rollback()
    Write-Host "APPLY FAILED - transaction ROLLED BACK: $($_.Exception.Message)"
    throw
}

# --- report ------------------------------------------------------------------
$remaining = Invoke-Rows "SELECT COUNT(*) AS n FROM ShiftEntries s WHERE $where" @{ '@from' = $FromDate }
$report = New-Object System.Collections.ArrayList
$P = { param($s) [void]$report.Add($s) }
& $P "BO / LEFT-WIC AGENTTASK CLEAN-UP - APPLIED"
& $P "generated        : $([DateTime]::Now.ToString('yyyy-MM-dd HH:mm:ss'))"
& $P "backup root      : $root"
& $P "row filter       : ShiftDate >= $FromDate AND ShiftType='WORKING' AND AgentTask = active WIC DisplayName AND no on-site WicShiftEntries row"
& $P "transaction      : single; per-row guard; committed once"
& $P ""
& $P "ROWS CLEARED     : $cleared"
& $P "REMAINING        : $($remaining[0].n)"
& $P "UNTOUCHED leave rows with a stale centre name : $($leaveRows.Count)"
& $P "UNTOUCHED columns: ShiftType, times, IsWicDuty, ManualChangeBy, ManualChangeAt, ManualChangeNote, SourceModule"
& $P ""
& $P "BACKUP FILES     : ShiftEntries-pre.csv, cleared-rows.csv, untouched-leave-rows.csv, SHA256SUMS.txt, rollback.sql"
& $P ""
& $P "SHA256"
foreach ($l in $hashLines) { & $P "   $l" }
($report -join "`r`n") | Set-Content -Path (Join-Path $root 'REPORT.txt') -Encoding UTF8
$report | ForEach-Object { Write-Host $_ }

$conn.Close()
Write-Host ''
Write-Host "APPLIED: cleared $cleared row(s). Backup: $root"
