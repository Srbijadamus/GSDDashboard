param(
    [string] $ConnectionString = "Server=localhost\SQLEXPRESS;Database=GSDDashboard;Integrated Security=true;TrustServerCertificate=yes;",
    [ValidateSet('DryRun','Apply')] [string] $Mode = 'DryRun',
    [string] $BackupRoot = 'C:\ProgramData\PulseRollback',
    [string] $BackupPrefix = 'agenttask-restore',
    [string] $ClearedCsv = 'C:\ProgramData\PulseRollback\bo-agenttask-20261015-164944\cleared-rows.csv',
    [int]    $ExpectedRestoredCount = 19,
    [switch] $Apply
)
<#
    RESTORE ShiftEntries.AgentTask for the 19 rows the 2026-10-15 bo-agenttask run cleared
    that are NOT employee 9129428 (Pfaffenhofen stays cleared: RTM moved that one to BO).

    WHY
      Those 19 rows are the trace of a TEMPORARY move (another WIC centre, or BO/GSD) that
      ends with the agent returning to his home centre. The clean-up treated them as stale
      phantom cover and nulled the centre name; the trace must come back.

    WHAT IT WRITES
      Only ShiftEntries.AgentTask, set back to exactly the value in cleared-rows.csv.
      Nothing else: no ShiftType, no times, no IsWicDuty, no ManualChangeBy/At/Note.

    SAFETY
      DryRun (default) only SELECTs. Apply requires -ExpectedRestoredCount, writes the backup
      of the CURRENT rows FIRST (full rows + SHA256SUMS + rollback.sql), then ONE transaction
      with a per-row guard (still WORKING, AgentTask still NULL, same employee+date) and
      ROLLBACK on any mismatch. The 10 rows of employee 9129428 are never in the set.
#>
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Data
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
if ($Apply) { $Mode = 'Apply' }
$isDryRun = ($Mode -ne 'Apply')

function Enc([string]$s) { if ($null -eq $s) { return 'NULL' } return "N'" + $s.Replace("'","''") + "'" }
function Sha([string]$p) { (Get-FileHash -LiteralPath $p -Algorithm SHA256).Hash }

# ---- the target set: cleared-rows.csv without employee 9129428 --------------------------
$csv = Import-Csv -LiteralPath $ClearedCsv
$targets = @($csv | Where-Object { $_.EmployeeId -ne '9129428' })
if ($targets.Count -ne $ExpectedRestoredCount) {
    throw ("TARGET MISMATCH: cleared-rows.csv without 9129428 has {0} rows, expected {1}." -f $targets.Count, $ExpectedRestoredCount)
}
if (@($csv | Where-Object { $_.EmployeeId -eq '9129428' }).Count -ne 10) {
    throw 'EXPECTED the 10 Pfaffenhofen rows of 9129428 to remain in cleared-rows.csv (and stay cleared).'
}
foreach ($t in $targets) {
    $t | Add-Member -NotePropertyName TargetDate -NotePropertyValue ([datetime]::ParseExact($t.ShiftDate.Substring(0,10), 'dd.MM.yyyy', $null).ToString('yyyy-MM-dd')) -Force
}

$conn = New-Object System.Data.SqlClient.SqlConnection($ConnectionString)
$conn.Open()
function Invoke-Rows([string]$sql, $pars = $null, $tx = $null) {
    $cmd = $conn.CreateCommand(); $cmd.CommandText = $sql; $cmd.CommandTimeout = 900
    if ($tx) { $cmd.Transaction = $tx }
    if ($pars) { foreach ($pv in $pars.GetEnumerator()) { $pp = $cmd.CreateParameter(); $pp.ParameterName = $pv.Key; $pp.Value = $pv.Value; [void]$cmd.Parameters.Add($pp) } }
    $rdr = $cmd.ExecuteReader()
    $out = New-Object System.Collections.ArrayList
    while ($rdr.Read()) {
        $h = [ordered]@{}
        for ($i = 0; $i -lt $rdr.FieldCount; $i++) { $v = $rdr.GetValue($i); if ($v -is [System.DBNull]) { $v = $null }; $h[$rdr.GetName($i)] = $v }
        [void]$out.Add([pscustomobject]$h)
    }
    $rdr.Close()
    return ,$out
}
function Invoke-NonQuery([string]$sql, $pars = $null, $tx = $null) {
    $cmd = $conn.CreateCommand(); $cmd.CommandText = $sql; $cmd.CommandTimeout = 900
    if ($tx) { $cmd.Transaction = $tx }
    if ($pars) { foreach ($pv in $pars.GetEnumerator()) { $pp = $cmd.CreateParameter(); $pp.ParameterName = $pv.Key; $pp.Value = $pv.Value; [void]$cmd.Parameters.Add($pp) } }
    return $cmd.ExecuteNonQuery()
}

$ids = @($targets | ForEach-Object { [int]$_.Id } | Sort-Object)
$inIds = ($ids -join ',')

Write-Host ("MODE              : {0}" -f $Mode)
Write-Host ("source            : {0}" -f $ClearedCsv)
Write-Host ("rows to restore   : {0}" -f $targets.Count)
$targets | Group-Object EmployeeId | Sort-Object Name | ForEach-Object {
    Write-Host ("   employee {0}: {1} row(s)  {2} .. {3}" -f $_.Name, $_.Count,
        (($_.Group | Sort-Object TargetDate | Select-Object -First 1).TargetDate),
        (($_.Group | Sort-Object TargetDate | Select-Object -Last 1).TargetDate))
}

# ---- current state (SELECT only) --------------------------------------------------------
$current = Invoke-Rows "SELECT Id, EmployeeId, ShiftDate, ShiftType, RawValue, AgentTask, IsWicDuty, ShiftStart, ShiftEnd, ManualChangeBy, ManualChangeAt, ManualChangeNote, SourceModule, SourceId, AutoGenerated FROM ShiftEntries WHERE Id IN ($inIds) ORDER BY Id"
if ($current.Count -ne $targets.Count) { throw ("STATE MISMATCH: found {0} of {1} rows" -f $current.Count, $targets.Count) }

$problems = New-Object System.Collections.ArrayList
foreach ($t in $targets) {
    $cur = @($current | Where-Object { $_.Id -eq [int]$t.Id })[0]
    if (-not $cur) { [void]$problems.Add("Id $($t.Id): row missing"); continue }
    if ($cur.ShiftType -ne 'WORKING') { [void]$problems.Add("Id $($t.Id): ShiftType is '$($cur.ShiftType)', expected WORKING") }
    if ($null -ne $cur.AgentTask) { [void]$problems.Add("Id $($t.Id): AgentTask is '$($cur.AgentTask)', expected NULL") }
    if ($cur.EmployeeId -ne $t.EmployeeId) { [void]$problems.Add("Id $($t.Id): EmployeeId '$($cur.EmployeeId)' <> '$($t.EmployeeId)'") }
    if ($cur.ShiftDate.ToString('yyyy-MM-dd') -ne $t.TargetDate) { [void]$problems.Add("Id $($t.Id): ShiftDate '$($cur.ShiftDate)' <> '$($t.TargetDate)'") }
}
if ($problems.Count) {
    $problems | ForEach-Object { Write-Host "PROBLEM: $_" }
    throw 'PRE-CHECK FAILED: the live rows are not in the expected cleared state. Nothing written.'
}
Write-Host 'pre-check         : all 19 rows are WORKING with AgentTask NULL and matching identity'

if ($isDryRun) {
    Write-Host ''
    Write-Host 'DRY RUN - nothing written.'
    $conn.Close()
    return
}

# ---- APPLY ------------------------------------------------------------------------------
if ($ExpectedRestoredCount -le 0) { throw 'APPLY REFUSED: pass -ExpectedRestoredCount.' }
if ($targets.Count -ne $ExpectedRestoredCount) { throw 'APPLY REFUSED: count mismatch.' }

$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$root  = Join-Path $BackupRoot ("{0}-{1}" -f $BackupPrefix, $stamp)
New-Item -ItemType Directory -Force -Path $root | Out-Null
Write-Host ''
Write-Host "backup root       : $root"

# backup BEFORE any write
$current | Export-Csv (Join-Path $root 'ShiftEntries-pre.csv') -NoTypeInformation -Encoding UTF8
$targets | Select-Object Id,EmployeeId,ShiftDate,ShiftType,RawValue,AgentTask,ManualChangeBy,ManualChangeAt,ManualChangeNote,SourceModule,SourceId,AutoGenerated,TargetDate |
    Export-Csv (Join-Path $root 'restored-rows.csv') -NoTypeInformation -Encoding UTF8

$hashLines = New-Object System.Collections.ArrayList
foreach ($f in @('ShiftEntries-pre.csv','restored-rows.csv')) {
    [void]$hashLines.Add("$(Sha (Join-Path $root $f))  $f")
}

# rollback.sql: put AgentTask back to NULL, only while the row still holds exactly the value
# this run wrote, so a later human edit can never be overwritten.
$rb = New-Object System.Collections.ArrayList
[void]$rb.Add("-- ROLLBACK for $BackupPrefix-$stamp (generated $([DateTime]::Now.ToString('yyyy-MM-dd HH:mm:ss')))")
[void]$rb.Add("-- Re-clears AgentTask for the $($targets.Count) WORKING rows this run restored.")
[void]$rb.Add("-- Guarded by Id AND the restored value, so a later edit is never overwritten.")
[void]$rb.Add("SET XACT_ABORT ON;")
[void]$rb.Add("BEGIN TRAN;")
foreach ($t in ($targets | Sort-Object { [int]$_.Id })) {
    [void]$rb.Add("UPDATE ShiftEntries SET AgentTask=NULL WHERE Id=$($t.Id) AND ShiftType='WORKING' AND AgentTask=$(Enc $t.AgentTask);")
}
[void]$rb.Add("COMMIT;")
($rb -join "`r`n") | Set-Content -Path (Join-Path $root 'rollback.sql') -Encoding UTF8
[void]$hashLines.Add("$(Sha (Join-Path $root 'rollback.sql'))  rollback.sql")
($hashLines -join "`r`n") | Set-Content -Path (Join-Path $root 'SHA256SUMS.txt') -Encoding ASCII

# ONE transaction with a per-row guard
$restored = 0
$tx = $conn.BeginTransaction()
try {
    $guard = @{}
    $cmd = $conn.CreateCommand(); $cmd.Transaction = $tx
    $cmd.CommandText = "SELECT Id, EmployeeId, ShiftDate, ShiftType, AgentTask FROM ShiftEntries WITH (UPDLOCK, HOLDLOCK) WHERE Id IN ($inIds)"
    $rdr = $cmd.ExecuteReader()
    while ($rdr.Read()) {
        $gid = [int]$rdr.GetValue(0)
        $guard[$gid] = [pscustomobject]@{
            EmployeeId = [string]$rdr.GetValue(1)
            ShiftDate  = ([datetime]$rdr.GetValue(2)).ToString('yyyy-MM-dd')
            ShiftType  = [string]$rdr.GetValue(3)
            AgentTask  = if ($rdr.IsDBNull(4)) { $null } else { [string]$rdr.GetValue(4) }
        }
    }
    $rdr.Close()

    foreach ($t in ($targets | Sort-Object { [int]$_.Id })) {
        $cur = $guard[[int]$t.Id]
        if (-not $cur) { throw "Row $($t.Id) disappeared; transaction rolled back." }
        if ($cur.ShiftType -ne 'WORKING') { throw "Row $($t.Id) is no longer WORKING ('$($cur.ShiftType)'); transaction rolled back." }
        if ($null -ne $cur.AgentTask) { throw "Row $($t.Id) AgentTask is no longer NULL ('$($cur.AgentTask)'); transaction rolled back." }
        if ($cur.EmployeeId -ne $t.EmployeeId -or $cur.ShiftDate -ne $t.TargetDate) { throw "Row $($t.Id) identity changed; transaction rolled back." }

        $n = Invoke-NonQuery "UPDATE ShiftEntries SET AgentTask = @task WHERE Id = @id AND ShiftType = 'WORKING' AND AgentTask IS NULL" @{ '@id' = [int]$t.Id; '@task' = [string]$t.AgentTask } $tx
        if ($n -ne 1) { throw "ShiftEntries Id=$($t.Id) update affected $n row(s)" }
        $restored++
    }

    # post-write verification INSIDE the transaction
    $after = Invoke-Rows "SELECT Id, AgentTask, ManualChangeBy, ManualChangeNote FROM ShiftEntries WHERE Id IN ($inIds)" $null $tx
    foreach ($t in $targets) {
        $a = @($after | Where-Object { $_.Id -eq [int]$t.Id })[0]
        if ($a.AgentTask -ne $t.AgentTask) { throw "POST-WRITE VERIFY FAILED Id=$($t.Id) AgentTask='$($a.AgentTask)' expected '$($t.AgentTask)'" }
    }
    $stillNull = @($after | Where-Object { $null -eq $_.AgentTask })
    if ($stillNull.Count) { throw "POST-WRITE VERIFY FAILED: $($stillNull.Count) row(s) still NULL" }

    $tx.Commit()
} catch {
    $tx.Rollback()
    Write-Host "APPLY FAILED - transaction ROLLED BACK: $($_.Exception.Message)"
    throw
}

# report
$report = New-Object System.Collections.ArrayList
$P = { param($s) [void]$report.Add($s) }
& $P "AGENTTASK RESTORE (temporary-move traces) - APPLIED"
& $P "generated        : $([DateTime]::Now.ToString('yyyy-MM-dd HH:mm:ss'))"
& $P "backup root      : $root"
& $P "source           : $ClearedCsv"
& $P "row filter       : cleared-rows.csv without employee 9129428 (kept cleared: RTM moved to BO)"
& $P "transaction      : single; per-row guard (WORKING + AgentTask IS NULL + identity); committed once"
& $P ""
& $P "ROWS RESTORED    : $restored"
& $P "UNTOUCHED columns: ShiftType, RawValue, times, IsWicDuty, ManualChangeBy/At/Note, SourceModule"
& $P "KEPT CLEARED     : 9129428 (10 rows, Pfaffenhofen 16.-27.11.2026)"
& $P ""
& $P "BACKUP FILES     : ShiftEntries-pre.csv, restored-rows.csv, rollback.sql, SHA256SUMS.txt"
& $P ""
& $P "SHA256"
foreach ($l in $hashLines) { & $P "   $l" }
($report -join "`r`n") | Set-Content -Path (Join-Path $root 'REPORT.txt') -Encoding UTF8
$report | ForEach-Object { Write-Host $_ }

$conn.Close()
Write-Host ''
Write-Host "APPLIED: restored AgentTask on $restored row(s). Backup: $root"
$root | Set-Content -LiteralPath 'C:\GSDDashboard_secure\Tools\AgentTaskRestore20261015\backup-root.txt' -Encoding UTF8
