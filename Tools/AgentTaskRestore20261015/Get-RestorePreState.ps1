param(
    [string] $ConnectionString = "Server=localhost\SQLEXPRESS;Database=GSDDashboard;Integrated Security=true;TrustServerCertificate=yes;",
    [string] $OutFile = 'C:\GSDDashboard_secure\Tools\AgentTaskRestore20261015\pre-state.json'
)
# READ-ONLY. Reads the current live state of the 19 ShiftEntries rows whose AgentTask the
# 2026-10-15 bo-agenttask run cleared, plus the WicShiftEntries rows of the same
# employee+date and the active WIC centre names. Nothing is written.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Data
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8

# Ids to restore = cleared-rows.csv minus the 10 rows of employee 9129428 (Pfaffenhofen).
$ids = @(57009,57098,57105,57195,57285,57312,57376,57403,57461,57468,57495,57553,
         57560,57587,57653,57680,57736,57746,57838)
$inIds = ($ids -join ',')

$conn = New-Object System.Data.SqlClient.SqlConnection($ConnectionString)
$conn.Open()
function Rows([string]$sql) {
    $cmd = $conn.CreateCommand(); $cmd.CommandText = $sql; $cmd.CommandTimeout = 300
    $rdr = $cmd.ExecuteReader()
    $out = New-Object System.Collections.ArrayList
    while ($rdr.Read()) {
        $h = [ordered]@{}
        for ($i = 0; $i -lt $rdr.FieldCount; $i++) {
            $v = $rdr.GetValue($i); if ($v -is [System.DBNull]) { $v = $null }
            $h[$rdr.GetName($i)] = $v
        }
        [void]$out.Add([pscustomobject]$h)
    }
    $rdr.Close()
    return ,$out
}

$rows = Rows "SELECT Id, EmployeeId, ShiftDate, ShiftType, RawValue, AgentTask, IsWicDuty, ShiftStart, ShiftEnd, ManualChangeBy, ManualChangeAt, ManualChangeNote, SourceModule, SourceId, AutoGenerated FROM ShiftEntries WHERE Id IN ($inIds) ORDER BY EmployeeId, ShiftDate, Id"
$wic  = Rows "SELECT w.Id, w.EmployeeId, w.ShiftDate, w.SupportLocation, w.LocationCode, w.IsOnSite, w.WorkingShift, w.Task FROM WicShiftEntries w WHERE EXISTS (SELECT 1 FROM ShiftEntries s WHERE s.Id IN ($inIds) AND s.EmployeeId = w.EmployeeId AND s.ShiftDate = w.ShiftDate) ORDER BY w.EmployeeId, w.ShiftDate"
$locs = Rows "SELECT LocationCode, DisplayName, City, IsActive FROM WicLocations WHERE IsActive = 1 ORDER BY DisplayName"

$result = [pscustomobject]@{
    when = (Get-Date).ToString('o')
    rows = $rows
    wicRows = $wic
    activeCentres = $locs
}
$result | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $OutFile -Encoding UTF8
$rows | Format-Table Id,EmployeeId,ShiftDate,ShiftType,RawValue,AgentTask,IsWicDuty,ShiftStart,ShiftEnd,ManualChangeBy,SourceModule -AutoSize | Out-String -Width 250 | Write-Output
'--- WicShiftEntries (same employee+date) ---'
$wic | Format-Table Id,EmployeeId,ShiftDate,SupportLocation,IsOnSite,WorkingShift,Task -AutoSize | Out-String -Width 200 | Write-Output
"receipt: $OutFile"
$conn.Close()
