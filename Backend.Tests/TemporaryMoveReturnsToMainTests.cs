using GSDDashboard.API.Data;
using GSDDashboard.API.Data.Models;
using GSDDashboard.API.Modules.Roster;
using GSDDashboard.API.Modules.Shifts;
using GSDDashboard.API.Modules.WicShifts;
using GSDDashboard.API.Services;
using Microsoft.AspNetCore.Http;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using Xunit;

namespace GSDDashboard.Tests;

// Scenario: the primary agent's MAIN WIC assignment is Centre A. RTM sends him to
// Centre B for two weeks (2026-10-14 .. 2026-10-27) with the Shift Plan / Assign
// Agent action (POST /api/wic/assignments, the call AssignAgentModal.tsx loops over).
//
// What the code actually does, pinned here:
//   * the manual action writes ONLY the selected dates (ShiftEntries + the matching
//     WicShiftEntries row — replacing an AUTOMATIC same-day commitment at Centre A);
//   * it never creates, moves or deactivates the MAIN WicAgentAssignments row
//     (no code path in the manual move touches WicAgentAssignments at all);
//   * rows that already exist AFTER the period are left byte-identical — nothing is
//     deleted or rewritten beyond the selected dates;
//   * therefore the generator puts the agent back at Centre A for 2026-10-28 and
//     later without any extra RTM centre choice: the next roster run with no
//     LocationCode auto-detects MAIN = Centre A (RosterService.ValidateAsync,
//     the permanent WIC-priority rule) and creates Centre A WIC duty.
public class TemporaryMoveReturnsToMainTests
{
    private const string Emp    = "E-TEMP";
    private const string Actor  = "RTM-KID";
    private const string Name   = "Temporary Agent";

    private static readonly DateOnly PeriodStart    = new(2026, 10, 14); // Wednesday
    private static readonly DateOnly PeriodEnd      = new(2026, 10, 27); // Tuesday
    private static readonly DateOnly FirstDayAfter  = new(2026, 10, 28); // Wednesday
    private static readonly DateOnly SecondDayAfter = new(2026, 10, 29); // Thursday

    // The roster generator opens a transaction; the in-memory provider ignores it with
    // a warning. Ignore that one warning, the same way ManualShiftProtectionTests does.
    private static GSDContext NewDb() =>
        new(new DbContextOptionsBuilder<GSDContext>()
            .UseInMemoryDatabase(Guid.NewGuid().ToString())
            .ConfigureWarnings(w => w.Ignore(InMemoryEventId.TransactionIgnoredWarning))
            .Options);

    private static WicShiftService WicSvc(GSDContext db) => new(db, new AvailabilityResolver(db));

    private static RosterService RosterSvc(GSDContext db) =>
        new(db, new WicShiftService(db, new AvailabilityResolver(db)), new WicCoverageGapService(db));

    private static object Value(IResult r) => ((IValueHttpResult)r).Value!;
    private static bool Bool(object v, string p) => (bool)(v.GetType().GetProperty(p)?.GetValue(v) ?? false);

    private static void Seed(GSDContext db)
    {
        db.Employees.Add(new Employee { EmployeeId = Emp, FullName = Name, IsActive = true });

        db.WicLocations.Add(new WicLocation { LocationCode = "A", DisplayName = "Centre A", IsActive = true });
        db.WicLocations.Add(new WicLocation { LocationCode = "B", DisplayName = "Centre B", IsActive = true });
        // Both centres open every weekday, so every date in the scenario is a valid WIC day.
        for (var dow = 1; dow <= 5; dow++)
        {
            db.WicOpeningHours.Add(new WicOpeningHour
            { LocationCode = "A", DayOfWeek = dow, OpenTime = "08:00", CloseTime = "17:00", IsClosed = false });
            db.WicOpeningHours.Add(new WicOpeningHour
            { LocationCode = "B", DayOfWeek = dow, OpenTime = "08:00", CloseTime = "17:00", IsClosed = false });
        }

        // The agent's permanent MAIN assignment: Centre A. This is the only MAIN row.
        db.WicAgentAssignments.Add(new WicAgentAssignment
        { LocationCode = "A", EmployeeName = Name, AssignmentType = "MAIN", IsActive = true });

        // The first day of the move already carries the automatic Centre A commitment
        // a normal rostered day has, so the test can prove the manual move replaces it
        // in the same write (Assign Agent, WicShiftService.CreateAssignmentAsync).
        db.ShiftEntries.Add(new ShiftEntry
        {
            EmployeeId = Emp, ShiftDate = PeriodStart, ShiftType = ShiftTypes.WicDuty,
            IsWicDuty = true, AgentTask = "Centre A", ShiftStart = "08:00", ShiftEnd = "17:00",
            AutoGenerated = true, SourceModule = "Roster",
        });
        db.WicShiftEntries.Add(new WicShiftEntry
        {
            EmployeeId = Emp, ShiftDate = PeriodStart, SupportLocation = "Centre A", LocationCode = "A",
            WorkingShift = "08:00-17:00", IsOnSite = true, Task = "WIC",
        });

        // Rows AFTER the temporary period: one generated WIC_DUTY row at Centre A and
        // one plain PATTERN_FILL WORKING row. They must survive the manual move untouched.
        db.ShiftEntries.Add(new ShiftEntry
        {
            EmployeeId = Emp, ShiftDate = FirstDayAfter, ShiftType = ShiftTypes.WicDuty,
            IsWicDuty = true, AgentTask = "Centre A", ShiftStart = "08:00", ShiftEnd = "17:00",
            AutoGenerated = true, SourceModule = "Roster",
        });
        db.WicShiftEntries.Add(new WicShiftEntry
        {
            EmployeeId = Emp, ShiftDate = FirstDayAfter, SupportLocation = "Centre A", LocationCode = "A",
            WorkingShift = "08:00-17:00", IsOnSite = true, Task = "WIC",
        });
        db.ShiftEntries.Add(new ShiftEntry
        {
            EmployeeId = Emp, ShiftDate = SecondDayAfter, ShiftType = ShiftTypes.Working,
            RawValue = "08:00 - 16:30", SourceModule = "PATTERN_FILL", AutoGenerated = true,
        });
    }

    private static Task<List<ShiftEntry>> AfterPeriodRowsAsync(GSDContext db) =>
        db.ShiftEntries
            .Where(s => s.EmployeeId == Emp && s.ShiftDate > PeriodEnd)
            .OrderBy(s => s.ShiftDate)
            .ToListAsync();

    [Fact]
    public async Task TemporaryMove_ReturnsToMainAfterPeriod()
    {
        using var db = NewDb();
        Seed(db);
        await db.SaveChangesAsync();

        // Snapshot every day after the period BEFORE anything moves.
        var afterBefore = (await AfterPeriodRowsAsync(db))
            .Select(s => new { s.ShiftDate, s.ShiftType, s.AgentTask, s.SourceModule, s.RawValue, s.ManualChangeBy })
            .ToList();

        // ── 1. The RTM's manual "Assign Agent" for Centre B, one call per weekday in
        //       the range — exactly what AssignAgentModal.tsx loops over. ───────────
        var assigned = new List<DateOnly>();
        for (var d = PeriodStart; d <= PeriodEnd; d = d.AddDays(1))
        {
            if (d.DayOfWeek is DayOfWeek.Saturday or DayOfWeek.Sunday) continue;
            var res = await WicSvc(db).CreateAssignmentAsync(
                new CreateAssignmentRequest(Emp, "B", d.ToString("yyyy-MM-dd"), "08:00", "17:00"),
                db, manualActor: Actor);
            Assert.True(Bool(Value(res), "saved"), $"Assign Agent saved nothing for {d:yyyy-MM-dd}");
            assigned.Add(d);
        }
        Assert.Equal(10, assigned.Count); // 14-16, 19-23, 26-27 October 2026

        foreach (var d in assigned)
        {
            // Q1: every SELECTED day is a Centre B commitment, owned by the human.
            var shift = Assert.Single(await db.ShiftEntries
                .Where(s => s.EmployeeId == Emp && s.ShiftDate == d).ToListAsync());
            Assert.Equal(ShiftTypes.WicDuty, shift.ShiftType);
            Assert.Equal("Centre B", shift.AgentTask);
            Assert.Equal(Actor, shift.ManualChangeBy);

            // On 14.10 the automatic Centre A row was superseded; on the other days
            // this is the only on-site WIC row. Never two centres at once.
            var wic = Assert.Single(await db.WicShiftEntries
                .Where(w => w.EmployeeId == Emp && w.ShiftDate == d).ToListAsync());
            Assert.Equal("Centre B", wic.SupportLocation);
            Assert.True(wic.IsOnSite);
        }

        // Q1 + Q3: the manual action changed NO WicAgentAssignments row — still exactly
        // one row, still MAIN, still Centre A. No MAIN was created for Centre B.
        var assignments = await db.WicAgentAssignments.ToListAsync();
        var main = Assert.Single(assignments);
        Assert.Equal("A", main.LocationCode);
        Assert.Equal("MAIN", main.AssignmentType);
        Assert.True(main.IsActive);
        Assert.DoesNotContain(assignments, a => a.LocationCode == "B");

        // Q4: rows AFTER 27.10 are untouched — the move is confined to the selected
        // dates and deletes/rewrites nothing beyond them.
        var afterPostMove = (await AfterPeriodRowsAsync(db))
            .Select(s => new { s.ShiftDate, s.ShiftType, s.AgentTask, s.SourceModule, s.RawValue, s.ManualChangeBy })
            .ToList();
        Assert.Equal(afterBefore, afterPostMove);
        Assert.Equal(2, afterPostMove.Count);
        Assert.Contains(afterPostMove, r => r.SourceModule == "PATTERN_FILL"
            && r.ShiftType == ShiftTypes.Working && r.RawValue == "08:00 - 16:30");

        // ── 2. The next generator run after the period, with NO location argument
        //       (the RTM only picks agent + range): the permanent WIC-priority rule
        //       auto-detects MAIN = Centre A, so the agent is back at Centre A. ────
        var generated = await RosterSvc(db).GenerateAsync(
            new RosterRequest(Emp, "2026-10-28", "2026-11-03", "08:00", "17:00", null, null),
            "K1", "Tester");

        Assert.False(generated.AssignmentCreated);  // MAIN already existed -> nothing new created
        Assert.Single(await db.WicAgentAssignments.ToListAsync());
        Assert.Equal(2, generated.SkippedExisting); // 28.10 + 29.10 kept their pre-existing rows
        Assert.Equal(3, generated.Created);         // 30.10, 2.11, 3.11
        Assert.Equal(3, generated.WicDays);
        Assert.Equal(0, generated.BoDays);

        foreach (var d in new[] { "2026-10-30", "2026-11-02", "2026-11-03" })
        {
            var date = DateOnly.Parse(d);
            var shift = await db.ShiftEntries.SingleAsync(s => s.EmployeeId == Emp && s.ShiftDate == date);
            Assert.Equal(ShiftTypes.WicDuty, shift.ShiftType);
            Assert.Equal("Centre A", shift.AgentTask);
            var wic = await db.WicShiftEntries.SingleAsync(w => w.EmployeeId == Emp && w.ShiftDate == date);
            Assert.Equal("Centre A", wic.SupportLocation);
            Assert.True(wic.IsOnSite);
        }

        // The pre-existing after-period rows were not overwritten either...
        var kept28 = await db.ShiftEntries.SingleAsync(s => s.EmployeeId == Emp && s.ShiftDate == FirstDayAfter);
        Assert.Equal(ShiftTypes.WicDuty, kept28.ShiftType);
        Assert.Equal("Centre A", kept28.AgentTask);
        Assert.Equal("Roster", kept28.SourceModule);
        Assert.Null(kept28.ManualChangeBy);

        var kept29 = await db.ShiftEntries.SingleAsync(s => s.EmployeeId == Emp && s.ShiftDate == SecondDayAfter);
        Assert.Equal(ShiftTypes.Working, kept29.ShiftType);
        Assert.Equal("PATTERN_FILL", kept29.SourceModule);
        Assert.Equal("08:00 - 16:30", kept29.RawValue);
        Assert.Null(kept29.ManualChangeBy);

        // ...and MAIN is still the single Centre A row.
        var onlyMain = await db.WicAgentAssignments.SingleAsync();
        Assert.Equal("A", onlyMain.LocationCode);
        Assert.Equal("MAIN", onlyMain.AssignmentType);
    }
}
