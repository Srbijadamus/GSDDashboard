    // ── 5. The two readings agree: /api/wic/open and /api/wic/cards ─────────────────────

    [Fact]
    public async Task OpenAndCards_ReportTheSameStatus_ForAGeneratedWicDutyDay()
    {
        using var db = NewDb();
        SeedAgent(db);
        SeedCentre(db);
        await db.SaveChangesAsync();

        await NewRoster(db).GenerateAsync(WicRequest(Mon, Mon), "K1", "Tester");

        // /api/wic/open — SIGNAL 1, the on-site WicShiftEntries rows.
        var open = await new WicShiftService(db, new AvailabilityResolver(db))
            .GetOpenAsync(Mon.ToString("yyyy-MM-dd"), 1);
        var day = Assert.Single(open);
        var status = day.Locations.Single(l => l.LocationCode == CentreA);
        Assert.True(status.IsOpen);
        Assert.Equal("COVERED", status.CoverageStatus);
        Assert.Equal(1, status.ScheduledCount);
        Assert.Equal(1, status.EffectiveCoverage);

        // /api/wic/cards — the ShiftEntries reading.
        var card = Assert.Single(await new WicCardsService(db).GetCardsAsync(Mon, "DE"));
        Assert.Equal("COVERED", card.CoverageStatus);
        Assert.Contains(card.AssignedAgents, a => a.EmployeeId == "E1");
    }

    [Fact]
    public async Task OpenAndCards_ReportTheSameStatus_ForTheOverwriteCase()
    {
        using var db = NewDb();
        SeedAgent(db);
        SeedCentre(db);
        db.ShiftEntries.Add(WicDuty(Mon, CentreAName, "08:00", "12:00"));
        await db.SaveChangesAsync();

        await NewRoster(db).GenerateAsync(WicRequest(Mon, Mon), "K1", "Tester");

        var open = await new WicShiftService(db, new AvailabilityResolver(db))
            .GetOpenAsync(Mon.ToString("yyyy-MM-dd"), 1);
        var status = Assert.Single(open).Locations.Single(l => l.LocationCode == CentreA);
        Assert.Equal("COVERED", status.CoverageStatus);

        var card = Assert.Single(await new WicCardsService(db).GetCardsAsync(Mon, "DE"));
        Assert.Equal("COVERED", card.CoverageStatus);
    }
}
