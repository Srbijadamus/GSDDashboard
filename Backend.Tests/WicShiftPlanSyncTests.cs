namespace GSDDashboard.Tests;

// RTM 2026-10-15, follow-up: A WIC_DUTY ShiftEntries ROW MUST HAVE ITS ON-SITE
// WicShiftEntries ROW — the Shift Plan -> WIC sync.
//
// The live defect this pins down (Wesel, 9074345, 2026-11-05/12/19/26, RosterBatch 265):
// the roster generator's OVERWRITE path removed the day's WicShiftEntries rows and then
// found the still-tracked, DELETED entity, updated its fields and let SaveChanges delete
// it. The ShiftEntries row stayed WIC_DUTY, so /api/wic/cards read the day as COVERED while
// /api/wic/open (SIGNAL 1, on-site rows only) read it as UNCOVERED.
//
// No real employee names or centre names are used here.
public class WicShiftPlanSyncTests
{
    // 2026-10-05 is a Monday.
    private static readonly DateOnly Mon = new(2026, 10, 5);
    private static readonly DateOnly Tue = new(2026, 10, 6);

    private const string CentreA = "CTR-A";
    private const string CentreAName = "Centre A";

    private static GSDContext NewDb() =>
        new(new DbContextOptionsBuilder<GSDContext>()
            .UseInMemoryDatabase(Guid.NewGuid().ToString())
            // RosterService.GenerateAsync runs in a transaction; the in-memory store has none.
            .ConfigureWarnings(w => w.Ignore(InMemoryEventId.TransactionIgnoredWarning))
            .Options);

    private static WicLocation Loc(string code, string name) => new()
    {
        LocationCode = code, DisplayName = name, City = name, Country = "DE",
        IsActive = true, MinAgentsRequired = 1,
    };

    private static RosterService NewRoster(GSDContext db) =>
        new(db, new WicShiftService(db, new AvailabilityResolver(db)), new WicCoverageGapService(db));

    private static void SeedAgent(GSDContext db, string id = "E1")
    {
        db.Employees.Add(new Employee { EmployeeId = id, FullName = "Agent " + id, IsActive = true });
    }

    /// <summary>Centre A open 08:00-16:00 on the working days, closed at the weekend.</summary>
    private static void SeedCentre(GSDContext db, string code = CentreA, string name = CentreAName)
    {
        db.WicLocations.Add(Loc(code, name));
        for (var dow = 1; dow <= 5; dow++)
            db.WicOpeningHours.Add(new WicOpeningHour
            {
                LocationCode = code, DayOfWeek = dow, OpenTime = "08:00", CloseTime = "16:00",
            });
        for (var dow = 0; dow <= 6; dow++)
            if (dow is 0 or 6)
                db.WicOpeningHours.Add(new WicOpeningHour
                {
                    LocationCode = code, DayOfWeek = dow, IsClosed = true,
                });
    }

    private static ShiftEntry WicDuty(DateOnly date, string? agentTask = CentreAName,
        string from = "06:00", string to = "16:00") => new()
    {
        EmployeeId = "E1", ShiftDate = date, ShiftType = ShiftTypes.WicDuty, IsWicDuty = true,
        AgentTask = agentTask, ShiftStart = from, ShiftEnd = to,
        SourceModule = "Roster", SourceSheet = "ROSTER", AutoGenerated = true,
    };

    private static RosterRequest WicRequest(DateOnly from, DateOnly to, bool overwrite = true) =>
        new("E1", from.ToString("yyyy-MM-dd"), to.ToString("yyyy-MM-dd"),
            "06:00", "16:00", null, null, CentreA, overwrite);

    // ── 1. The generator: WIC_DUTY -> on-site WIC row is created ─────────────────────────

    [Fact]
    public async Task Generate_WicDutyDay_WritesTheOnSiteRow_AsShiftIntersectedWithCentreHours()
    {
        using var db = NewDb();
        SeedAgent(db);
        SeedCentre(db);
        await db.SaveChangesAsync();

        var gen = await NewRoster(db).GenerateAsync(WicRequest(Mon, Mon), "K1", "Tester");
        Assert.Equal(1, gen.Created);

        var shift = await db.ShiftEntries.SingleAsync();
        Assert.Equal(ShiftTypes.WicDuty, shift.ShiftType);
        Assert.Equal(CentreAName, shift.AgentTask);

        var wic = await db.WicShiftEntries.SingleAsync();
        Assert.True(wic.IsOnSite);
        Assert.Equal(CentreAName, wic.SupportLocation);
        Assert.Equal(CentreA, wic.LocationCode);
        // Agent 06:00-16:00 ∩ centre 08:00-16:00.
        Assert.Equal("08:00-16:00", wic.WorkingShift);
        Assert.Equal("WIC", wic.Task);
    }

    // ── 2. The live defect: the OVERWRITE path must not lose the on-site row ────────────

    [Fact]
    public async Task Overwrite_ReplacingTheDay_KeepsTheOnSiteRowOnSite_WithTheIntersection()
    {
        // Exactly the RosterBatch 265 shape: the day already is WIC_DUTY at Centre A with an
        // on-site WicShiftEntries row; the batch regenerates the same centre in Overwrite mode.
        using var db = NewDb();
        SeedAgent(db);
        SeedCentre(db);
        db.ShiftEntries.Add(WicDuty(Mon, CentreAName, "08:00", "12:00"));
        await db.SaveChangesAsync();

        // The pre-existing commitment, as an earlier batch left it.
        var before = await db.WicShiftEntries.SingleAsync();
        Assert.True(before.IsOnSite);
        Assert.Equal("08:00-12:00", before.WorkingShift);
        var wicRowId = before.Id;

        var gen = await NewRoster(db).GenerateAsync(WicRequest(Mon, Mon), "K1", "Tester");
        Assert.Equal(1, gen.Replaced);

        // THE ASSERTION THAT FAILED BEFORE: the row still exists, on site, with the
        // regenerated day's intersection — it was not deleted by SaveChanges.
        var after = await db.WicShiftEntries.SingleAsync();
        Assert.Equal(wicRowId, after.Id);            // the same row, revived, not duplicated
        Assert.True(after.IsOnSite);
        Assert.Equal(CentreAName, after.SupportLocation);
        Assert.Equal(CentreA, after.LocationCode);
        Assert.Equal("08:00-16:00", after.WorkingShift);
        Assert.Equal("WIC", after.Task);
    }

    [Fact]
    public async Task Overwrite_MultiDay_MonthOfWicDutyThursdays_AllHaveTheirOnSiteRow()
    {
        // The Wesel month shape: several WIC duty days regenerated in one overwrite batch.
        using var db = NewDb();
        SeedAgent(db);
        SeedCentre(db);
        // 2026-10-05 Mon .. 2026-10-30 Fri, WIC_DUTY + on-site row on every Monday and Thursday.
        var wicDays = new[] { 5, 8, 12, 15, 19, 22, 26, 29 }.Select(d => new DateOnly(2026, 10, d)).ToList();
        foreach (var d in wicDays)
            db.ShiftEntries.Add(WicDuty(d, CentreAName, "08:00", "12:00"));
        await db.SaveChangesAsync();
        Assert.Equal(wicDays.Count, await db.WicShiftEntries.CountAsync());

        await NewRoster(db).GenerateAsync(
            new RosterRequest("E1", "2026-10-05", "2026-10-30", "06:00", "16:00", null, null, CentreA, true),
            "K1", "Tester");

        var rows = await db.WicShiftEntries.ToListAsync();
        // The whole month is generated: 20 working days (2026-10-05 .. 2026-10-30), each with
        // its on-site row — the 8 WIC duty days replaced in place plus the 12 new plain days.
        Assert.Equal(20, rows.Count);
        Assert.Equal(20, rows.Select(w => w.ShiftDate).Distinct().Count());
        Assert.All(rows, w =>
        {
            Assert.True(w.IsOnSite);
            Assert.Equal("08:00-16:00", w.WorkingShift);
            Assert.Equal(CentreAName, w.SupportLocation);
        });
        // Every WIC duty day of the overwrite kept its row.
        Assert.All(wicDays, d => Assert.Contains(rows, w => w.ShiftDate == d));
    }

    // ── 3. The central sync: any writer, one unit of work ───────────────────────────────

    [Fact]
    public async Task CentralSync_RevivesARowTheSameUnitOfWorkIsDeleting()
    {
        using var db = NewDb();
        SeedAgent(db);
        SeedCentre(db);
        db.ShiftEntries.Add(WicDuty(Mon));
        await db.SaveChangesAsync();

        var created = await db.WicShiftEntries.SingleAsync();
        Assert.True(created.IsOnSite);

        // A writer (the old overwrite path) removes the day's WIC row in the same unit of
        // work that keeps the day WIC_DUTY.
        var row = await db.ShiftEntries.SingleAsync();
        db.WicShiftEntries.Remove(created);
        row.RawValue = "regenerated";
        await db.SaveChangesAsync();

        // The commitment survives: the row is revived, on site, at the right centre. The
        // hook fills a gap and keeps a row alive — it never re-times a row that exists
        // (only a writer that knows the day's decided window for this centre does that, see
        // Overwrite_ReplacingTheDay_KeepsTheOnSiteRowOnSite_WithTheIntersection).
        var after = await db.WicShiftEntries.SingleAsync();
        Assert.True(after.IsOnSite);
        Assert.Equal(CentreAName, after.SupportLocation);
        Assert.Equal(CentreA, after.LocationCode);
        Assert.Equal("08:00-16:00", after.WorkingShift);
    }

    [Fact]
    public async Task CentralSync_WriterThatOnlyAddsTheShiftRow_GetsTheWicRowInTheSameSave()
    {
        using var db = NewDb();
        SeedAgent(db);
        SeedCentre(db);
        await db.SaveChangesAsync();

        db.ShiftEntries.Add(WicDuty(Tue));
        await db.SaveChangesAsync();

        var wic = await db.WicShiftEntries.SingleAsync();
        Assert.True(wic.IsOnSite);
        Assert.Equal(CentreAName, wic.SupportLocation);
        Assert.Equal("08:00-16:00", wic.WorkingShift);
    }

    [Fact]
    public async Task CentralSync_IsIdempotent_AndLeavesACorrectRowAlone()
    {
        using var db = NewDb();
        SeedAgent(db);
        SeedCentre(db);
        db.ShiftEntries.Add(WicDuty(Mon));
        await db.SaveChangesAsync();

        var first = await db.WicShiftEntries.SingleAsync();
        var id = first.Id;

        var row = await db.ShiftEntries.SingleAsync();
        row.RawValue = "note";              // unrelated field change, same unit of work
        await db.SaveChangesAsync();

        var again = await db.WicShiftEntries.SingleAsync();
        Assert.Equal(id, again.Id);
        Assert.Equal("08:00-16:00", again.WorkingShift);
        Assert.Equal(1, await db.WicShiftEntries.CountAsync());
    }

    // ── 4. What the sync must NOT do ────────────────────────────────────────────────────

    [Fact]
    public async Task ClosedCentre_GetsNoOnSiteRow()
    {
        using var db = NewDb();
        SeedAgent(db);
        // Centre A exists but is closed on the Monday.
        db.WicLocations.Add(Loc(CentreA, CentreAName));
        db.WicOpeningHours.Add(new WicOpeningHour
        {
            LocationCode = CentreA, DayOfWeek = (int)DayOfWeek.Monday, IsClosed = true,
        });
        db.ShiftEntries.Add(WicDuty(Mon));
        await db.SaveChangesAsync();

        Assert.Empty(db.WicShiftEntries.ToList());
    }

    [Fact]
    public async Task WicDutyWithoutACentre_IsLeftAlone_TheSyncNeverGuesses()
    {
        using var db = NewDb();
        SeedAgent(db);
        SeedCentre(db);
        db.ShiftEntries.Add(WicDuty(Mon, agentTask: null));
        await db.SaveChangesAsync();

        Assert.Empty(db.WicShiftEntries.ToList());
    }

    [Fact]
    public async Task ManualBackOfficeDay_IsNeverTouched()
    {
        // The Mülheim 29.10 shape: RTM set BO by hand (WORKING + RawValue=BO + ManualChangeBy)
        // and the centre name is still on the row. WIC over BO does NOT apply, and the
        // WIC_DUTY sync must not create anything either.
        using var db = NewDb();
        SeedAgent(db);
        SeedCentre(db);
        db.WicAgentAssignments.Add(new WicAgentAssignment
        {
            LocationCode = CentreA, EmployeeName = "Agent E1", AssignmentType = "MAIN", IsActive = true,
        });
        db.ShiftEntries.Add(new ShiftEntry
        {
            EmployeeId = "E1", ShiftDate = Mon, ShiftType = ShiftTypes.Working, RawValue = "BO",
            AgentTask = CentreAName, ShiftStart = "08:00", ShiftEnd = "17:00",
            ManualChangeBy = "ACTOR-1", ManualChangeAt = new DateTime(2026, 10, 5, 11, 0, 0, DateTimeKind.Utc),
        });
        await db.SaveChangesAsync();

        Assert.Empty(db.WicShiftEntries.ToList());
    }

