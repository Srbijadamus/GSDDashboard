namespace GSDDashboard.Tests;

// Regression tests for the live 2026-10-07 incident: a team lead tried to move
// Amani Kedo's 2026-10-07 WIC duty (ShiftEntries id 56294, ManualChangeBy S60028)
// to GSD Backlog. POST /api/wic/move-to-gsd had no way to tell a deliberate human
// move from an automatic writer, so GSDContext.PreserveManualShift refused it and
// the UI showed only the generic "Failed to move agent".
//
// The rule this pins down: a human move ALWAYS works (and re-stamps the row as the
// human's decision); an automatic writer still cannot overwrite the manual row.
//
// 2026-10-07 variant b: a strict session/KID gate (401 anonymous / 403 wrong role)
// was considered, but no live request log for the last 7 days proves that every real
// team-lead call arrives with a session and a usable KID. Rather than risk locking a
// real team lead out of the manual move, the route now reuses ResolveManualActor
// exactly like /api/wic/shifts and /api/wic/assignments: the session KID when present,
// otherwise the fixed UI-MANUAL tag. The automatic-writer refusal stays at the service
// layer (manualActor == null), which is what the protection is actually for.
public class MoveToGsdManualEditTests
{
    private static readonly DateOnly ManualDate = new(2026, 10, 7); // Wednesday

    private static GSDContext NewDb() =>
        new(new DbContextOptionsBuilder<GSDContext>().UseInMemoryDatabase(Guid.NewGuid().ToString()).Options);

    private static WicShiftService Svc(GSDContext db) => new(db, new AvailabilityResolver(db));

    // Mirrors the live row shape: a WIC_DUTY ShiftEntry the human set earlier
    // (ManualChangeBy = the team-lead KID) plus its on-site Essen - TK WicShiftEntries row.
    private static async Task<ShiftEntry> SeedManualWicDayAsync(GSDContext db)
    {
        db.Employees.Add(new Employee { EmployeeId = "9120970", FullName = "Synthetic agent", IsActive = true });
        db.WicShiftEntries.Add(new WicShiftEntry
        {
            Id = 47420,
            EmployeeId = "9120970",
            ShiftDate = ManualDate,
            DayOfWeek = "Wednesday",
            SupportLocation = "Essen - TK",
            WorkingShift = "08:00-16:00",
            IsOnSite = true,
            Task = "WIC",
        });
        var row = new ShiftEntry
        {
            Id = 56294,
            EmployeeId = "9120970",
            ShiftDate = ManualDate,
            ShiftType = ShiftTypes.WicDuty,
            ShiftStart = "08:00",
            ShiftEnd = "16:00",
            IsWicDuty = true,
            SourceModule = "MANUAL",
            AutoGenerated = false,
            ManualChangeBy = "S60028",
            ManualChangeAt = new DateTime(2026, 10, 6, 9, 35, 58, DateTimeKind.Utc),
            ManualChangeNote = "Manual shift cell edit (/shifts); automatic writers must preserve this row.",
        };
        db.ShiftEntries.Add(row);
        await db.SaveChangesAsync();
        return row;
    }

    // The exact live failure: the team lead's own move of a manual row must succeed,
    // and the moved row must still be marked as a human decision.
    [Fact]
    public async Task HumanMove_OnProtectedManualRow_Succeeds_AndKeepsManualMarker()
    {
        using var db = NewDb();
        await SeedManualWicDayAsync(db);

        var result = await Svc(db).MoveToGsdAsync(
            "9120970", ManualDate, ManualDate, skipWeekends: false, db, manualActor: "TEAM-LEAD-KID");

        var value = ((IValueHttpResult)result).Value!;
        Assert.True((bool)value.GetType().GetProperty("success")!.GetValue(value)!);

        var row = await db.ShiftEntries.SingleAsync(s => s.Id == 56294);
        Assert.Equal(ShiftTypes.Working, row.ShiftType);
        Assert.Equal("GSD", row.AgentTask);
        Assert.False(row.IsWicDuty);
        Assert.Equal("MOVE_TO_GSD", row.SourceModule);
        Assert.Equal("TEAM-LEAD-KID", row.ManualChangeBy);
        Assert.NotNull(row.ManualChangeAt);
        Assert.False(row.AutoGenerated);

        var wic = await db.WicShiftEntries.SingleAsync(w => w.Id == 47420);
        Assert.False(wic.IsOnSite);
        Assert.True(wic.IsGSDDay);
    }

    // The whole point of the protection survives: an automatic writer (no actor) is
    // still refused, sees the exact actionable reason, and nothing is moved.
    [Fact]
    public async Task AutomaticWriter_WithoutActor_IsRefused_WithTheExactReason()
    {
        using var db = NewDb();
        await SeedManualWicDayAsync(db);

        var result = await Svc(db).MoveToGsdAsync(
            "9120970", ManualDate, ManualDate, skipWeekends: false, db, manualActor: null);

        var conflict = Assert.IsAssignableFrom<IStatusCodeHttpResult>(result);
        Assert.Equal(409, conflict.StatusCode);
        var value = ((IValueHttpResult)result).Value!;
        var reason = (string)value.GetType().GetProperty("error")!.GetValue(value)!;
        Assert.Contains("2026-10-07", reason);
        Assert.Contains("protected manual shift", reason);

        var row = await db.ShiftEntries.SingleAsync(s => s.Id == 56294);
        Assert.Equal(ShiftTypes.WicDuty, row.ShiftType);
        Assert.True(row.IsWicDuty);
        Assert.Equal("S60028", row.ManualChangeBy);
        Assert.True((await db.WicShiftEntries.SingleAsync(w => w.Id == 47420)).IsOnSite);
    }

    // Moving a range that contains a manual day still works for the human: every day in
    // the range is moved (manual and non-manual alike), and the marker follows the human.
    [Fact]
    public async Task HumanMove_OverARange_MovesEveryDayIncludingTheManualOne()
    {
        using var db = NewDb();
        await SeedManualWicDayAsync(db);
        db.ShiftEntries.Add(new ShiftEntry
        {
            Id = 56295, EmployeeId = "9120970", ShiftDate = ManualDate.AddDays(1),
            ShiftType = ShiftTypes.Working, AgentTask = null, AutoGenerated = true, SourceModule = "Roster",
        });
        await db.SaveChangesAsync();

        var result = await Svc(db).MoveToGsdAsync(
            "9120970", ManualDate, ManualDate.AddDays(1), skipWeekends: false, db, manualActor: "TEAM-LEAD-KID");

        var value = ((IValueHttpResult)result).Value!;
        Assert.Equal(2, (int)value.GetType().GetProperty("daysMoved")!.GetValue(value)!);
        Assert.Equal(2, await db.ShiftEntries.CountAsync(s => s.AgentTask == "GSD"));
        // The human's move is itself a manual decision, so both moved days carry the
        // session actor — nothing in the range can be silently re-overwritten later.
        Assert.Equal("TEAM-LEAD-KID", (await db.ShiftEntries.SingleAsync(s => s.Id == 56294)).ManualChangeBy);
        Assert.Equal("TEAM-LEAD-KID", (await db.ShiftEntries.SingleAsync(s => s.Id == 56295)).ManualChangeBy);
    }

    // Route-level wiring (variant b): with no session the route resolves the fixed
    // UI-MANUAL actor, so the move still succeeds and the row stays a human decision.
    // This is deliberate: no team lead may lose the manual move because login state or
    // KID lookup is not what the other manual WIC routes depend on either.
    [Fact]
    public async Task AnonymousHttpCall_UsesUiManualActor_AndMovesTheRow()
    {
        var builder = WebApplication.CreateBuilder(new WebApplicationOptions { EnvironmentName = "Testing" });
        builder.Configuration.Sources.Clear();
        builder.Logging.ClearProviders();
        builder.Services.AddSingleton<IDataProtectionProvider>(new EphemeralDataProtectionProvider());
        builder.Services.AddAuthentication(CookieAuthenticationDefaults.AuthenticationScheme).AddCookie();
        var database = Guid.NewGuid().ToString();
        builder.Services.AddDbContext<GSDContext>(o => o.UseInMemoryDatabase(database));
        builder.Services.AddScoped<WicShiftService>();
        builder.Services.AddScoped<AvailabilityResolver>();
        builder.Services.AddScoped<ShiftValidationService>();
        await using var app = builder.Build();
        app.Urls.Add("http://127.0.0.1:0");
        app.UseAuthentication();
        app.MapWicEndpoints();
        using (var scope = app.Services.CreateScope())
            await SeedManualWicDayAsync(scope.ServiceProvider.GetRequiredService<GSDContext>());
        await app.StartAsync();
        try
        {
            var address = app.Services.GetRequiredService<IServer>().Features.Get<IServerAddressesFeature>()!.Addresses.Single();
            using var client = new HttpClient(new HttpClientHandler { UseProxy = false, AllowAutoRedirect = false })
            {
                BaseAddress = new Uri(address)
            };
            using var response = await client.PostAsJsonAsync("/api/wic/move-to-gsd", new
            {
                employeeId = "9120970",
                date = "2026-10-07",
                dateTo = "2026-10-07",
                skipWeekends = false,
            });
            Assert.Equal(HttpStatusCode.OK, response.StatusCode);

            using var verifyScope = app.Services.CreateScope();
            var db = verifyScope.ServiceProvider.GetRequiredService<GSDContext>();
            var row = await db.ShiftEntries.SingleAsync(s => s.Id == 56294);
            Assert.Equal(ShiftTypes.Working, row.ShiftType);
            Assert.Equal("GSD", row.AgentTask);
            Assert.False(row.IsWicDuty);
            Assert.Equal("UI-MANUAL", row.ManualChangeBy);
            Assert.True((await db.WicShiftEntries.SingleAsync(w => w.Id == 47420)).IsGSDDay);
        }
        finally { await app.StopAsync(); }
    }
}
