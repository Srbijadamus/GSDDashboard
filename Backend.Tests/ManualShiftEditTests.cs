    [Fact]
    public async Task ManualRoutes_AllCellStatuses_SaveTimesAndSessionActor_AndRejectUnauthorizedUsers()
    {
        var builder = WebApplication.CreateBuilder(new WebApplicationOptions { EnvironmentName = "Testing" });
        builder.Configuration.Sources.Clear();
        builder.Configuration.AddInMemoryCollection(new Dictionary<string, string?> { ["Auth:EnforceAuthorization"] = "false" });
        builder.Logging.ClearProviders();
        builder.Services.AddSingleton<IDataProtectionProvider>(new EphemeralDataProtectionProvider());
        builder.Services.AddAuthentication(CookieAuthenticationDefaults.AuthenticationScheme).AddCookie();
        var database = Guid.NewGuid().ToString();
        builder.Services.AddDbContext<GSDContext>(options => options.UseInMemoryDatabase(database));
        builder.Services.AddScoped<ShiftService>();
        builder.Services.AddScoped<ShiftValidationService>();
        await using var app = builder.Build();
        app.Urls.Add("http://127.0.0.1:0");
        app.UseAuthentication();
        app.MapShiftEndpoints();
        app.MapPost("/test/login", async (string role, bool? noKid, HttpContext ctx) =>
        {
            await ctx.SignInAsync(CookieAuthenticationDefaults.AuthenticationScheme,
                new ClaimsPrincipal(new ClaimsIdentity(
                    [new Claim(AuthClaims.Kid, noKid == true ? "" : "TEST-OPERATOR"), new Claim(AuthClaims.Role, role)],
                    CookieAuthenticationDefaults.AuthenticationScheme)));
            return Results.Ok();
        });
        using (var scope = app.Services.CreateScope())
        {
            var db = scope.ServiceProvider.GetRequiredService<GSDContext>();
            db.Employees.Add(new Employee { EmployeeId = "TEST-E", FullName = "Synthetic agent", IsActive = true });
            db.ShiftEntries.Add(new ShiftEntry
            {
                Id = 101,
                EmployeeId = "TEST-E",
                ShiftDate = DateOnly.FromDateTime(DateTime.Today),
                ShiftType = "SL",
                AutoGenerated = true,
                SourceModule = "SickLeave",
                SourceId = 7,
                PreviousStatus = "WORKING"
            });
            await db.SaveChangesAsync();
        }
        await app.StartAsync();
        var address = app.Services.GetRequiredService<IServer>().Features.Get<IServerAddressesFeature>()!.Addresses.Single();
        HttpClient Client() => new(new HttpClientHandler { UseProxy = false, AllowAutoRedirect = false }) { BaseAddress = new Uri(address) };
        try
        {
            using var anonymous = Client();
            using var denied = await anonymous.PatchAsJsonAsync("/api/shifts/101/manual", new { shiftType = "WORKING" });
            Assert.Equal(HttpStatusCode.Unauthorized, denied.StatusCode);
            using var deniedAssign = await anonymous.PostAsJsonAsync("/api/shifts/assign/manual", new { employeeId = "TEST-E", shiftDate = "2026-10-06", shiftType = "WORKING" });
            Assert.Equal(HttpStatusCode.Unauthorized, deniedAssign.StatusCode);
            using var deniedGeneric = await anonymous.PatchAsJsonAsync("/api/shifts/101", new { shiftType = "WORKING" });
            Assert.Equal(HttpStatusCode.Unauthorized, deniedGeneric.StatusCode);
            using var deniedGenericAssign = await anonymous.PostAsJsonAsync("/api/shifts/assign", new { employeeId = "TEST-E", shiftDate = "2026-10-06", shiftType = "WORKING" });
            Assert.Equal(HttpStatusCode.Unauthorized, deniedGenericAssign.StatusCode);
            using var agent = Client();
            using var agentLogin = await agent.PostAsync("/test/login?role=AGENT", null);
            using var forbidden = await agent.PatchAsJsonAsync("/api/shifts/101/manual", new { shiftType = "WORKING" });
            Assert.Equal(HttpStatusCode.Forbidden, forbidden.StatusCode);
            using var forbiddenGeneric = await agent.PatchAsJsonAsync("/api/shifts/101", new { shiftType = "WORKING" });
            Assert.Equal(HttpStatusCode.Forbidden, forbiddenGeneric.StatusCode);
            using var missingActor = Client();
            using var missingLogin = await missingActor.PostAsync("/test/login?role=RTM&noKid=true", null);
            using var missingRejected = await missingActor.PatchAsJsonAsync("/api/shifts/101", new { shiftType = "WORKING" });
            Assert.Equal(HttpStatusCode.Forbidden, missingRejected.StatusCode);
            foreach (var role in new[] { "DEV", "RTM", "TEAM_LEAD" })
            {
                using var client = Client();
                using var login = await client.PostAsync("/test/login?role=" + role, null);
                foreach (var type in Types)
                    foreach (var route in new[] { "/api/shifts/101", "/api/shifts/101/manual" })
                    {
                        using var saved = await client.PatchAsJsonAsync(route,
                            new { shiftType = type, shiftStart = "09:00", shiftEnd = "17:00", manualChangeBy = "FORGED" });
                        Assert.Equal(HttpStatusCode.OK, saved.StatusCode);
                        using var scope = app.Services.CreateScope();
                        var db = scope.ServiceProvider.GetRequiredService<GSDContext>();
                        var row = await db.ShiftEntries.SingleAsync();
                        Assert.Equal(type, row.ShiftType);
                        Assert.Equal("09:00", row.ShiftStart);
                        Assert.Equal("17:00", row.ShiftEnd);
                        Assert.Equal(type == "WIC_DUTY", row.IsWicDuty);
                        Assert.Equal("TEST-OPERATOR", row.ManualChangeBy);
                        Assert.NotNull(row.ManualChangeAt);
                        Assert.NotNull(row.ManualChangeNote);
                        Assert.Equal("SickLeave", row.SourceModule);
                        Assert.Equal(7, row.SourceId);
                        Assert.False(row.AutoGenerated);
                    }
            }
            using var operatorClient = Client();
            using var operatorLogin = await operatorClient.PostAsync("/test/login?role=RTM", null);
            using var assigned = await operatorClient.PostAsJsonAsync("/api/shifts/assign/manual",
                new { employeeId = "TEST-E", shiftDate = DateTime.Today.AddDays(1).ToString("yyyy-MM-dd"), shiftType = "WIC_DUTY", shiftStart = "10:00", shiftEnd = "18:00" });
            Assert.Equal(HttpStatusCode.OK, assigned.StatusCode);
            using var finalScope = app.Services.CreateScope();
            var created = await finalScope.ServiceProvider.GetRequiredService<GSDContext>().ShiftEntries.OrderBy(x => x.ShiftDate).LastAsync();
            Assert.True(created.IsWicDuty);
            Assert.Equal("TEST-OPERATOR", created.ManualChangeBy);
            using var reassigned = await operatorClient.PostAsJsonAsync("/api/shifts/assign/manual",
                new { employeeId = "TEST-E", shiftDate = DateTime.Today.AddDays(1).ToString("yyyy-MM-dd"), shiftType = "WIC_DUTY", shiftStart = "11:00", shiftEnd = "19:00" });
            Assert.Equal(HttpStatusCode.OK, reassigned.StatusCode);
            using var legacyDuplicate = await operatorClient.PostAsJsonAsync("/api/shifts/assign",
                new { employeeId = "TEST-E", shiftDate = DateTime.Today.AddDays(1).ToString("yyyy-MM-dd"), shiftType = "WIC_DUTY" });
            Assert.Equal(HttpStatusCode.Conflict, legacyDuplicate.StatusCode);
            using var changedGeneric = await operatorClient.PostAsJsonAsync("/api/shifts/assign",
                new { employeeId = "TEST-E", shiftDate = DateTime.Today.AddDays(1).ToString("yyyy-MM-dd"), shiftType = "OFF" });
            Assert.Equal(HttpStatusCode.OK, changedGeneric.StatusCode);
            using var blockedBulk = await operatorClient.PostAsJsonAsync("/api/shifts/assign/bulk",
                new { employeeId = "TEST-E", shiftDate = DateTime.Today.AddDays(1).ToString("yyyy-MM-dd"), shiftType = "SL" });
            Assert.Equal(HttpStatusCode.Conflict, blockedBulk.StatusCode);
            foreach (var role in new[] { "DEV", "RTM", "TEAM_LEAD" })
            {
                using var client = Client();
                using var login = await client.PostAsync("/test/login?role=" + role, null);
                foreach (var type in Types)
                {
                    var date = DateOnly.FromDateTime(DateTime.Today.AddDays(3));
                    using var result = await client.PostAsJsonAsync("/api/shifts/assign",
                        new
                        {
                            employeeId = "TEST-E",
                            shiftDate = date.ToString("yyyy-MM-dd"),
                            shiftType = type,
                            shiftStart = "09:00",
                            shiftEnd = "17:00",
                            manualChangeBy = "FORGED"
                        });
                    Assert.Equal(HttpStatusCode.OK, result.StatusCode);
                    using var scope = app.Services.CreateScope();
                    var row = await scope.ServiceProvider.GetRequiredService<GSDContext>().ShiftEntries.SingleAsync(s => s.ShiftDate == date);
                    Assert.Equal(type, row.ShiftType);
                    Assert.Equal(type == "WIC_DUTY", row.IsWicDuty);
                    Assert.Equal("TEST-OPERATOR", row.ManualChangeBy);
                    Assert.NotNull(row.ManualChangeAt);
                    Assert.NotNull(row.ManualChangeNote);
                }
            }
            using var bulkCreated = await operatorClient.PostAsJsonAsync("/api/shifts/assign/bulk",
                new { employeeId = "TEST-E", shiftDate = DateTime.Today.AddDays(4).ToString("yyyy-MM-dd"), shiftType = "WORKING" });
            Assert.Equal(HttpStatusCode.OK, bulkCreated.StatusCode);
            using var bulkScope = app.Services.CreateScope();
            var bulkRow = await bulkScope.ServiceProvider.GetRequiredService<GSDContext>().ShiftEntries
                .SingleAsync(s => s.ShiftDate == DateOnly.FromDateTime(DateTime.Today.AddDays(4)));
            Assert.Null(bulkRow.ManualChangeBy);
        }
        finally { await app.StopAsync(); }
    }

    [Fact]
    public async Task NonCellSwapSubstitution_RefuseManualRows_AndMoveUsesUiManualActor()
    {
        var builder = WebApplication.CreateBuilder(new WebApplicationOptions { EnvironmentName = "Testing" });
        builder.Configuration.Sources.Clear();
        builder.Logging.ClearProviders();
        var database = Guid.NewGuid().ToString();
        builder.Services.AddDbContext<GSDContext>(options => options.UseInMemoryDatabase(database));
        builder.Services.AddScoped<ShiftService>();
        builder.Services.AddScoped<ShiftValidationService>();
        builder.Services.AddScoped<WicShiftService>();
        builder.Services.AddScoped<AvailabilityResolver>();
        await using var app = builder.Build();
        app.Urls.Add("http://127.0.0.1:0");
        app.MapShiftEndpoints();
        app.MapWicEndpoints();
        app.MapSubstituteAcceptEndpoints();
        var date = DateOnly.FromDateTime(DateTime.Today);
        using (var scope = app.Services.CreateScope())
        {
            var db = scope.ServiceProvider.GetRequiredService<GSDContext>();
            db.Employees.AddRange(new Employee { EmployeeId = "E1", IsActive = true }, new Employee { EmployeeId = "E2", IsActive = true });
            db.WicLocations.Add(new WicLocation { LocationCode = "LOC", DisplayName = "Centre", IsActive = true });
            db.ShiftEntries.AddRange(
                new ShiftEntry
                {
                    Id = 101,
                    EmployeeId = "E1",
                    ShiftDate = date,
                    ShiftType = "WORKING",
                    ManualChangeBy = "HUMAN",
                    ManualChangeAt = DateTime.UtcNow,
                    ManualChangeNote = "Human decision"
                },
                new ShiftEntry { Id = 102, EmployeeId = "E2", ShiftDate = date, ShiftType = "WIC_DUTY", IsWicDuty = true },
                new ShiftEntry { Id = 103, EmployeeId = "E1", ShiftDate = date.AddDays(1), ShiftType = "WIC_DUTY", IsWicDuty = true });
            db.WicShiftEntries.Add(new WicShiftEntry { EmployeeId = "E1", ShiftDate = date, IsOnSite = true, SupportLocation = "Centre" });
            await db.SaveChangesAsync();
        }
        await app.StartAsync();
        var address = app.Services.GetRequiredService<IServer>().Features.Get<IServerAddressesFeature>()!.Addresses.Single();
        using var client = new HttpClient(new HttpClientHandler { UseProxy = false }) { BaseAddress = new Uri(address) };
        try
        {
            using var swapSource = await client.PostAsJsonAsync("/api/shifts/101/swap", new { newEmployeeId = "E2" });
            Assert.Equal(HttpStatusCode.Conflict, swapSource.StatusCode);
            using var swapTarget = await client.PostAsJsonAsync("/api/shifts/102/swap", new { newEmployeeId = "E1" });
            Assert.Equal(HttpStatusCode.Conflict, swapTarget.StatusCode);
            using var substitute = await client.PostAsJsonAsync("/api/wic/substitutes/accept",
                new { employeeId = "E1", locationCode = "LOC", date = date.ToString("yyyy-MM-dd") });
            Assert.Equal(HttpStatusCode.Conflict, substitute.StatusCode);
            // Non-cell routes that touch a manual row still refuse it and write nothing.
            using (var scope = app.Services.CreateScope())
            {
                var db = scope.ServiceProvider.GetRequiredService<GSDContext>();
                Assert.Equal("WORKING", (await db.ShiftEntries.FindAsync(101))!.ShiftType);
                Assert.Equal("WIC_DUTY", (await db.ShiftEntries.FindAsync(102))!.ShiftType);
                Assert.Equal("WIC_DUTY", (await db.ShiftEntries.FindAsync(103))!.ShiftType);
                Assert.True((await db.WicShiftEntries.SingleAsync()).IsOnSite);
                Assert.Empty(await db.SubstitutionHistory.ToListAsync());
            }
            // Move-to-GSD follows the same actor rule as the other manual WIC routes
            // (variant b): an unauthenticated UI call resolves to UI-MANUAL, so the move
            // succeeds and stamps the row instead of being refused up front. This is what
            // guarantees no team lead is locked out of a manual change.
            using var move = await client.PostAsJsonAsync("/api/wic/move-to-gsd",
                new { employeeId = "E1", date = date.ToString("yyyy-MM-dd"), dateTo = date.AddDays(1).ToString("yyyy-MM-dd"), skipWeekends = false });
            Assert.Equal(HttpStatusCode.OK, move.StatusCode);
            using (var scope = app.Services.CreateScope())
            {
                var db = scope.ServiceProvider.GetRequiredService<GSDContext>();
                var moved = await db.ShiftEntries.FindAsync(101);
                Assert.Equal("WORKING", moved!.ShiftType);
                Assert.Equal("GSD", moved.AgentTask);
                Assert.Equal("UI-MANUAL", moved.ManualChangeBy);
                var movedNext = await db.ShiftEntries.FindAsync(103);
                Assert.Equal("WORKING", movedNext!.ShiftType);
                Assert.Equal("GSD", movedNext.AgentTask);
                Assert.Equal("UI-MANUAL", movedNext.ManualChangeBy);
                var wic = await db.WicShiftEntries.SingleAsync();
                Assert.False(wic.IsOnSite);
                Assert.True(wic.IsGSDDay);
            }
        }
        finally { await app.StopAsync(); }
    }

    [Fact]
    public async Task ManualWicToWorking_PreservesBusinessLinks_AndAutomaticServiceDoesNotInventMarkers()
    {
        using var db = new GSDContext(new DbContextOptionsBuilder<GSDContext>().UseInMemoryDatabase(Guid.NewGuid().ToString()).Options);
        db.Employees.Add(new Employee { EmployeeId = "TEST-E", FullName = "Synthetic agent", IsActive = true });
        var row = new ShiftEntry
        {
            EmployeeId = "TEST-E",
            ShiftDate = DateOnly.FromDateTime(DateTime.Today),
            ShiftType = "WIC_DUTY",
            IsWicDuty = true,
            AgentTask = "Synthetic centre",
            LocationId = "TEST-CENTRE",
            AssignmentStatus = "ASSIGNED"
        };
        var untouched = new ShiftEntry { EmployeeId = "TEST-E", ShiftDate = row.ShiftDate.AddDays(1), ShiftType = "SL", AgentTask = "Synthetic centre" };
        var legacy = new ShiftEntry { EmployeeId = "TEST-E", ShiftDate = row.ShiftDate.AddDays(2), ShiftType = "SL" };
        db.ShiftEntries.AddRange(row, untouched, legacy);
        await db.SaveChangesAsync();
        var service = new ShiftService(db);
        var result = await service.UpdateShiftAsync(row.Id, new ShiftUpdateDto("WORKING", "09:00", "17:00", null, null, null), "TEST-OPERATOR");
        Assert.Null(result.Error);
        Assert.False(row.IsWicDuty);
        Assert.Equal("Synthetic centre", row.AgentTask);
        Assert.Equal("TEST-CENTRE", row.LocationId);
        Assert.Equal("ASSIGNED", row.AssignmentStatus);
        Assert.Null(untouched.ManualChangeBy);
        Assert.Equal("SL", untouched.ShiftType);
        await service.UpdateShiftAsync(untouched.Id, new ShiftUpdateDto("WORKING", "08:00", "16:00", null, null, null), "TEST-OPERATOR");
        Assert.Equal("Synthetic centre", untouched.AgentTask);
        Assert.Equal("TEST-OPERATOR", untouched.ManualChangeBy);
        await service.UpdateShiftAsync(legacy.Id, new ShiftUpdateDto("WORKING", "08:00", "16:00", null, null, null));
        Assert.Null(legacy.ManualChangeBy);
    }
