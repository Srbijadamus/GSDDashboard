using System.Text.Json;
using GSDDashboard.API.Data;
using GSDDashboard.API.Modules.Roster;
using GSDDashboard.API.Modules.Shifts;
using GSDDashboard.API.Modules.WicShifts;
using GSDDashboard.API.Services;
using Microsoft.AspNetCore.Http;
using Microsoft.Data.SqlClient;
using Microsoft.EntityFrameworkCore;

namespace GSDDashboard.Tests;

public sealed class LiveManualAcceptanceFactAttribute : FactAttribute
{
    public LiveManualAcceptanceFactAttribute()
    {
        if (string.IsNullOrWhiteSpace(Environment.GetEnvironmentVariable("PULSE_MANUAL_SQL_ACCEPTANCE")))
            Skip = "Requires an explicit protected live acceptance receipt.";
    }
}

public class LiveManualShiftAcceptanceTests
{
    [LiveManualAcceptanceFact]
    public async Task LiveMarkedRows_SurviveTargetedAutomaticWriters_WithoutOtherWrites()
    {
        var path = Environment.GetEnvironmentVariable("PULSE_MANUAL_SQL_ACCEPTANCE")!;
        using var receipt = JsonDocument.Parse(await File.ReadAllTextAsync(path));
        var connection = receipt.RootElement.GetProperty("ConnectionString").GetString()!;
        var builder = new SqlConnectionStringBuilder(connection);
        Assert.True(builder.IntegratedSecurity);
        Assert.Equal("GSDDashboard", builder.InitialCatalog);
        var ids = receipt.RootElement.GetProperty("Ids").EnumerateArray().Select(x => x.GetInt32()).ToArray();
        Assert.Equal(5, ids.Length);
        var options = new DbContextOptionsBuilder<GSDContext>().UseSqlServer(connection).Options;
        using var db = new GSDContext(options);
        await using var transaction = await db.Database.BeginTransactionAsync();
        try
        {
            var rows = await db.ShiftEntries.Where(x => ids.Contains(x.Id)).OrderBy(x => x.Id).ToListAsync();
            Assert.Equal(5, rows.Count);
            Assert.Equal(new[] { "AL", "OFF", "SL", "WIC_DUTY", "WORKING" },
                rows.Select(x => x.ShiftType).OrderBy(x => x).ToArray());
            var before = JsonSerializer.Serialize(rows);
            var linksBefore = JsonSerializer.Serialize(await db.WicShiftEntries.AsNoTracking()
                .Where(x => rows.Select(r => r.EmployeeId).Contains(x.EmployeeId))
                .OrderBy(x => x.Id).ToListAsync());
            var sync = new ShiftSyncService(db);
            var shifts = new ShiftService(db);
            var wic = new WicShiftService(db, new AvailabilityResolver(db));
            var roster = new RosterService(db, wic, new WicCoverageGapService(db));
            foreach (var row in rows)
            {
                Assert.Equal("S60028", row.ManualChangeBy);
                Assert.NotNull(row.ManualChangeAt);
                Assert.False(row.AutoGenerated);
                Assert.False(string.IsNullOrWhiteSpace(row.ManualChangeNote));
                await sync.SyncSickLeaveAsync(row.EmployeeId, row.ShiftDate, row.ShiftDate, -1);
                await sync.SyncVacationAsync(row.EmployeeId, row.ShiftDate, row.ShiftDate, -1);
                if (row.SourceId.HasValue && row.SourceModule != null)
                    await sync.RevertVacationAsync(row.EmployeeId, row.ShiftDate, row.ShiftDate,
                        row.SourceId.Value, row.SourceModule);
                var rejected = await shifts.UpdateShiftAsync(row.Id,
                    new ShiftUpdateDto("SL", null, null, null, null, null));
                Assert.NotNull(rejected.Error);
                var bulk = await shifts.AssignShiftAsync(new AssignShiftDto(row.EmployeeId,
                    row.ShiftDate.ToString("yyyy-MM-dd"), "OFF", null, null));
                Assert.NotNull(bulk.DuplicateError);
                var upsert = await wic.CreateShiftAsync(new CreateShiftRequest(row.EmployeeId,
                    row.ShiftDate.ToString("yyyy-MM-dd"), "SL", null, null, null, null),
                    db, new ShiftValidationService(db));
                Assert.Equal(409, ((IStatusCodeHttpResult)upsert).StatusCode);
                var preview = await roster.PreviewAsync(new RosterRequest(row.EmployeeId,
                    row.ShiftDate.ToString("yyyy-MM-dd"), row.ShiftDate.ToString("yyyy-MM-dd"),
                    "08:00", "17:00", null, "Voice", Overwrite: true));
                Assert.Equal(0, preview.ReplaceCount);
                Assert.Equal(0, preview.RowCount);
                Assert.True(Assert.Single(preview.Collisions).Protected);
            }
            Assert.Equal(0, await sync.ReconcileFutureVacationsAsync());
            db.ChangeTracker.Clear();
            Assert.Equal(before, JsonSerializer.Serialize(await db.ShiftEntries.AsNoTracking()
                .Where(x => ids.Contains(x.Id)).OrderBy(x => x.Id).ToListAsync()));
            Assert.Equal(linksBefore, JsonSerializer.Serialize(await db.WicShiftEntries.AsNoTracking()
                .Where(x => rows.Select(r => r.EmployeeId).Contains(x.EmployeeId))
                .OrderBy(x => x.Id).ToListAsync()));
        }
        finally { await transaction.RollbackAsync(); }
    }
}
