    private static DateOnly Monday
    {
        get
        {
            var date = DateOnly.FromDateTime(DateTime.Today);
            while (date.DayOfWeek != DayOfWeek.Monday) date = date.AddDays(1);
            return date;
        }
    }

    private static DbContextOptions<GSDContext> Options(string? name = null) =>
        new DbContextOptionsBuilder<GSDContext>().UseInMemoryDatabase(name ?? Guid.NewGuid().ToString())
            .ConfigureWarnings(w => w.Ignore(InMemoryEventId.TransactionIgnoredWarning)).Options;

    private static ShiftEntry Seed(GSDContext db, bool manual = true, string source = "Vacation", int sourceId = 7,
        string employee = "E1", DateOnly? date = null, string? previous = "WORKING")
    {
        db.Employees.Add(new Employee { EmployeeId = employee, FullName = employee, IsActive = true });
        var row = new ShiftEntry
        {
            EmployeeId = employee, ShiftDate = date ?? Monday, ShiftType = "WORKING",
            ShiftStart = "09:00", ShiftEnd = "17:00", AgentTask = "Voice", LocationId = "LOC",
            AssignmentStatus = "ASSIGNED", RawValue = "original", AutoGenerated = true,
            SourceModule = source, SourceId = sourceId, PreviousStatus = previous, SourceSheet = "EXCEL",
            ManualChangeBy = manual ? "HUMAN" : null,
            ManualChangeAt = manual ? DateTime.UtcNow.AddHours(-1) : null,
            ManualChangeNote = manual ? "Human decision" : null
        };
        db.ShiftEntries.Add(row);
        return row;
    }

    private static RosterService Roster(GSDContext db) =>
        new(db, new WicShiftService(db, new AvailabilityResolver(db)), new WicCoverageGapService(db));

    private static void Location(GSDContext db, bool closed = false)
    {
        db.WicLocations.Add(new WicLocation { LocationCode = "LOC", DisplayName = "Centre", IsActive = true });
        db.WicOpeningHours.Add(new WicOpeningHour { LocationCode = "LOC", DayOfWeek = 1,
            IsClosed = closed, OpenTime = "08:00", CloseTime = "17:00" });
    }

    [Theory]
    [InlineData("SickLeave")]
    [InlineData("Vacation")]
    [InlineData("OtherLeave")]
    public async Task LeaveSync_PreservesEntireManualRow_StillUpdatesAutomaticRows_AndLogs(string source)
    {
        var log = new CaptureLogger();
        using var db = new GSDContext(Options(), log);
        var manual = Seed(db, source: source);
        var automatic = Seed(db, manual: false, employee: "E2", source: source);
        await db.SaveChangesAsync();
        var before = JsonSerializer.Serialize(manual);
        var sync = new ShiftSyncService(db);
        foreach (var employee in new[] { "E1", "E2" })
        {
            if (source == "SickLeave") await sync.SyncSickLeaveAsync(employee, Monday, Monday, 8);
            else await sync.SyncVacationAsync(employee, Monday, Monday, 8, source == "OtherLeave" ? "OL" : "AL", source);
        }
        Assert.Equal(before, JsonSerializer.Serialize(manual));
        Assert.Equal(source == "SickLeave" ? "SL" : source == "OtherLeave" ? "OL" : "AL", automatic.ShiftType);
        Assert.Contains(log.Messages, m => m.Contains("Manual shift preserved"));
    }

    [Theory]
    [InlineData("SickLeave", true)]
    [InlineData("SickLeave", false)]
    [InlineData("Vacation", true)]
    [InlineData("Vacation", false)]
    [InlineData("OtherLeave", true)]
    [InlineData("OtherLeave", false)]
    public async Task LeaveRevert_NeitherRestoresNorDeletesManualRows(string source, bool hadPrevious)
    {
        using var db = new GSDContext(Options());
        var manual = Seed(db, source: source, previous: hadPrevious ? "OFF" : null);
        var automatic = Seed(db, manual: false, employee: "E2", source: source, previous: hadPrevious ? "OFF" : null);
        await db.SaveChangesAsync();
        var before = JsonSerializer.Serialize(manual);
        var sync = new ShiftSyncService(db);
        foreach (var employee in new[] { "E1", "E2" })
        {
            if (source == "SickLeave") await sync.RevertSickLeaveAsync(employee, Monday, Monday, 7);
            else await sync.RevertVacationAsync(employee, Monday, Monday, 7, source);
        }
        Assert.Equal(before, JsonSerializer.Serialize(manual));
        Assert.True(await db.ShiftEntries.AnyAsync(s => s.Id == manual.Id));
        if (hadPrevious) Assert.Equal("OFF", automatic.ShiftType);
        else Assert.False(await db.ShiftEntries.AnyAsync(s => s.Id == automatic.Id));
    }

