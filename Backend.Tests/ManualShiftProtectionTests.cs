    [Fact]
    public async Task ClosedDayCleanup_PreservesManualDutyAndLink_DeletesAutomaticDuty()
    {
        using var db = new GSDContext(Options());
        var manual = Seed(db);
        manual.ShiftType = "WIC_DUTY";
        var automatic = Seed(db, manual: false, employee: "E2");
        automatic.ShiftType = "WIC_DUTY";
        Location(db, closed: true);
        foreach (var employee in new[] { "E1", "E2" })
            db.WicShiftEntries.Add(new WicShiftEntry { EmployeeId = employee, ShiftDate = Monday,
                SupportLocation = "Centre", LocationCode = "LOC", IsOnSite = true });
        await db.SaveChangesAsync();
        var before = JsonSerializer.Serialize(manual);
        var result = await new WicScheduleService(db, NullLogger<WicScheduleService>.Instance)
            .CleanupClosedDayDutiesAsync("LOC", Monday);
        Assert.Equal(1, result.ShiftEntriesRemoved);
        Assert.Equal(1, result.WicShiftEntriesRemoved);
        Assert.Equal(before, JsonSerializer.Serialize(manual));
        Assert.Equal("E1", (await db.WicShiftEntries.SingleAsync()).EmployeeId);
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task ContextSafetyNet_BlocksUnapprovedUpdatesAndDeletes_EvenIfMarkerIsCleared(bool delete)
    {
        using var db = new GSDContext(Options());
        var manual = Seed(db);
        await db.SaveChangesAsync();
        if (delete) db.ShiftEntries.Remove(manual);
        else { manual.ShiftType = "SL"; manual.ManualChangeBy = null; }
        Assert.Throws<InvalidOperationException>(() => db.SaveChanges());
        await Assert.ThrowsAsync<InvalidOperationException>(() => db.SaveChangesAsync());
    }

    [Fact]
    public async Task ConcurrentAutomaticWriter_LoadedBeforeHumanEdit_CannotOverwriteIt()
    {
        var options = Options();
        using var automaticDb = new GSDContext(options);
        var row = Seed(automaticDb, manual: false);
        await automaticDb.SaveChangesAsync();
        using var humanDb = new GSDContext(options);
        await new ShiftService(humanDb).UpdateShiftAsync(row.Id,
            new ShiftUpdateDto("OFF", null, null, null, null, null), "HUMAN");
        row.ShiftType = "SL";
        await Assert.ThrowsAsync<DbUpdateConcurrencyException>(() => automaticDb.SaveChangesAsync());
        using var verify = new GSDContext(options);
        Assert.Equal("OFF", (await verify.ShiftEntries.SingleAsync()).ShiftType);
    }

    private sealed class CaptureLogger : ILogger<GSDContext>
    {
        public List<string> Messages { get; } = [];
        public IDisposable? BeginScope<TState>(TState state) where TState : notnull => null;
        public bool IsEnabled(LogLevel logLevel) => true;
        public void Log<TState>(LogLevel logLevel, EventId eventId, TState state, Exception? exception,
            Func<TState, Exception?, string> formatter) => Messages.Add(formatter(state, exception));
    }
