    [Fact]
    public async Task RosterOverwriteAndUndo_RespectManualMarkersRegardlessOfBatchOwnership()
    {
        using var db = new GSDContext(Options());
        var manual = Seed(db, source: "Roster", sourceId: 55);
        var automatic = new ShiftEntry { EmployeeId = "E1", ShiftDate = Monday.AddDays(1),
            ShiftType = "WORKING", SourceModule = "Roster", SourceId = 55 };
        db.ShiftEntries.Add(automatic);
        db.RosterBatches.Add(new RosterBatch { Id = 55, EmployeeId = "E1", DateFrom = Monday,
            DateTo = Monday.AddDays(1), WorkingDays = "1,2,3,4,5", ShiftStart = "08:00", ShiftEnd = "17:00" });
        await db.SaveChangesAsync();
        var before = JsonSerializer.Serialize(manual);
        var request = new RosterRequest("E1", Monday.ToString("yyyy-MM-dd"), Monday.AddDays(1).ToString("yyyy-MM-dd"),
            "08:00", "16:00", null, "Voice", Overwrite: true);
        var preview = await Roster(db).PreviewAsync(request);
        Assert.True(Assert.Single(preview.Collisions).Protected);
        Assert.Equal(1, preview.ReplaceCount);
        var generated = await Roster(db).GenerateAsync(request, "OPERATOR", "Operator");
        Assert.Equal(1, generated.Replaced);
        await new ShiftService(db).UpdateShiftAsync(automatic.Id,
            new ShiftUpdateDto("OFF", null, null, null, null, null), "OPERATOR");
        var edited = JsonSerializer.Serialize(automatic);
        var undo = await Roster(db).DeleteBatchAsync(generated.BatchId);
        Assert.Equal(1, undo!.DetachedRows);
        Assert.Equal(1, undo.RestoreSkipped);
        Assert.Equal(edited, JsonSerializer.Serialize(automatic));
        var oldUndo = await Roster(db).DeleteBatchAsync(55);
        Assert.Equal(1, oldUndo!.DetachedRows);
        Assert.Equal(0, oldUndo.DeletedRows);
        Assert.Equal(before, JsonSerializer.Serialize(manual));
    }

    [Fact]
    public async Task WicUpsertsAndTraining_DoNotMutateManualRowsOrAssociatedDuty()
    {
        using var db = new GSDContext(Options());
        var manual = Seed(db);
        Location(db);
        db.WicShiftEntries.Add(new WicShiftEntry { EmployeeId = "E1", ShiftDate = Monday,
            SupportLocation = "Original centre", IsOnSite = true });
        await db.SaveChangesAsync();
        var before = JsonSerializer.Serialize(manual);
        var wicBefore = JsonSerializer.Serialize(await db.WicShiftEntries.SingleAsync());
        var svc = new WicShiftService(db, new AvailabilityResolver(db));
        var assigned = await svc.CreateAssignmentAsync(new CreateAssignmentRequest("E1", "LOC",
            Monday.ToString("yyyy-MM-dd"), null, null), db, "Roster", 99);
        var assignedValue = ((IValueHttpResult)assigned).Value!;
        Assert.Equal(false, assignedValue.GetType().GetProperty("success")!.GetValue(assignedValue));
        Assert.Equal(true, assignedValue.GetType().GetProperty("skipped")!.GetValue(assignedValue));
        var created = await svc.CreateShiftAsync(new CreateShiftRequest("E1", Monday.ToString("yyyy-MM-dd"),
            "SL", null, null, null, null), db, new ShiftValidationService(db));
        Assert.Equal(409, ((IStatusCodeHttpResult)created).StatusCode);
        await new TrainingService(db).ConfirmAsync(new ConfirmRequest(1, Monday.ToString("yyyy-MM-dd"),
            "10:00", "11:00", ["E1"], null));
        Assert.Equal(before, JsonSerializer.Serialize(manual));
        Assert.Equal(wicBefore, JsonSerializer.Serialize(await db.WicShiftEntries.SingleAsync()));
    }

    [Fact]
