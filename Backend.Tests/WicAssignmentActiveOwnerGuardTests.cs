using GSDDashboard.API.Data;
using GSDDashboard.API.Data.Models;
using GSDDashboard.API.Modules.WicShifts;
using GSDDashboard.API.Services;
using Microsoft.AspNetCore.Http;
using Microsoft.EntityFrameworkCore;
using Xunit;

namespace GSDDashboard.Tests;

// REQUIREMENT 5 — the RTM / human assign guard in
// WicShiftService.CreateAssignmentAsync.
//
// A human assignment into centre B that OVERLAPS an IsOnSite row at a different
// centre A must not silently delete the A row when BOTH hold:
//   (a) WicAgentAssignments has an ACTIVE row for A matching this employee
//       (LocationCode + EmployeeName == FullName; the table has no EmployeeId), and
//   (b) the day's ShiftEntries row is human-owned (ManualChangeBy set, or the
//       row is rollout-owned).
// The first call then answers MANUAL_CONFLICT / requiresConfirmation and writes
// nothing; only a re-send with ConfirmManualReplace=true replaces A.
// Otherwise (no active A assignment, or the day row is not human-owned) the
// human's centre wins and the stale A row is removed in the same SaveChanges —
// two overlapping IsOnSite rows for one employee+day must never survive.
public class WicAssignmentActiveOwnerGuardTests
{
    private static readonly DateOnly Monday = new(2026, 10, 12);

    private const string Emp  = "E-GUARD";
    private const string Name = "Guard Agent";

    private static GSDContext NewDb() =>
        new(new DbContextOptionsBuilder<GSDContext>().UseInMemoryDatabase(Guid.NewGuid().ToString()).Options);

    private static WicShiftService Svc(GSDContext db) => new(db, new AvailabilityResolver(db));

    private static object Value(IResult r) => ((IValueHttpResult)r).Value!;
    private static bool Bool(object v, string p) => (bool)(v.GetType().GetProperty(p)?.GetValue(v) ?? false);
    private static bool Has(object v, string p) => v.GetType().GetProperty(p) != null;
    private static string? Str(object v, string p) => (string?)v.GetType().GetProperty(p)?.GetValue(v);

    // Employee + both centres open all Monday. The working windows come from the
    // explicit request time and the existing WorkingShift, so the opening hours
    // only have to keep the centres open.
    private static void SeedBase(GSDContext db)
    {
        db.Employees.Add(new Employee { EmployeeId = Emp, FullName = Name, IsActive = true });
        db.WicLocations.Add(new WicLocation { LocationCode = "A", DisplayName = "Centre A", IsActive = true });
        db.WicLocations.Add(new WicLocation { LocationCode = "B", DisplayName = "Centre B", IsActive = true });
        db.WicOpeningHours.Add(new WicOpeningHour
        { LocationCode = "A", DayOfWeek = 1, OpenTime = "06:00", CloseTime = "20:00", IsClosed = false });
        db.WicOpeningHours.Add(new WicOpeningHour
        { LocationCode = "B", DayOfWeek = 1, OpenTime = "06:00", CloseTime = "20:00", IsClosed = false });
    }

    private static void SeedActiveAssignmentFor(GSDContext db, string locationCode) =>
        db.WicAgentAssignments.Add(new WicAgentAssignment
        { LocationCode = locationCode, EmployeeName = Name, AssignmentType = "MAIN", IsActive = true });

    // The day's own ShiftEntries row — the only source of "human-owned" because
    // WicShiftEntries has no manual columns. `human` = ManualChangeBy set.
    private static ShiftEntry SeedDayRow(GSDContext db, bool human, string start = "10:00", string end = "14:00")
    {
        var row = new ShiftEntry
        {
            EmployeeId = Emp,
            ShiftDate = Monday,
            ShiftType = ShiftTypes.WicDuty,
            IsWicDuty = true,
            AgentTask = "Centre A",
            ShiftStart = start,
            ShiftEnd = end,
            AutoGenerated = !human,
            SourceModule = human ? "ASSIGN" : "Roster",
            ManualChangeBy = human ? "S60028" : null,
            ManualChangeAt = human ? DateTime.UtcNow.AddHours(-2) : null,
            ManualChangeNote = human ? "Human decision" : null,
        };
        db.ShiftEntries.Add(row);
        return row;
    }

    // The pre-existing overlapping commitment at centre A.
    private static void SeedExistingA(GSDContext db, string workingShift = "10:00-14:00")
    {
        db.WicShiftEntries.Add(new WicShiftEntry
        {
            EmployeeId = Emp,
            ShiftDate = Monday,
            SupportLocation = "Centre A",
            LocationCode = "A",
            WorkingShift = workingShift,
            IsOnSite = true,
            Task = "WIC",
        });
    }

    private static CreateAssignmentRequest ReqB(string start = "07:30", string end = "16:00", bool confirm = false) =>
        new(Emp, "B", Monday.ToString("yyyy-MM-dd"), start, end, confirm);

    private static List<WicShiftEntry> OnSiteRows(GSDContext db) =>
        db.WicShiftEntries.Where(w => w.EmployeeId == Emp && w.ShiftDate == Monday && w.IsOnSite).ToList();

    // ── HEADLINE 1: no active A assignment -> the stale A row is removed ─────────
    // Human-owned day row (ManualChangeBy set) but NO active WicAgentAssignments
    // row for A: there is nothing to protect, so the human's centre B wins.
    [Fact]
    public async Task HumanAssign_NoActiveAssignmentForA_RemovesOverlappingRow()
    {
        using var db = NewDb();
        SeedBase(db);
        SeedDayRow(db, human: true);
        SeedExistingA(db); // 10:00-14:00, no WicAgentAssignments row
        await db.SaveChangesAsync();

        var result = await Svc(db).CreateAssignmentAsync(ReqB(), db, manualActor: "S60028");
        var v = Value(result);

        Assert.True(Bool(v, "saved"));
        Assert.False(Has(v, "skipped"));

        var only = Assert.Single(OnSiteRows(db));
        Assert.Equal("Centre B", only.SupportLocation);
        Assert.Equal("07:30-16:00", only.WorkingShift);
        // No two overlapping IsOnSite rows survived.
        Assert.Single(db.WicShiftEntries.Where(w => w.EmployeeId == Emp && w.ShiftDate == Monday));
    }

    // ── HEADLINE 2: active A assignment but the day row is NOT human-owned ───────
    // The automatic/rostered row is not a human decision, so it is replaced.
    [Fact]
    public async Task HumanAssign_ActiveAssignmentButRowNotManual_RemovesOverlappingRow()
    {
        using var db = NewDb();
        SeedBase(db);
        SeedDayRow(db, human: false, start: "09:00", end: "17:00");
        SeedActiveAssignmentFor(db, "A");
        SeedExistingA(db);
        await db.SaveChangesAsync();

        var result = await Svc(db).CreateAssignmentAsync(ReqB(), db, manualActor: "S60028");
        var v = Value(result);

        Assert.True(Bool(v, "saved"));
        Assert.Equal("REPLACED_AUTOMATIC", Str(v, "reasonCode"));

        var only = Assert.Single(OnSiteRows(db));
        Assert.Equal("Centre B", only.SupportLocation);
        Assert.Single(db.WicShiftEntries.Where(w => w.EmployeeId == Emp && w.ShiftDate == Monday));
    }

    // ── INVERSE: active A assignment AND human-owned -> MANUAL_CONFLICT ──────────
    [Fact]
    public async Task HumanAssign_ActiveAssignmentAndManualRow_RequiresConfirmationAndChangesNothing()
    {
        using var db = NewDb();
        SeedBase(db);
        SeedDayRow(db, human: true);
        SeedActiveAssignmentFor(db, "A");
        SeedExistingA(db);
        await db.SaveChangesAsync();

        var result = await Svc(db).CreateAssignmentAsync(ReqB(), db, manualActor: "S60028");
        var v = Value(result);

        Assert.True(Bool(v, "requiresConfirmation"));
        Assert.False(Bool(v, "saved"));
        Assert.Equal("MANUAL_CONFLICT", Str(v, "reasonCode"));

        var conflict = ((System.Collections.IEnumerable)v.GetType().GetProperty("conflicts")!.GetValue(v)!)
            .Cast<object>().Single();
        Assert.Equal("Centre A", (string?)conflict.GetType().GetProperty("location")!.GetValue(conflict));
        Assert.Equal("10:00-14:00", (string?)conflict.GetType().GetProperty("workingShift")!.GetValue(conflict));
        Assert.Equal("S60028", (string?)conflict.GetType().GetProperty("actor")!.GetValue(conflict));

        // Nothing was deleted and nothing new was written.
        var only = Assert.Single(OnSiteRows(db));
        Assert.Equal("Centre A", only.SupportLocation);
        Assert.Equal("10:00-14:00", only.WorkingShift);
        Assert.DoesNotContain(db.WicShiftEntries, w => w.SupportLocation == "Centre B");
    }

    // ── confirmed re-send replaces the protected row ─────────────────────────────
    [Fact]
    public async Task HumanAssign_Confirmed_ReplacesProtectedRow()
    {
        using var db = NewDb();
        SeedBase(db);
        SeedDayRow(db, human: true);
        SeedActiveAssignmentFor(db, "A");
        SeedExistingA(db);
        await db.SaveChangesAsync();

        var result = await Svc(db).CreateAssignmentAsync(ReqB(confirm: true), db, manualActor: "S60028");
        var v = Value(result);

        Assert.True(Bool(v, "saved"));
        var only = Assert.Single(OnSiteRows(db));
        Assert.Equal("Centre B", only.SupportLocation);
    }

    // ── no overlap -> the A row is kept (current behaviour) ──────────────────────
    [Fact]
    public async Task HumanAssign_NonOverlappingRow_IsKept()
    {
        using var db = NewDb();
        SeedBase(db);
        SeedDayRow(db, human: true, start: "10:00", end: "12:00");
        SeedActiveAssignmentFor(db, "A");
        SeedExistingA(db, "10:00-12:00");
        await db.SaveChangesAsync();

        var result = await Svc(db).CreateAssignmentAsync(ReqB("13:00", "15:00"), db, manualActor: "S60028");
        var v = Value(result);

        Assert.True(Bool(v, "saved"));
        var onSite = OnSiteRows(db);
        Assert.Equal(2, onSite.Count);
        Assert.Contains(onSite, w => w.SupportLocation == "Centre A" && w.WorkingShift == "10:00-12:00");
        Assert.Contains(onSite, w => w.SupportLocation == "Centre B" && w.WorkingShift == "13:00-15:00");
    }

    // ── same centre -> update in place, never a second row ───────────────────────
    [Fact]
    public async Task HumanAssign_SameCentre_UpdatesInPlace()
    {
        using var db = NewDb();
        SeedBase(db);
        SeedDayRow(db, human: true);
        SeedActiveAssignmentFor(db, "B");
        db.WicShiftEntries.Add(new WicShiftEntry
        {
            EmployeeId = Emp, ShiftDate = Monday, SupportLocation = "Centre B", LocationCode = "B",
            WorkingShift = "10:00-14:00", IsOnSite = true, Task = "WIC",
        });
        await db.SaveChangesAsync();

        var result = await Svc(db).CreateAssignmentAsync(ReqB(), db, manualActor: "S60028");

        Assert.True(Bool(Value(result), "saved"));
        var only = Assert.Single(db.WicShiftEntries.Where(w => w.EmployeeId == Emp && w.ShiftDate == Monday));
        Assert.Equal("Centre B", only.SupportLocation);
        Assert.Equal("07:30-16:00", only.WorkingShift);
    }

    // ── no ShiftEntries row at all: ownership is unknowable -> replace ───────────
    // Requirement 5 reads human ownership from the day's ShiftEntries row; with no
    // such row the A row is not provably human-owned, so the human's B wins.
    [Fact]
    public async Task HumanAssign_NoShiftEntriesRow_RemovesOverlappingRow()
    {
        using var db = NewDb();
        SeedBase(db);
        SeedActiveAssignmentFor(db, "A");
        SeedExistingA(db);
        await db.SaveChangesAsync();

        var result = await Svc(db).CreateAssignmentAsync(ReqB(), db, manualActor: "S60028");

        Assert.True(Bool(Value(result), "saved"));
        var only = Assert.Single(OnSiteRows(db));
        Assert.Equal("Centre B", only.SupportLocation);
    }

    // ── requirement 5 step 5: the automatic writer is unchanged ─────────────────
    [Fact]
    public async Task AutomaticWriter_StillSkipsAndChangesNothing()
    {
        using var db = NewDb();
        SeedBase(db);
        // A non-manual day row: a manual one is refused even earlier by
        // PreserveManualShift (PROTECTED_MANUAL), which is not this requirement.
        SeedDayRow(db, human: false, start: "09:00", end: "17:00");
        SeedActiveAssignmentFor(db, "A");
        SeedExistingA(db);
        await db.SaveChangesAsync();

        var result = await Svc(db).CreateAssignmentAsync(ReqB(), db, "Roster", 42); // manualActor null
        var v = Value(result);

        Assert.False(Bool(v, "saved"));
        Assert.True(Bool(v, "skipped"));
        Assert.Equal("TIME_CONFLICT", Str(v, "reasonCode"));

        var only = Assert.Single(OnSiteRows(db));
        Assert.Equal("Centre A", only.SupportLocation);
        Assert.DoesNotContain(db.WicShiftEntries, w => w.SupportLocation == "Centre B");
    }
}
