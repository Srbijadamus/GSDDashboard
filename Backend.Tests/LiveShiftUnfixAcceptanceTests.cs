/// <summary>
/// Opt-in guard, same shape as LiveManualAcceptanceFactAttribute: the test reads the live
/// database and only runs when PULSE_SHIFT_UNFIX_ACCEPTANCE points at a receipt written by
/// the operator. It opens NO transaction and performs NO write (the live write of the
/// generator path is exercised by Tools\ShiftUnfix\Test-ShiftUnfixAcceptance.ps1, which
/// snapshots and restores the row it touches).
/// </summary>
public sealed class LiveShiftUnfixFactAttribute : FactAttribute
{
    public LiveShiftUnfixFactAttribute()
    {
        if (string.IsNullOrWhiteSpace(Environment.GetEnvironmentVariable("PULSE_SHIFT_UNFIX_ACCEPTANCE")))
            Skip = "Requires PULSE_SHIFT_UNFIX_ACCEPTANCE (path to a live acceptance receipt).";
    }
}

/// <summary>
/// Step-3 acceptance for the 2026-10-14 label correction (Tools\ShiftUnfix): once
/// ManualChangeBy/At/Note are cleared, the row is a normal automatic row again and the
/// roster generator in Overwrite mode may take it back - while rows that are still
/// somebody's manual decision (RTM's S60028 row, an absence, a WIC commitment at another
/// centre) stay protected.
///
/// Read-only: only PreviewAsync is called here. The write half of the same acceptance
/// (a real GenerateAsync overwrite of the freed row, with the row restored afterwards)
/// lives in Tools\ShiftUnfix\Test-ShiftUnfixAcceptance.ps1.
/// </summary>
public class LiveShiftUnfixAcceptanceTests
{
    [LiveShiftUnfixFact]
    public async Task FreedRow_IsReplaceableAgain_ManualAndAbsenceRowsStayProtected()
    {
        var path = Environment.GetEnvironmentVariable("PULSE_SHIFT_UNFIX_ACCEPTANCE")!;
        using var receipt = JsonDocument.Parse(await File.ReadAllTextAsync(path));
        var root = receipt.RootElement;

        var connection = root.GetProperty("ConnectionString").GetString()!;
        var builder = new SqlConnectionStringBuilder(connection);
        Assert.True(builder.IntegratedSecurity);
        Assert.Equal("GSDDashboard", builder.InitialCatalog);

        static (int Id, string Emp, string Centre, string LocCode, DateOnly Date) Row(JsonElement e) => (
            e.GetProperty("Id").GetInt32(),
            e.GetProperty("EmployeeId").GetString()!,
            e.GetProperty("Centre").GetString()!,
            e.GetProperty("LocationCode").GetString()!,
            DateOnly.ParseExact(e.GetProperty("Date").GetString()!, "yyyy-MM-dd"));

        var freed  = Row(root.GetProperty("FreedRow"));
        var manual = Row(root.GetProperty("ManualRow"));

        var options = new DbContextOptionsBuilder<GSDContext>().UseSqlServer(connection).Options;
        using var db = new GSDContext(options);

        // ---- the freed row really is an automatic row again, with the trace ------
        var freedRow = await db.ShiftEntries.AsNoTracking().SingleAsync(x => x.Id == freed.Id);
        Assert.Equal(freed.Emp, freedRow.EmployeeId);
        Assert.Null(freedRow.ManualChangeBy);
        Assert.Null(freedRow.ManualChangeAt);
        Assert.Null(freedRow.ManualChangeNote);
        Assert.True(freedRow.AutoGenerated);
        Assert.Equal("SHIFT_FIX 2026-10-14", freedRow.SourceModule);
        Assert.False(freedRow.IsManualChange);

        // ---- the RTM row is still a human decision ------------------------------
        var manualRow = await db.ShiftEntries.AsNoTracking().SingleAsync(x => x.Id == manual.Id);
        Assert.Equal("S60028", manualRow.ManualChangeBy);
        Assert.NotNull(manualRow.ManualChangeAt);
        Assert.True(manualRow.IsManualChange);

        var centre = await db.WicLocations.AsNoTracking().FirstOrDefaultAsync(l => l.LocationCode == freed.LocCode);
        Assert.NotNull(centre);
        var centreManual = await db.WicLocations.AsNoTracking().FirstOrDefaultAsync(l => l.LocationCode == manual.LocCode);
        Assert.NotNull(centreManual);

        var wic = new WicShiftService(db, new AvailabilityResolver(db));
        var roster = new RosterService(db, wic, new WicCoverageGapService(db));

        // =====================================================================
        // 3a) the freed row: generator WITH Overwrite targeting its own centre
        //     -> planned as a REPLACEMENT, not a collision.
        // =====================================================================
        var reqA = new RosterRequest(freed.Emp,
            freed.Date.ToString("yyyy-MM-dd"), freed.Date.ToString("yyyy-MM-dd"),
            "07:00", "15:00", null, "WIC", freed.LocCode, Overwrite: true);
        var previewA = await roster.PreviewAsync(reqA);
        Assert.Contains(previewA.Replacements, r => r.Date == freed.Date.ToString("yyyy-MM-dd"));
        Assert.DoesNotContain(previewA.Collisions, c => c.Date == freed.Date.ToString("yyyy-MM-dd"));
        Assert.True(previewA.ReplaceCount >= 1);

        // =====================================================================
        // 3b) RTM's manual row at its own centre: still refused.
        //     The centre matches, so ONLY the manual marker can protect it.
        // =====================================================================
        var reqB = new RosterRequest(manual.Emp,
            manual.Date.ToString("yyyy-MM-dd"), manual.Date.ToString("yyyy-MM-dd"),
            "07:00", "15:00", null, "WIC", manual.LocCode, Overwrite: true);
        var previewB = await roster.PreviewAsync(reqB);
        Assert.DoesNotContain(previewB.Replacements, r => r.Date == manual.Date.ToString("yyyy-MM-dd"));
        var collisionB = Assert.Single(previewB.Collisions, c => c.Date == manual.Date.ToString("yyyy-MM-dd"));
        Assert.True(collisionB.Protected);
        Assert.Equal(0, previewB.ReplaceCount);

        // =====================================================================
        // 3c) AL/SL stay protected and the WIC commitment at another centre stays
        //     protected. AL/SL were already proven elsewhere in this suite
        //     (RosterOverwriteScopeTests, ManualShiftProtectionTests); the live
        //     database is not assumed to hold an absence for these two employees,
        //     so only the other-centre commitment is exercised against live data.
        // =====================================================================
        var otherCentre = await db.ShiftEntries.AsNoTracking().FirstOrDefaultAsync(x =>
            x.EmployeeId == freed.Emp && x.ShiftType == ShiftTypes.WicDuty &&
            x.ShiftDate != freed.Date && x.AgentTask != null && x.AgentTask != freed.Centre);
        if (otherCentre != null)
        {
            var reqOther = new RosterRequest(freed.Emp,
                otherCentre.ShiftDate.ToString("yyyy-MM-dd"), otherCentre.ShiftDate.ToString("yyyy-MM-dd"),
                "07:00", "15:00", null, "WIC", freed.LocCode, Overwrite: true);
            var previewOther = await roster.PreviewAsync(reqOther);
            Assert.DoesNotContain(previewOther.Replacements, r => r.Date == otherCentre.ShiftDate.ToString("yyyy-MM-dd"));
            Assert.True(Assert.Single(previewOther.Collisions,
                c => c.Date == otherCentre.ShiftDate.ToString("yyyy-MM-dd")).Protected);
        }
        // The absence rule itself, on live data: an AL row in the same period is never
        // a replacement, whatever the employee.
        var anyAl = await db.ShiftEntries.AsNoTracking()
            .Where(x => x.ShiftType == ShiftTypes.AnnualLeave && x.ShiftDate >= freed.Date)
            .OrderBy(x => x.ShiftDate).FirstOrDefaultAsync();
        if (anyAl != null)
        {
            var centreOfAl = await db.WicLocations.AsNoTracking().FirstOrDefaultAsync(l => l.IsActive);
            var reqAl = new RosterRequest(anyAl.EmployeeId,
                anyAl.ShiftDate.ToString("yyyy-MM-dd"), anyAl.ShiftDate.ToString("yyyy-MM-dd"),
                "07:00", "15:00", null, "WIC", centreOfAl!.LocationCode, Overwrite: true);
            var previewAl = await roster.PreviewAsync(reqAl);
            Assert.DoesNotContain(previewAl.Replacements, r => r.Date == anyAl.ShiftDate.ToString("yyyy-MM-dd"));
            Assert.True(Assert.Single(previewAl.Collisions,
                c => c.Date == anyAl.ShiftDate.ToString("yyyy-MM-dd")).Protected);
        }

        // =====================================================================
        // 3d) the human cell-edit path still serves a human (manualActor != null)
        //     and stays refused for an automatic caller (manualActor == null) on
        //     the still-manual row. Read-only: the automatic call is refused before
        //     anything is written.
        // =====================================================================
        var shifts = new ShiftService(db);
        var refused = await shifts.UpdateShiftAsync(manual.Id, new ShiftUpdateDto("SL", null, null, null, null, null));
        Assert.NotNull(refused.Error);
        Assert.Contains("protected", refused.Error!, StringComparison.OrdinalIgnoreCase);

        // The freed row is no longer refused by that guard (it is no longer manual).
        Assert.False(freedRow.IsManualChange);

        db.ChangeTracker.Clear();
        var untouched = await db.ShiftEntries.AsNoTracking().SingleAsync(x => x.Id == manual.Id);
        Assert.Equal(manualRow.ShiftStart, untouched.ShiftStart);
        Assert.Equal(manualRow.ShiftEnd, untouched.ShiftEnd);
        Assert.Equal("S60028", untouched.ManualChangeBy);
    }
}
