using GSDDashboard.API.Data;
using GSDDashboard.API.Data.Models;
using GSDDashboard.API.Modules.Roster;
using GSDDashboard.API.Modules.Shifts;
using GSDDashboard.API.Modules.WicShifts;
using GSDDashboard.API.Services;
using Microsoft.AspNetCore.Http;
using Microsoft.EntityFrameworkCore;
using Xunit;

namespace GSDDashboard.Tests;

// Regression tests for the live bug: "Assign to gap" / "Create Shift" in Pulse WIC
// Shifts returned 409 "Manual shift is protected." even for the human's OWN new
// manual click, because CreateShiftAsync/CreateAssignmentAsync had no way to tell a
// manual UI call apart from an automatic writer. manualActor fixes that: non-null =>
// this call IS the manual decision, so it bypasses PreserveManualShift and self-tags.
public class WicManualUiAlwaysSucceedsTests
{
    private static DateOnly Monday
    {
        get
        {
            var date = DateOnly.FromDateTime(DateTime.Today);
            while (date.DayOfWeek != DayOfWeek.Monday) date = date.AddDays(1);
            return date;
        }
    }

    private static GSDContext NewDb() =>
        new(new DbContextOptionsBuilder<GSDContext>().UseInMemoryDatabase(Guid.NewGuid().ToString()).Options);

    private static ShiftEntry SeedManual(GSDContext db, string employee = "E1", DateOnly? date = null)
    {
        db.Employees.Add(new Employee { EmployeeId = employee, FullName = employee, IsActive = true });
        var row = new ShiftEntry
        {
            EmployeeId = employee, ShiftDate = date ?? Monday, ShiftType = "WORKING",
            ManualChangeBy = "S60028", ManualChangeAt = DateTime.UtcNow.AddHours(-1),
            ManualChangeNote = "Human decision",
        };
        db.ShiftEntries.Add(row);
        return row;
    }

    private static void SeedLocation(GSDContext db) =>
        db.WicLocations.Add(new WicLocation { LocationCode = "LOC", DisplayName = "Halle", IsActive = true });

    private static WicShiftService Svc(GSDContext db) => new(db, new AvailabilityResolver(db));

    // The exact live case: Halle, assign-to-gap onto a day that already carries a
    // (different) manual decision — must now succeed, not 409.
    [Fact]
    public async Task AssignToGap_WithManualActor_SucceedsOnPreviouslyManualCell_AndSelfTags()
    {
        using var db = NewDb();
        var manual = SeedManual(db);
        SeedLocation(db);
        await db.SaveChangesAsync();

        var result = await Svc(db).CreateAssignmentAsync(
            new CreateAssignmentRequest("E1", "LOC", Monday.ToString("yyyy-MM-dd"), null, null),
            db, manualActor: "S60028");

        var value = ((IValueHttpResult)result).Value!;
        Assert.True((bool)value.GetType().GetProperty("success")!.GetValue(value)!);
        Assert.Null(value.GetType().GetProperty("skipped"));
        Assert.Equal("S60028", manual.ManualChangeBy);
        Assert.Equal("WIC_DUTY", manual.ShiftType);
        Assert.False(manual.AutoGenerated);
    }

    // "+ New Shift" / edit-cell path on a previously manual row.
    [Fact]
    public async Task CreateShift_WithManualActor_SucceedsOnPreviouslyManualCell_AndSelfTags()
    {
        using var db = NewDb();
        var manual = SeedManual(db);
        await db.SaveChangesAsync();

        var svc = Svc(db);
        var result = await svc.CreateShiftAsync(
            new CreateShiftRequest("E1", Monday.ToString("yyyy-MM-dd"), "SL", null, null, null, null),
            db, new ShiftValidationService(db), manualActor: "S60028");

        var value = ((IValueHttpResult)result).Value!;
        Assert.True((bool)value.GetType().GetProperty("success")!.GetValue(value)!);
        Assert.Equal("SL", manual.ShiftType);
        Assert.Equal("S60028", manual.ManualChangeBy);
    }

    // Brand-new cell (no prior row) via the manual UI path also succeeds and self-tags.
    [Fact]
    public async Task AssignToGap_WithManualActor_NewCell_SucceedsAndSelfTags()
    {
        using var db = NewDb();
        db.Employees.Add(new Employee { EmployeeId = "E1", FullName = "E1", IsActive = true });
        SeedLocation(db);
        await db.SaveChangesAsync();

        var result = await Svc(db).CreateAssignmentAsync(
            new CreateAssignmentRequest("E1", "LOC", Monday.ToString("yyyy-MM-dd"), null, null),
            db, manualActor: "S60028");

        var value = ((IValueHttpResult)result).Value!;
        Assert.True((bool)value.GetType().GetProperty("success")!.GetValue(value)!);
        var row = await db.ShiftEntries.SingleAsync(s => s.EmployeeId == "E1");
        Assert.Equal("S60028", row.ManualChangeBy);
        Assert.NotNull(row.ManualChangeAt);
    }

    // Automatic writers (manualActor omitted) must still be refused — the whole point
    // of the protection must survive this fix.
    [Fact]
    public async Task AutomaticWriter_WithoutManualActor_IsStillRefused()
    {
        using var db = NewDb();
        var manual = SeedManual(db);
        SeedLocation(db);
        await db.SaveChangesAsync();
        var before = manual.ShiftType;

        var assignResult = await Svc(db).CreateAssignmentAsync(
            new CreateAssignmentRequest("E1", "LOC", Monday.ToString("yyyy-MM-dd"), null, null), db, "Roster", 99);
        var assignValue = ((IValueHttpResult)assignResult).Value!;
        Assert.Equal(false, assignValue.GetType().GetProperty("success")!.GetValue(assignValue));
        Assert.Equal(true, assignValue.GetType().GetProperty("skipped")!.GetValue(assignValue));

        var createResult = await Svc(db).CreateShiftAsync(
            new CreateShiftRequest("E1", Monday.ToString("yyyy-MM-dd"), "SL", null, null, null, null),
            db, new ShiftValidationService(db));
        Assert.Equal(409, ((IStatusCodeHttpResult)createResult).StatusCode);

        Assert.Equal(before, manual.ShiftType);
        Assert.Equal("S60028", manual.ManualChangeBy);
    }

    // RosterService's real internal automatic call path (MAIN/BACKUP walk) must
    // continue to omit manualActor and so remain blocked from a manual cell.
    [Fact]
    public async Task RosterServiceCoverageGeneration_StillCannotOverwriteManualCell()
    {
        using var db = NewDb();
        var manual = SeedManual(db);
        SeedLocation(db);
        db.WicOpeningHours.Add(new WicOpeningHour { LocationCode = "LOC", DayOfWeek = (int)Monday.DayOfWeek,
            IsClosed = false, OpenTime = "08:00", CloseTime = "17:00" });
        db.WicAgentAssignments.Add(new WicAgentAssignment
        { LocationCode = "LOC", EmployeeName = "E1", AssignmentType = "MAIN", IsActive = true });
        await db.SaveChangesAsync();

        var roster = new RosterService(db, Svc(db), new WicCoverageGapService(db));
        var result = await roster.GenerateLocationCoverageAsync("LOC", Monday, Monday, "OPERATOR", "Operator");

        Assert.Empty(result.Assignments);
        Assert.Equal("WORKING", manual.ShiftType);
    }
}
