using GSDDashboard.API.Data;
using GSDDashboard.API.Data.Models;
using GSDDashboard.API.Modules.Roster;
using GSDDashboard.API.Modules.Shifts;
using GSDDashboard.API.Modules.WicShifts;
using GSDDashboard.API.Services;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using Xunit;

namespace GSDDashboard.Tests;

// RTM 2026-10-15 (follow-up) — THE TRACE OF A TEMPORARY MOVE SURVIVES AUTOMATION.
//
// An agent is sent to help at another WIC centre, or to BO/GSD, and then returns to his home
// centre. The centre name in ShiftEntries.AgentTask is that trace. The central hook
// (GSDContext.LinkWicRowsToShiftTypeChanges) may clear it ONLY for a MANUAL RTM edit — the
// Shift Plan cell or the Bulk RTM paste — and only when that edit takes the row from
// WIC_DUTY to WORKING or BO. Everything else keeps it:
//   * an automatic writer (roster generator, sickness/vacation sync, revert, future-vacation
//     reconciliation, rollout, substitute accept, WIC writers, startup) never clears it;
//   * a manual WIC_DUTY -> AL/SL/OFF/... never clears it (a decision about the day, not the
//     centre);
//   * WIC_DUTY centre A -> WIC_DUTY centre B (temporary help) is not a departure from WIC
//     duty at all, so nothing is cleared.
//
// The stand-down of the on-site WicShiftEntries row is unchanged: it still happens for EVERY
// writer (including the automatic ones) and is the only thing automation may do to the row.
public class TemporaryMoveAgentTaskTests
{
    private const string Emp      = "E-MOVE";
    private const string Actor    = "RTM-ACTOR";
    private const string Home     = "Helmstedt";
    private const string HomeCode = "DE~38350~Helmstedt~Schillerstr. 3";
    private const string Other    = "Neu-Isenburg";
    private const string OtherCode = "DE~63263~Neu-Isenburg~Frankfurter Str. 1";

    // 2026-10-19 is a Monday.
    private static readonly DateOnly Mon = new(2026, 10, 19);
    // The two BO weeks and the week the agent comes home.
    private static readonly DateOnly BoFrom = new(2026, 10, 19);
    private static readonly DateOnly BoTo   = new(2026, 10, 30);
    private static readonly DateOnly BackFrom = new(2026, 11, 2);
    private static readonly DateOnly BackTo   = new(2026, 11, 6);
    // The last WIC duty day before the two BO weeks (Friday).
    private static readonly DateOnly PreWicDay = new(2026, 10, 16);

    private static GSDContext NewDb() =>
        new(new DbContextOptionsBuilder<GSDContext>()
            .UseInMemoryDatabase(Guid.NewGuid().ToString())
            .ConfigureWarnings(w => w.Ignore(InMemoryEventId.TransactionIgnoredWarning))
            .Options);

    private static void SeedCentres(GSDContext db)
    {
        db.Employees.Add(new Employee { EmployeeId = Emp, FullName = "Moved Agent", IsActive = true });
        db.WicLocations.Add(new WicLocation { LocationCode = HomeCode, DisplayName = Home, City = Home, Country = "DE", IsActive = true, MinAgentsRequired = 1 });
        db.WicLocations.Add(new WicLocation { LocationCode = OtherCode, DisplayName = Other, City = Other, Country = "DE", IsActive = true, MinAgentsRequired = 1 });
        for (var dow = 1; dow <= 5; dow++)
        {
            db.WicOpeningHours.Add(new WicOpeningHour { LocationCode = HomeCode, DayOfWeek = dow, OpenTime = "08:00", CloseTime = "17:00", IsClosed = false });
            db.WicOpeningHours.Add(new WicOpeningHour { LocationCode = OtherCode, DayOfWeek = dow, OpenTime = "08:00", CloseTime = "17:00", IsClosed = false });
        }
    }

    private static ShiftEntry SeedWicDutyDay(GSDContext db, string centre, DateOnly date, int id = 1)
    {
        var row = new ShiftEntry
        {
            Id = id, EmployeeId = Emp, ShiftDate = date, ShiftType = ShiftTypes.WicDuty,
            IsWicDuty = true, AgentTask = centre, ShiftStart = "08:00", ShiftEnd = "17:00",
            AutoGenerated = true, SourceModule = "Roster",
        };
        db.ShiftEntries.Add(row);
        db.WicShiftEntries.Add(new WicShiftEntry
        {
            EmployeeId = Emp, ShiftDate = date, DayOfWeek = date.DayOfWeek.ToString(),
            SupportLocation = centre, WorkingShift = "08:00-17:00", IsOnSite = true, Task = "WIC",
        });
        return row;
    }

    // ── 1. RTM manual cell: WIC_DUTY -> WORKING / BO clears centre + WIC row ──────────────

    [Fact]
    public async Task RtmShiftPlanCell_WicDutyToWorking_ClearsTheCentreNameAndStandsTheWicRowDown()
    {
        using var db = NewDb();
        SeedCentres(db);
        SeedWicDutyDay(db, Home, Mon);
        await db.SaveChangesAsync();

        var result = await new ShiftService(db).UpdateShiftAsync(
            1, new ShiftUpdateDto(ShiftTypes.Working, "08:00", "17:00", null, null, null), Actor);

        Assert.Null(result.Error);
        var saved = await db.ShiftEntries.SingleAsync(s => s.Id == 1);
        Assert.Equal(ShiftTypes.Working, saved.ShiftType);
        Assert.Null(saved.AgentTask);
        Assert.Equal(Actor, saved.ManualChangeBy);
        Assert.False((await db.WicShiftEntries.SingleAsync()).IsOnSite);
    }

    [Fact]
    public async Task RtmManualEdit_WicDutyToBo_ClearsTheCentreNameAndStandsTheWicRowDown()
    {
        // A BO day in ShiftEntries is ShiftType=WORKING + RawValue="BO" (RosterService).
        using var db = NewDb();
        SeedCentres(db);
        SeedWicDutyDay(db, Home, Mon);
        await db.SaveChangesAsync();

        var row = await db.ShiftEntries.SingleAsync(s => s.Id == 1);
        row.ShiftType = ShiftTypes.Working;
        row.RawValue  = "BO";
        row.IsWicDuty = false;
        db.RecordManualRtmShiftEdit(row, Actor);   // the RTM Shift Plan cell / Bulk RTM paste
        await db.SaveChangesAsync();

        var saved = await db.ShiftEntries.SingleAsync(s => s.Id == 1);
        Assert.Equal("BO", saved.RawValue);
        Assert.Null(saved.AgentTask);
        Assert.False((await db.WicShiftEntries.SingleAsync()).IsOnSite);
    }

    [Fact]
    public async Task RtmManualEdit_WicDutyToOff_KeepsTheCentreName_ButStillStandsTheWicRowDown()
    {
        // Only WORKING / BO may clear. A leave or a day off is a decision about the DAY.
        using var db = NewDb();
        SeedCentres(db);
        SeedWicDutyDay(db, Home, Mon);
        await db.SaveChangesAsync();

        var row = await db.ShiftEntries.SingleAsync(s => s.Id == 1);
        row.ShiftType = ShiftTypes.Off;
        row.IsWicDuty = false;
        db.RecordManualRtmShiftEdit(row, Actor);
        await db.SaveChangesAsync();

        Assert.Equal(Home, (await db.ShiftEntries.SingleAsync(s => s.Id == 1)).AgentTask);
        Assert.False((await db.WicShiftEntries.SingleAsync()).IsOnSite);
    }

    // ── 2. Automatic writers never clear the centre name ─────────────────────────────────

    [Fact]
    public async Task AbsenceSync_WicDutyToSickLeave_KeepsTheCentreName_AndStandsTheWicRowDown()
    {
        using var db = NewDb();
        SeedCentres(db);
        SeedWicDutyDay(db, Home, Mon);
        await db.SaveChangesAsync();

        // Bulk RTM "SL" pastes go to POST /api/sickleave -> ShiftSyncService.SyncSickLeaveAsync,
        // a writer that never touches AgentTask.
        await new ShiftSyncService(db).SyncSickLeaveAsync(Emp, Mon, Mon, sourceId: 7);

        var saved = await db.ShiftEntries.SingleAsync(s => s.Id == 1);
        Assert.Equal(ShiftTypes.SickLeave, saved.ShiftType);
        Assert.Equal(Home, saved.AgentTask);
        Assert.False((await db.WicShiftEntries.SingleAsync()).IsOnSite);
    }

    [Fact]
    public async Task AbsenceSync_WicDutyToAnnualLeave_KeepsTheCentreName_AndStandsTheWicRowDown()
    {
        using var db = NewDb();
        SeedCentres(db);
        SeedWicDutyDay(db, Home, Mon);
        await db.SaveChangesAsync();

        await new ShiftSyncService(db).SyncVacationAsync(Emp, Mon, Mon, sourceId: 9);

        var saved = await db.ShiftEntries.SingleAsync(s => s.Id == 1);
        Assert.Equal(ShiftTypes.AnnualLeave, saved.ShiftType);
        Assert.Equal(Home, saved.AgentTask);
        Assert.False((await db.WicShiftEntries.SingleAsync()).IsOnSite);
    }

    [Fact]
    public async Task AutomaticWriterShapedChange_WicDutyToBo_KeepsTheCentreName()
    {
        // The exact write shape an automatic writer produces for a BO day (ShiftType=WORKING
        // + RawValue="BO", e.g. RosterService.ApplyGenerated) with NO manual RTM declaration:
        // the hook must not clear the trace. Only the WIC row is stood down.
        using var db = NewDb();
        SeedCentres(db);
        SeedWicDutyDay(db, Home, Mon);
        await db.SaveChangesAsync();

        var row = await db.ShiftEntries.SingleAsync(s => s.Id == 1);
        row.ShiftType = ShiftTypes.Working;
        row.RawValue  = "BO";
        row.IsWicDuty = false;
        await db.SaveChangesAsync();               // no RecordManualRtmShiftEdit

        var saved = await db.ShiftEntries.SingleAsync(s => s.Id == 1);
        Assert.Equal(ShiftTypes.Working, saved.ShiftType);
        Assert.Equal("BO", saved.RawValue);
        Assert.Equal(Home, saved.AgentTask);
        Assert.False((await db.WicShiftEntries.SingleAsync()).IsOnSite);
    }

    [Fact]
    public async Task ManualWritersThatAreNotTheRtmCellOrBulkPaste_KeepTheCentreName()
    {
        // Rollout / substitute / WIC writers all register the PLAIN manual marker
        // (GSDContext.RecordManualShiftEdit); only the RTM cell and the Bulk RTM paste
        // declare the type edit, so they must not clear the trace.
        using var db = NewDb();
        SeedCentres(db);
        SeedWicDutyDay(db, Home, Mon);
        await db.SaveChangesAsync();

        var row = await db.ShiftEntries.SingleAsync(s => s.Id == 1);
        row.ShiftType = ShiftTypes.Working;
        row.IsWicDuty = false;
        db.RecordManualShiftEdit(row, Actor);      // as RolloutService / WicShiftService do
        await db.SaveChangesAsync();

        var saved = await db.ShiftEntries.SingleAsync(s => s.Id == 1);
        Assert.Equal(ShiftTypes.Working, saved.ShiftType);
        Assert.Equal(Home, saved.AgentTask);
        Assert.False((await db.WicShiftEntries.SingleAsync()).IsOnSite);
    }

    // ── 3. WIC_DUTY centre A -> centre B -> centre A (temporary help) ────────────────────

    [Fact]
    public async Task TemporaryMove_CentreAToBAndBack_KeepsTheCentreNameAndNeverClearsAnything()
    {
        using var db = NewDb();
        SeedCentres(db);
        SeedWicDutyDay(db, Home, Mon);
        await db.SaveChangesAsync();

        var svc = new WicShiftService(db, new AvailabilityResolver(db));

        // A -> B (temporary help at another centre).
        await svc.CreateAssignmentAsync(
            new CreateAssignmentRequest(Emp, OtherCode, Mon.ToString("yyyy-MM-dd"), null, null),
            db, manualActor: Actor);

        var atB = await db.ShiftEntries.SingleAsync(s => s.Id == 1);
        Assert.Equal(ShiftTypes.WicDuty, atB.ShiftType);   // never left WIC duty
        Assert.Equal(Other, atB.AgentTask);
        Assert.True((await db.WicShiftEntries.SingleAsync(w => w.SupportLocation == Other)).IsOnSite);

        // B -> A (back to the home centre).
        await svc.CreateAssignmentAsync(
            new CreateAssignmentRequest(Emp, HomeCode, Mon.ToString("yyyy-MM-dd"), null, null),
            db, manualActor: Actor);

        var atA = await db.ShiftEntries.SingleAsync(s => s.Id == 1);
        Assert.Equal(ShiftTypes.WicDuty, atA.ShiftType);
        Assert.Equal(Home, atA.AgentTask);
        Assert.True((await db.WicShiftEntries.SingleAsync(w => w.SupportLocation == Home)).IsOnSite);
    }

    // ── 4. WIC -> BO for two weeks, then the automatic return to the home centre ─────────

    private static RosterService RosterSvc(GSDContext db) =>
        new(db, new WicShiftService(db, new AvailabilityResolver(db)), new WicCoverageGapService(db));

    [Fact]
    public async Task WicDutyToBoForTwoWeeks_ThenAutomaticReturnToTheHomeCentre()
    {
        using var db = NewDb();
        SeedCentres(db);
        // The home centre is the agent's permanent MAIN. Its recurring weekday pattern is
        // CLOSED for the two BO weeks (a closed exception day wins over the pattern); the
        // return week is opened by manual exception days, exactly the mechanism
        // WicHoursResolver prefers.
        db.WicAgentAssignments.Add(new WicAgentAssignment
        { LocationCode = HomeCode, EmployeeName = "Moved Agent", AssignmentType = "MAIN", IsActive = true });
        for (var d = BoFrom; d <= BoTo; d = d.AddDays(1))
        {
            if (d.DayOfWeek is DayOfWeek.Saturday or DayOfWeek.Sunday) continue;
            db.WicOpeningHours.Add(new WicOpeningHour
            { LocationCode = HomeCode, DayOfWeek = (int)d.DayOfWeek, ExceptionDate = d, IsClosed = true });
        }
        for (var d = BackFrom; d <= BackTo; d = d.AddDays(1))
        {
            if (d.DayOfWeek is DayOfWeek.Saturday or DayOfWeek.Sunday) continue;
            db.WicOpeningHours.Add(new WicOpeningHour
            { LocationCode = HomeCode, DayOfWeek = (int)d.DayOfWeek, ExceptionDate = d, OpenTime = "08:00", CloseTime = "17:00", IsClosed = false });
        }
        // Before the period the agent really is on WIC duty at the home centre; that day must
        // survive the whole cycle untouched.
        SeedWicDutyDay(db, Home, PreWicDay);
        await db.SaveChangesAsync();

        // ── two weeks of BO (the centre is closed): an AUTOMATIC writer ───────────────────
        var bo = await RosterSvc(db).GenerateAsync(
            new RosterRequest(Emp, BoFrom.ToString("yyyy-MM-dd"), BoTo.ToString("yyyy-MM-dd"), "08:00", "17:00", null, null),
            "K1", "Tester");

        Assert.Equal(0, bo.WicDays);
        Assert.Equal(10, bo.BoDays);                     // 19.-23. and 26.-30.10.2026
        Assert.False(bo.AssignmentCreated);              // the permanent MAIN is never re-created
        var boRows = await db.ShiftEntries
            .Where(s => s.EmployeeId == Emp && s.ShiftDate >= BoFrom && s.ShiftDate <= BoTo)
            .OrderBy(s => s.ShiftDate).ToListAsync();
        Assert.Equal(10, boRows.Count);
        Assert.All(boRows, r =>
        {
            Assert.Equal(ShiftTypes.Working, r.ShiftType);
            Assert.Equal("BO", r.RawValue);
        });
        // No on-site WIC row on any BO day — the stand-down half of the rule.
        Assert.Empty(await db.WicShiftEntries
            .Where(w => w.EmployeeId == Emp && w.ShiftDate >= BoFrom && w.ShiftDate <= BoTo && w.IsOnSite)
            .ToListAsync());
        // The pre-period WIC day is untouched: nothing the generator did erased it.
        var pre = await db.ShiftEntries.SingleAsync(s => s.ShiftDate == PreWicDay);
        Assert.Equal(ShiftTypes.WicDuty, pre.ShiftType);
        Assert.Equal(Home, pre.AgentTask);
        Assert.True((await db.WicShiftEntries.SingleAsync(w => w.ShiftDate == PreWicDay)).IsOnSite);

        // ── the automatic return to the home centre ──────────────────────────────────────
        var back = await RosterSvc(db).GenerateAsync(
            new RosterRequest(Emp, BackFrom.ToString("yyyy-MM-dd"), BackTo.ToString("yyyy-MM-dd"), "08:00", "17:00", null, null),
            "K1", "Tester");

        Assert.Equal(5, back.WicDays);
        Assert.Equal(0, back.BoDays);
        Assert.False(back.AssignmentCreated);            // the permanent MAIN is never re-created
        Assert.Single(await db.WicAgentAssignments.ToListAsync());
        for (var d = BackFrom; d <= BackTo; d = d.AddDays(1))
        {
            if (d.DayOfWeek is DayOfWeek.Saturday or DayOfWeek.Sunday) continue;
            var shift = await db.ShiftEntries.SingleAsync(s => s.EmployeeId == Emp && s.ShiftDate == d);
            Assert.Equal(ShiftTypes.WicDuty, shift.ShiftType);
            Assert.Equal(Home, shift.AgentTask);
            var wic = await db.WicShiftEntries.SingleAsync(w => w.EmployeeId == Emp && w.ShiftDate == d);
            Assert.Equal(Home, wic.SupportLocation);
            Assert.True(wic.IsOnSite);
        }
    }
}
