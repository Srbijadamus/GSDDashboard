using GSDDashboard.API.Data;
using GSDDashboard.API.Data.Models;
using GSDDashboard.API.Modules.Shifts;
using GSDDashboard.API.Modules.WicShifts;
using GSDDashboard.API.Services;
using Microsoft.AspNetCore.Http;
using Microsoft.EntityFrameworkCore;
using Xunit;

namespace GSDDashboard.Tests;

// The live 2026-10-12 S60028 report: "Assign Agent to Location" for Münster on a day
// that already carried an Essen - BP1 commitment returned SUCCESS three times, while
// nothing was saved and the Overview stayed a gap. These tests pin the corrected
// contract:
//   * a manual assignment replaces an AUTOMATIC overlapping commitment in the same write;
//   * an overlapping HUMAN commitment is never replaced silently: the response asks for
//     confirmation and names who set it and when; a confirmed re-send replaces it;
//   * a closed centre is reported, never "success";
//   * the per-day answer always says whether something was actually saved.
public class WicAssignOutcomeTests
{
    private static readonly DateOnly Monday = new(2026, 10, 12); // Monday

    private static GSDContext NewDb() =>
        new(new DbContextOptionsBuilder<GSDContext>().UseInMemoryDatabase(Guid.NewGuid().ToString()).Options);

    private static WicShiftService Svc(GSDContext db) => new(db, new AvailabilityResolver(db));

    private static object Value(IResult r) => ((IValueHttpResult)r).Value!;
    private static bool Bool(object v, string p) => (bool)(v.GetType().GetProperty(p)?.GetValue(v) ?? false);
    private static string? Str(object v, string p) => (string?)v.GetType().GetProperty(p)?.GetValue(v);
    private static bool Has(object v, string p) => v.GetType().GetProperty(p) != null;

    private static void SeedEmployeeAndCentres(GSDContext db, string emp)
    {
        db.Employees.Add(new Employee { EmployeeId = emp, FullName = "Agent " + emp, IsActive = true });
        db.WicLocations.Add(new WicLocation { LocationCode = "A", DisplayName = "Centre A", IsActive = true });
        db.WicLocations.Add(new WicLocation { LocationCode = "B", DisplayName = "Centre B", IsActive = true });
        // Centre A open Monday 09:00-16:30; Centre B is added per test.
        db.WicOpeningHours.Add(new WicOpeningHour
        { LocationCode = "A", DayOfWeek = 1, OpenTime = "09:00", CloseTime = "16:30", IsClosed = false });
    }

    private static void SeedCentreBOpen(GSDContext db, int dayOfWeek = 1, bool closed = false) =>
        db.WicOpeningHours.Add(new WicOpeningHour
        {
            LocationCode = "B",
            DayOfWeek = dayOfWeek,
            OpenTime = closed ? null : "08:00",
            CloseTime = closed ? null : "17:00",
            IsClosed = closed,
        });

    // The pre-existing commitment at Centre A on Monday, automatic or human.
    private static void SeedExistingA(GSDContext db, string emp, bool human)
    {
        db.ShiftEntries.Add(new ShiftEntry
        {
            EmployeeId = emp,
            ShiftDate = Monday,
            ShiftType = ShiftTypes.WicDuty,
            IsWicDuty = true,
            AgentTask = "Centre A",
            ShiftStart = "09:00",
            ShiftEnd = "16:30",
            AutoGenerated = !human,
            ManualChangeBy = human ? "S60028" : null,
            ManualChangeAt = human ? DateTime.UtcNow.AddHours(-2) : null,
            ManualChangeNote = human ? "Human decision" : null,
        });
        db.WicShiftEntries.Add(new WicShiftEntry
        {
            EmployeeId = emp,
            ShiftDate = Monday,
            SupportLocation = "Centre A",
            LocationCode = "A",
            WorkingShift = "09:00-16:30",
            IsOnSite = true,
            Task = "WIC",
        });
    }

    private static CreateAssignmentRequest ReqB(string emp, bool confirm = false) =>
        new(emp, "B", Monday.ToString("yyyy-MM-dd"), "08:00", "17:00", confirm);

    // ── 1. Overlap with an AUTOMATIC commitment: replaced in the same write ──────
    [Fact]
    public async Task Overlap_WithAutomaticCommitment_IsReplaced_AndReportedAsSaved()
    {
        using var db = NewDb();
        SeedEmployeeAndCentres(db, "E1");
        SeedCentreBOpen(db);
        SeedExistingA(db, "E1", human: false);
        await db.SaveChangesAsync();

        var result = await Svc(db).CreateAssignmentAsync(ReqB("E1"), db, manualActor: "S60028");
        var v = Value(result);

        Assert.True(Bool(v, "saved"));
        Assert.True(Bool(v, "replacedAutomatic"));
        Assert.Equal("REPLACED_AUTOMATIC", Str(v, "reasonCode"));
        Assert.False(Has(v, "skipped"));

        var wicRows = db.WicShiftEntries.Where(w => w.EmployeeId == "E1" && w.ShiftDate == Monday).ToList();
        var only = Assert.Single(wicRows);
        Assert.Equal("Centre B", only.SupportLocation);
        Assert.True(only.IsOnSite);

        var shift = db.ShiftEntries.Single(s => s.EmployeeId == "E1" && s.ShiftDate == Monday);
        Assert.Equal("Centre B", shift.AgentTask);
        Assert.Equal(ShiftTypes.WicDuty, shift.ShiftType);
        Assert.Equal("S60028", shift.ManualChangeBy);   // the replacement is now the human's row
    }

    // ── 2. Overlap with a HUMAN commitment: confirmation, then replacement ───────
    // Requirement 5: a human-owned day row is only protected when the conflicting
    // centre ALSO carries an ACTIVE WicAgentAssignments row for this employee. The
    // seed therefore carries the permanent Centre A assignment (name+location match).
    [Fact]
    public async Task Overlap_WithManualCommitment_RequiresConfirmation_ThenReplaces()
    {
        using var db = NewDb();
        SeedEmployeeAndCentres(db, "E2");
        SeedCentreBOpen(db);
        SeedExistingA(db, "E2", human: true);
        db.WicAgentAssignments.Add(new WicAgentAssignment
        { LocationCode = "A", EmployeeName = "Agent E2", AssignmentType = "MAIN", IsActive = true });
        await db.SaveChangesAsync();

        var first = await Svc(db).CreateAssignmentAsync(ReqB("E2"), db, manualActor: "S60028");
        var v1 = Value(first);

        Assert.False(Bool(v1, "saved"));
        Assert.True(Bool(v1, "requiresConfirmation"));
        Assert.Equal("MANUAL_CONFLICT", Str(v1, "reasonCode"));
        Assert.NotNull(v1.GetType().GetProperty("conflicts")!.GetValue(v1));
        // The conflict carries who set it and when, so the UI can name them.
        var conflict = ((System.Collections.IEnumerable)v1.GetType().GetProperty("conflicts")!.GetValue(v1)!)
            .Cast<object>().Single();
        Assert.Equal("Centre A", (string?)conflict.GetType().GetProperty("location")!.GetValue(conflict));
        Assert.Equal("S60028", (string?)conflict.GetType().GetProperty("actor")!.GetValue(conflict));
        Assert.NotNull(conflict.GetType().GetProperty("atBerlin")!.GetValue(conflict));

        // Nothing was written by the first call.
        Assert.True(db.WicShiftEntries.Single(w => w.SupportLocation == "Centre A").IsOnSite);
        Assert.DoesNotContain(db.WicShiftEntries, w => w.SupportLocation == "Centre B");

        var second = await Svc(db).CreateAssignmentAsync(ReqB("E2", confirm: true), db, manualActor: "S60028");
        Assert.True(Bool(Value(second), "saved"));

        var only = Assert.Single(db.WicShiftEntries.Where(w => w.EmployeeId == "E2" && w.ShiftDate == Monday));
        Assert.Equal("Centre B", only.SupportLocation);
        Assert.True(only.IsOnSite);
    }

    // ── 3. Closed centre: exact reason, nothing saved ────────────────────────────
    [Fact]
    public async Task ClosedCentre_SavesNothing_AndReportsClosed()
    {
        using var db = NewDb();
        SeedEmployeeAndCentres(db, "E3");
        SeedCentreBOpen(db, dayOfWeek: 1, closed: true);
        await db.SaveChangesAsync();

        var result = await Svc(db).CreateAssignmentAsync(ReqB("E3"), db, manualActor: "S60028");
        var v = Value(result);

        Assert.False(Bool(v, "saved"));
        Assert.True(Bool(v, "skipped"));
        Assert.Equal("CLOSED", Str(v, "reasonCode"));
        Assert.Contains("closed", Str(v, "reason"), StringComparison.OrdinalIgnoreCase);
        Assert.Empty(db.WicShiftEntries);
        Assert.Empty(db.ShiftEntries);
    }

    // ── 4. Plain success: saved, no skip flag ────────────────────────────────────
    [Fact]
    public async Task SuccessfulAssignment_IsSaved_AndNotASkip()
    {
        using var db = NewDb();
        SeedEmployeeAndCentres(db, "E4");
        SeedCentreBOpen(db);
        await db.SaveChangesAsync();

        var result = await Svc(db).CreateAssignmentAsync(ReqB("E4"), db, manualActor: "S60028");
        var v = Value(result);

        Assert.True(Bool(v, "saved"));
        Assert.Equal("SAVED", Str(v, "reasonCode"));
        Assert.False(Has(v, "skipped"));
        Assert.Equal("Centre B", Assert.Single(db.WicShiftEntries).SupportLocation);
    }

    // ── 5. Partial across the range: one saved, one closed (per-day answers) ─────
    [Fact]
    public async Task Range_PartialSave_ReportsEachDaySeparately()
    {
        using var db = NewDb();
        SeedEmployeeAndCentres(db, "E5");
        SeedCentreBOpen(db, dayOfWeek: 1, closed: false); // Monday open
        SeedCentreBOpen(db, dayOfWeek: 2, closed: true);  // Tuesday closed
        await db.SaveChangesAsync();

        var monday = await Svc(db).CreateAssignmentAsync(ReqB("E5"), db, manualActor: "S60028");
        var tuesday = await Svc(db).CreateAssignmentAsync(
            new CreateAssignmentRequest("E5", "B", "2026-10-13", "08:00", "17:00"), db, manualActor: "S60028");

        Assert.True(Bool(Value(monday), "saved"));
        Assert.False(Bool(Value(tuesday), "saved"));
        Assert.True(Bool(Value(tuesday), "skipped"));
        Assert.Equal("CLOSED", Str(Value(tuesday), "reasonCode"));
        // Exactly the Monday row exists; the rejected Tuesday wrote nothing.
        Assert.Single(db.WicShiftEntries);
    }

    // ── 6. An automatic writer still never replaces or deletes anything ──────────
    [Fact]
    public async Task AutomaticWriter_OnOverlap_StillSkipsAndChangesNothing()
    {
        using var db = NewDb();
        SeedEmployeeAndCentres(db, "E6");
        SeedCentreBOpen(db);
        SeedExistingA(db, "E6", human: false);
        await db.SaveChangesAsync();

        var result = await Svc(db).CreateAssignmentAsync(ReqB("E6"), db, "Roster", 42); // manualActor null
        var v = Value(result);

        Assert.True(Bool(v, "skipped"));
        Assert.False(Bool(v, "saved"));
        Assert.Equal("TIME_CONFLICT", Str(v, "reasonCode"));
        Assert.Contains("Time conflict", Str(v, "reason"));
        var only = Assert.Single(db.WicShiftEntries);
        Assert.Equal("Centre A", only.SupportLocation);
        Assert.True(only.IsOnSite);
    }

    // ── 7. Shift Plan edit is visible on the Overview (coverage-gap seam) ────────
    [Fact]
    public async Task ShiftPlan_WicDutyEdit_CreatesWicRow_AndClosesTheCoverageGap()
    {
        using var db = NewDb();
        var date = DateOnly.FromDateTime(DateTime.Today);
        while (date.DayOfWeek != DayOfWeek.Monday) date = date.AddDays(1);

        db.Employees.Add(new Employee { EmployeeId = "E7", FullName = "Agent E7", IsActive = true });
        db.WicLocations.Add(new WicLocation { LocationCode = "A", DisplayName = "Centre A", IsActive = true });
        db.WicOpeningHours.Add(new WicOpeningHour
        { LocationCode = "A", DayOfWeek = (int)DayOfWeek.Monday, OpenTime = "08:00", CloseTime = "17:00", IsClosed = false });
        db.WicAgentAssignments.Add(new WicAgentAssignment
        { LocationCode = "A", EmployeeName = "Agent E7", AssignmentType = "MAIN", IsActive = true });
        var row = new ShiftEntry
        {
            EmployeeId = "E7", ShiftDate = date, ShiftType = ShiftTypes.Working,
            ShiftStart = "08:00", ShiftEnd = "17:00",
        };
        db.ShiftEntries.Add(row);
        await db.SaveChangesAsync();

        var gaps = new WicCoverageGapService(db);
        Assert.Equal(1, await gaps.GetStillGapCountAsync("A", date, date));

        var shiftSvc = new ShiftService(db);
        var result = await shiftSvc.UpdateShiftAsync(
            row.Id,
            new ShiftUpdateDto(ShiftTypes.WicDuty, "08:00", "17:00", null, null, null),
            manualActor: "S60028");

        Assert.Null(result.Warning);
        var wic = Assert.Single(db.WicShiftEntries.Where(w => w.EmployeeId == "E7" && w.ShiftDate == date));
        Assert.True(wic.IsOnSite);
        Assert.Equal("Centre A", wic.SupportLocation);
        // The exact seam the Overview banner reads.
        Assert.Equal(0, await gaps.GetStillGapCountAsync("A", date, date));
    }
}
